def opposite(action: str) -> str:
    return "SELL" if action.upper() == "BUY" else "BUY"


def submit_in_chunks(
    client: RITClient,
    ticker: str,
    action: str,
    quantity: int,
    *,
    reference_price: Optional[float] = None,
    execution_id: str = "",
    result_collector: Optional[List[OrderResult]] = None,
) -> int:
    maximum = (
        MAX_FX_ORDER_SIZE
        if ticker in (CAD, USD)
        else MAX_EQUITY_ORDER_SIZE
    )

    left = int(quantity)
    total_filled = 0

    while left > 0:
        requested = min(left, maximum)

        result = client.market_order(
            ticker=ticker,
            action=action,
            quantity=requested,
            reference_price=reference_price,
            execution_id=execution_id,
        )

        if result_collector is not None:
            result_collector.append(result)

        total_filled += result.filled
        left -= requested

        if result.filled < requested:
            break

    return total_filled


def execute_matched_legs(
    client: RITClient,
    state: MarketState,
    legs: Sequence[Tuple[str, str, int]],
    *,
    reference_prices: Optional[Dict[str, float]] = None,
    execution_id: str = "",
    result_collector: Optional[List[OrderResult]] = None,
) -> int:
    if not legs:
        return 0

    target = min(quantity for _, _, quantity in legs)

    normalized_legs = [
        (ticker, action, target)
        for ticker, action, _ in legs
    ]

    # RITC is the cross-currency price anchor and showed the largest adverse
    # drift in live testing. Execute it first, then rank the remaining legs by
    # visible depth to retain the mismatch-risk protection for BULL and BEAR.
    ritc_legs = [leg for leg in normalized_legs if leg[0] == RITC]
    other_legs = sorted(
        [leg for leg in normalized_legs if leg[0] != RITC],
        key=lambda leg: state.books[leg[0]].available(leg[1]),
    )
    ranked_legs = ritc_legs + other_legs

    completed: List[List[Any]] = []

    for ticker, action, _ in ranked_legs:
        filled = submit_in_chunks(
            client,
            ticker,
            action,
            target,
            reference_price=(reference_prices or {}).get(ticker),
            execution_id=execution_id,
            result_collector=result_collector,
        )

        if filled < target:
            logging.error(
                "LEG MISMATCH: %s filled %d/%d. "
                "Rolling earlier legs back to %d.",
                ticker,
                filled,
                target,
                filled,
            )

            client.audit.action(
                state=state,
                event="LEG_MISMATCH",
                module="EXECUTION",
                ticker=ticker,
                action=action,
                requested_quantity=target,
                filled_quantity=filled,
                status="ROLLBACK_STARTED",
            )

            for earlier in completed:
                excess = int(earlier[2]) - filled

                if excess <= 0:
                    continue

                rolled = submit_in_chunks(
                    client,
                    str(earlier[0]),
                    opposite(str(earlier[1])),
                    excess,
                    execution_id=execution_id,
                    result_collector=result_collector,
                )

                earlier[2] -= rolled

                if rolled < excess:
                    logging.critical(
                        "UNRESOLVED LEG RISK: rolled %d/%d %s",
                        rolled,
                        excess,
                        earlier[0],
                    )

                    client.audit.action(
                        state=state,
                        event="UNRESOLVED_LEG_RISK",
                        module="EXECUTION",
                        ticker=str(earlier[0]),
                        requested_quantity=excess,
                        filled_quantity=rolled,
                        status="CRITICAL",
                    )

            target = filled

        completed.append([ticker, action, filled])

        if target <= 0:
            break

    return max(0, target)


def execute_direct_legs_concurrently(
    client: RITClient,
    state: MarketState,
    legs: Sequence[Tuple[str, str, int]],
    *,
    reference_prices: Dict[str, float],
    execution_id: str,
    result_collector: List[OrderResult],
) -> int:
    """Submit the three neutral direct-arbitrage equity legs together."""
    if not legs:
        return 0
    target = min(int(quantity) for _, _, quantity in legs)
    normalized = [(ticker, action.upper(), target) for ticker, action, _ in legs]
    if target <= 0 or target > MAX_EQUITY_ORDER_SIZE:
        raise ValueError("Concurrent direct quantity is outside order limits")
    if len({ticker for ticker, _, _ in normalized}) != len(normalized):
        raise ValueError("Concurrent direct legs must have distinct tickers")

    client.audit.orders_requested += target * len(normalized)
    results: List[OrderResult] = []
    errors: List[str] = []
    with ThreadPoolExecutor(
        max_workers=len(normalized),
        thread_name_prefix="ritcx-direct-order",
    ) as executor:
        futures = {
            executor.submit(
                client._fast_market_order,
                ticker,
                action,
                target,
                reference_prices.get(ticker),
            ): (ticker, action)
            for ticker, action, _ in normalized
        }
        for future in as_completed(futures):
            ticker, action = futures[future]
            try:
                results.append(future.result())
            except Exception as exc:  # retain other leg results for rollback
                errors.append(f"{ticker} {action}: {exc}")

    for result in results:
        client.audit.orders_filled += result.filled
        result_collector.append(result)
        client.audit.action(
            state=state,
            event="ORDER",
            module="EXECUTION",
            ticker=result.ticker,
            action=result.action,
            requested_quantity=result.requested,
            filled_quantity=result.filled,
            price=(result.reference_price if result.reference_price is not None else ""),
            vwap=(result.vwap if result.vwap is not None else ""),
            status=result.status,
            details={
                "order_id": result.order_id,
                "execution_id": execution_id,
                "concurrent_direct_leg": True,
            },
        )
        logging.info(
            "ORDER (concurrent): %s %d %s -> filled %d, vwap=%s, status=%s",
            result.action,
            result.requested,
            result.ticker,
            result.filled,
            result.vwap,
            result.status,
        )

    matched = 0 if errors else min(
        (result.filled for result in results),
        default=0,
    )
    by_ticker = {result.ticker: result for result in results}
    for ticker, action, _ in normalized:
        result = by_ticker.get(ticker)
        excess = (result.filled if result is not None else 0) - matched
        if excess <= 0:
            continue
        logging.error(
            "CONCURRENT LEG MISMATCH: rolling back %d excess %s shares",
            excess,
            ticker,
        )
        submit_in_chunks(
            client,
            ticker,
            opposite(action),
            excess,
            execution_id=execution_id,
            result_collector=result_collector,
        )

    if errors:
        client.audit.action(
            state=state,
            event="CONCURRENT_DIRECT_ORDER_ERROR",
            module="DIRECT_ARB",
            status="ROLLED_BACK_KNOWN_FILLS",
            message="; ".join(errors),
            details={"execution_id": execution_id},
        )
        raise ApiException("Concurrent direct order failure: " + "; ".join(errors))
    return matched


def protected_ritc_limit_price(
    candidate: Candidate,
) -> Tuple[float, float]:
    """Return (limit price, protected post-hedge edge) for the RITC lead.

    The calculation uses the candidate's synchronized BULL, BEAR, and USD
    reference VWAPs. A one-cent basket reserve is held back from the permitted
    adverse drift, and the limit-order rebate is included conservatively.
    """
    bull = float(candidate.reference_prices[BULL])
    bear = float(candidate.reference_prices[BEAR])
    fx = float(candidate.reference_prices[USD])
    if not all(math.isfinite(value) and value > 0 for value in (bull, bear, fx)):
        raise ValueError("Direct reference prices are incomplete")

    protected_edge = max(
        DIRECT_MIN_REALIZED_EDGE_CAD,
        candidate.average_edge_cad - MAX_ADVERSE_EDGE_DRIFT_CAD,
    )
    lead_bound_edge = (
        protected_edge + DIRECT_BASKET_SLIPPAGE_RESERVE_CAD
    )

    if candidate.direction == "ETF_CHEAP":
        # actual edge = BULL-fee + BEAR-fee - (RITC-rebate)*FX
        raw_price = (
            bull
            + bear
            - 2.0 * EQUITY_MARKET_FEE_PER_SHARE
            - lead_bound_edge
        ) / fx + EQUITY_LIMIT_REBATE_PER_SHARE
        # Never round a BUY protection price upward.
        limit_price = math.floor(raw_price * 100.0 + 1e-9) / 100.0
    elif candidate.direction == "ETF_RICH":
        # actual edge = (RITC+rebate)*FX - BULL-fee - BEAR-fee
        raw_price = (
            lead_bound_edge
            + bull
            + bear
            + 2.0 * EQUITY_MARKET_FEE_PER_SHARE
        ) / fx - EQUITY_LIMIT_REBATE_PER_SHARE
        # Never round a SELL protection price downward.
        limit_price = math.ceil(raw_price * 100.0 - 1e-9) / 100.0
    else:
        raise ValueError(f"Unknown direct direction: {candidate.direction}")

    if not math.isfinite(limit_price) or limit_price <= 0:
        raise ValueError("Calculated RITC protection price is invalid")
    return limit_price, protected_edge


def infer_limit_fill_from_position(
    client: RITClient,
    *,
    ticker: str,
    action: str,
    position_before: int,
    requested: int,
) -> int:
    """Infer a raced terminal fill when the DMA order row disappeared.

    The strategy submits and resolves each protected lead synchronously, so no
    other module can alter the same ticker during this short reconciliation
    window. The inference is therefore a safe fallback for the DMA behavior
    where a just-filled order can return 404 to both DELETE and the final GET.
    """
    try:
        position_after = int(client.positions().get(ticker, position_before))
    except (requests.RequestException, ApiException) as exc:
        logging.error(
            "LIMIT FILL RECONCILIATION FAILED for %s: %s",
            ticker,
            exc,
        )
        return 0

    signed_change = position_after - int(position_before)
    inferred = signed_change if action.upper() == "BUY" else -signed_change
    return max(0, min(int(requested), int(inferred)))


def finish_short_lived_limit_order(
    client: RITClient,
    state: MarketState,
    initial: OrderResult,
    *,
    execution_id: str,
) -> OrderResult:
    """Observe a short-lived marketable limit, cancel, and freeze its fill."""
    terminal_statuses = {"CANCELLED", "TRANSACTED", "REJECTED"}
    latest = initial
    deadline = time.monotonic() + DIRECT_MARKETABLE_LIMIT_TTL_SECONDS

    while (
        latest.order_id is not None
        and latest.status.upper() not in terminal_statuses
        and time.monotonic() < deadline
    ):
        remaining = deadline - time.monotonic()
        if remaining > 0:
            time.sleep(min(DIRECT_LIMIT_POLL_INTERVAL_SECONDS, remaining))
        row = client.get_order_optional(latest.order_id)
        if row is None:
            break
        latest = client.order_result_from_payload(
            initial.ticker,
            initial.action,
            initial.requested,
            row,
            reference_price=initial.reference_price,
        )
        latest.order_type = "LIMIT"
        latest.limit_price = initial.limit_price

    if (
        latest.order_id is not None
        and latest.status.upper() not in terminal_statuses
    ):
        cancel_payload = client.cancel_order(latest.order_id)
        cancel_raced_terminal = bool(
            isinstance(cancel_payload, dict)
            and cancel_payload.get("_http_status") == 404
        )
        # A raced 404 usually means the order filled after the last GET. Give
        # the order endpoint one short opportunity to expose the terminal row.
        if cancel_raced_terminal:
            time.sleep(DIRECT_LIMIT_POLL_INTERVAL_SECONDS)
        row = client.get_order_optional(latest.order_id)
        if row is not None:
            latest = client.order_result_from_payload(
                initial.ticker,
                initial.action,
                initial.requested,
                row,
                reference_price=initial.reference_price,
            )
            latest.order_type = "LIMIT"
            latest.limit_price = initial.limit_price
        elif not cancel_raced_terminal:
            latest.status = "CANCELLED"

        if row is None:
            inferred_fill = infer_limit_fill_from_position(
                client,
                ticker=initial.ticker,
                action=initial.action,
                position_before=int(state.positions.get(initial.ticker, 0)),
                requested=initial.requested,
            )
            if inferred_fill > latest.filled:
                latest = OrderResult(
                    ticker=initial.ticker,
                    action=initial.action,
                    requested=initial.requested,
                    filled=inferred_fill,
                    # A marketable limit executes at its limit or better. Use
                    # the limit as a conservative VWAP when the terminal row
                    # vanished before it could report the actual VWAP.
                    vwap=initial.limit_price,
                    status="TERMINAL_FILL_INFERRED",
                    order_id=initial.order_id,
                    reference_price=initial.reference_price,
                    order_type="LIMIT",
                    limit_price=initial.limit_price,
                )
                logging.warning(
                    "DIRECT LIMIT RACE: inferred %d-share %s fill from "
                    "the RITC position change",
                    inferred_fill,
                    initial.action,
                )

    # Preserve a larger fill already reported by POST if a terminal GET is
    # briefly stale. The corresponding VWAP is kept with that larger fill.
    if initial.filled > latest.filled:
        latest = initial
    latest.order_type = "LIMIT"
    latest.limit_price = initial.limit_price
    client.audit.orders_filled += latest.filled
    client.audit.action(
        state=state,
        event="DIRECT_PROTECTED_LEAD_FINAL",
        module="DIRECT_ARB",
        ticker=latest.ticker,
        action=latest.action,
        requested_quantity=latest.requested,
        filled_quantity=latest.filled,
        price=(
            latest.limit_price
            if latest.limit_price is not None
            else ""
        ),
        vwap=latest.vwap if latest.vwap is not None else "",
        status=latest.status,
        details={
            "order_id": latest.order_id,
            "execution_id": execution_id,
            "ttl_seconds": DIRECT_MARKETABLE_LIMIT_TTL_SECONDS,
        },
    )
    return latest


def execute_protected_direct_child(
    client: RITClient,
    state: MarketState,
    candidate: Candidate,
    *,
    execution_id: str,
    result_collector: List[OrderResult],
) -> int:
    """Fill protected RITC first, then immediately hedge its actual fill."""
    ritc_leg = next(
        (leg for leg in candidate.legs if leg[0] == RITC),
        None,
    )
    if ritc_leg is None:
        raise ValueError("Direct candidate is missing its RITC leg")
    _, ritc_action, requested = ritc_leg
    limit_price, protected_edge = protected_ritc_limit_price(candidate)
    execution_child_id = f"{execution_id}-child-{time.monotonic_ns()}"

    client.audit.action(
        state=state,
        event="DIRECT_PROTECTED_CHILD_PREFLIGHT",
        module="DIRECT_ARB",
        label=candidate.label,
        ticker=RITC,
        action=ritc_action,
        requested_quantity=requested,
        price=limit_price,
        average_edge_cad=candidate.average_edge_cad,
        expected_pnl_cad=candidate.total_pnl_cad,
        status="PRICE_PROTECTED",
        details={
            "execution_id": execution_child_id,
            "protected_edge_cad": protected_edge,
            "basket_slippage_reserve_cad": (
                DIRECT_BASKET_SLIPPAGE_RESERVE_CAD
            ),
            "reference_prices": candidate.reference_prices,
        },
    )
    logging.warning(
        "DIRECT CHILD: %s %d RITC limit %.2f | q<=%d | "
        "signal edge %.4f | protected edge %.4f",
        ritc_action,
        requested,
        limit_price,
        DIRECT_PROTECTED_CHILD_QTY,
        candidate.average_edge_cad,
        protected_edge,
    )

    initial = client.limit_order(
        RITC,
        ritc_action,
        requested,
        limit_price,
        reference_price=float(candidate.reference_prices[RITC]),
        execution_id=execution_child_id,
        event="DIRECT_PROTECTED_LEAD_ORDER",
        module="DIRECT_ARB",
    )
    if not LIVE_TRADING:
        return 0
    lead = finish_short_lived_limit_order(
        client,
        state,
        initial,
        execution_id=execution_child_id,
    )
    if lead.filled <= 0:
        logging.info(
            "DIRECT CHILD NOT FILLED: price protection prevented execution."
        )
        return 0
    if lead.vwap is None:
        logging.error(
            "DIRECT CHILD: RITC filled %d but no VWAP was returned; "
            "flattening the lead.",
            lead.filled,
        )
        submit_in_chunks(
            client,
            RITC,
            opposite(ritc_action),
            lead.filled,
            execution_id=f"{execution_child_id}-missing-vwap-unwind",
        )
        return 0
    result_collector.append(lead)

    basket_legs = [
        (ticker, action, lead.filled)
        for ticker, action, _ in candidate.legs
        if ticker in (BULL, BEAR)
    ]
    try:
        basket_matched = execute_direct_legs_concurrently(
            client,
            state,
            basket_legs,
            reference_prices=candidate.reference_prices,
            execution_id=execution_child_id,
            result_collector=result_collector,
        )
    except Exception:
        # The concurrent basket helper rolls back any known basket fills.
        # Remove the lead as well before allowing the error to propagate.
        submit_in_chunks(
            client,
            RITC,
            opposite(ritc_action),
            lead.filled,
            execution_id=f"{execution_child_id}-basket-error-unwind",
        )
        raise
    if basket_matched < lead.filled:
        residual = lead.filled - basket_matched
        logging.error(
            "DIRECT CHILD PARTIAL HEDGE: flattening %d excess RITC shares",
            residual,
        )
        submit_in_chunks(
            client,
            RITC,
            opposite(ritc_action),
            residual,
            execution_id=f"{execution_child_id}-residual-unwind",
        )
    if basket_matched > 0:
        hedge_fx_to_target(
            client,
            execution_id=execution_child_id,
            result_collector=result_collector,
            force=True,
        )
    return basket_matched


def hedge_fx_to_target(
    client: RITClient,
    state: Optional[MarketState] = None,
    *,
    execution_id: str = "",
    result_collector: Optional[List[OrderResult]] = None,
    force: bool = False,
) -> int:
    if not ENABLE_FX_HEDGE:
        return 0

    if state is None:
        state, _fx_snapshot_metrics = load_direct_preflight_state(client)
    client.set_state_context(state)

    if state.seconds_remaining <= STOP_ALL_NEW_ORDERS_SECONDS:
        return 0

    # RITC trades create/consume USD cash automatically.  Because the edge
    # calculation prices that cash at the executable USD/CAD bid or ask, the
    # matching execution target is zero residual USD cash—not an additional
    # -RITC*price USD position.
    target_usd_position = 0
    current_usd_position = state.positions[USD]
    adjustment = target_usd_position - current_usd_position

    if adjustment == 0:
        return 0

    if not force and abs(adjustment) < FX_HEDGE_TRIGGER_USD:
        return 0

    action = "BUY" if adjustment > 0 else "SELL"
    quantity = min(abs(adjustment), MAX_FX_ORDER_SIZE)

    client.audit.action(
        state=state,
        event="FX_CASH_CONVERSION_SIGNAL",
        module="FX",
        label="Convert residual RITC cash flow through USD/CAD",
        ticker=USD,
        action=action,
        requested_quantity=quantity,
        status="QUALIFIED",
        details={
            "ritc_position": state.positions[RITC],
            "target_usd_position": target_usd_position,
            "current_usd_position": current_usd_position,
            "adjustment": adjustment,
            "forced_reconciliation": force,
        },
    )

    logging.info(
        "FX cash conversion: RITC=%s, target USD=0, "
        "current USD=%s -> %s %d USD",
        f"{state.positions[RITC]:+,d}",
        f"{current_usd_position:+,d}",
        action,
        quantity,
    )

    return submit_in_chunks(
        client,
        USD,
        action,
        quantity,
        reference_price=(
            state.books[USD].best_ask
            if action == "BUY"
            else state.books[USD].best_bid
        ),
        execution_id=execution_id,
        result_collector=result_collector,
    )


def lock_preconversion_fx_funding(
    client: RITClient,
    tender_id: int,
    converter_uses: int,
) -> bool:
    """Set USD to exactly the amount the pending converter will consume.

    V6 waited until every two-tick converter lot completed before converting
    the tender's residual USD cash. A five-lot CREATE therefore carried a
    roughly ten-second USD/CAD exposure. V7 converts the excess or shortfall
    immediately, retains only the known converter funding, and verifies the
    resulting cash position before the first converter request.
    """
    if not LOCK_MIXED_CONVERTER_FX_BEFORE_CONVERSION:
        return True

    target_usd = int(round(
        converter_uses * CONVERTER_COST_USD_PER_USE
    ))
    state_before = load_state(client)
    client.set_state_context(state_before)
    initial_usd = int(state_before.positions.get(USD, 0))
    adjustment = target_usd - initial_usd
    requested = abs(adjustment)
    filled_total = 0

    if adjustment:
        action = "BUY" if adjustment > 0 else "SELL"
        filled_total += submit_in_chunks(
            client,
            USD,
            action,
            requested,
            reference_price=(
                state_before.books[USD].best_ask
                if action == "BUY"
                else state_before.books[USD].best_bid
            ),
            execution_id=f"converter-{tender_id}-fx-lock",
        )

    # Retry the exact residual once. This also handles an intervening manual
    # USD trade without assuming that the original requested amount remains
    # correct.
    state_after_first = load_state(client)
    client.set_state_context(state_after_first)
    residual = target_usd - int(state_after_first.positions.get(USD, 0))
    if residual:
        retry_action = "BUY" if residual > 0 else "SELL"
        filled_total += submit_in_chunks(
            client,
            USD,
            retry_action,
            abs(residual),
            reference_price=(
                state_after_first.books[USD].best_ask
                if retry_action == "BUY"
                else state_after_first.books[USD].best_bid
            ),
            execution_id=f"converter-{tender_id}-fx-lock-retry",
        )

    final_state = load_state(client)
    client.set_state_context(final_state)
    final_usd = int(final_state.positions.get(USD, 0))
    locked = final_usd == target_usd
    action_label = (
        "BUY" if adjustment > 0 else ("SELL" if adjustment < 0 else "NONE")
    )
    details = {
        "initial_usd_position": initial_usd,
        "target_usd_position": target_usd,
        "initial_adjustment": adjustment,
        "initial_action": action_label,
        "requested_quantity": requested,
        "filled_quantity_across_attempts": filled_total,
        "final_usd_position": final_usd,
        "converter_uses": converter_uses,
        "converter_cost_usd_per_use": CONVERTER_COST_USD_PER_USE,
    }

    if pending_converter is not None:
        pending_converter["preconversion_fx_lock"] = details

    client.audit.action(
        state=final_state,
        event="PRECONVERSION_FX_LOCK",
        module="FX",
        tender_id=tender_id,
        ticker=USD,
        action=action_label,
        requested_quantity=requested,
        filled_quantity=(requested if locked else filled_total),
        status="LOCKED" if locked else "FAILED_RECONCILIATION",
        message=(
            f"USD locked at {target_usd:,}; converter funding reserved."
            if locked
            else (
                f"USD FX lock failed: expected {target_usd:+,}, "
                f"observed {final_usd:+,}."
            )
        ),
        details=details,
    )

    if locked:
        logging.warning(
            "PRE-CONVERSION FX LOCK: USD %s -> %s; reserved %d for %d "
            "converter use(s).",
            f"{initial_usd:+,d}",
            f"{final_usd:+,d}",
            target_usd,
            converter_uses,
        )
    else:
        logging.critical(
            "PRE-CONVERSION FX LOCK FAILED: expected USD %+d, observed %+d. "
            "Converter will not start.",
            target_usd,
            final_usd,
        )
    return locked


def aggregate_fill_vwap(
    results: Sequence[OrderResult],
    ticker: str,
    action: str,
    quantity: int,
) -> Optional[float]:
    if quantity <= 0:
        return None

    selected = [
        result
        for result in results
        if result.ticker == ticker
        and result.action == action
        and result.filled > 0
        and result.vwap is not None
    ]
    filled = sum(result.filled for result in selected)
    if filled != quantity:
        return None
    return sum(
        result.filled * float(result.vwap)
        for result in selected
    ) / filled


def direct_fill_based_pnl(
    candidate: Candidate,
    results: Sequence[OrderResult],
    matched_quantity: int,
) -> Tuple[Optional[float], Dict[str, Any]]:
    """Reconcile one completed four-leg package from actual order VWAPs."""
    if matched_quantity <= 0:
        return None, {"reason": "No matched equity quantity"}

    action_by_ticker = {
        ticker: action
        for ticker, action, _ in candidate.legs
    }
    action_by_ticker[USD] = (
        "BUY" if candidate.direction == "ETF_CHEAP" else "SELL"
    )

    actual_prices: Dict[str, float] = {}
    for ticker in (BULL, BEAR, RITC):
        price = aggregate_fill_vwap(
            results,
            ticker,
            action_by_ticker[ticker],
            matched_quantity,
        )
        if price is None:
            return None, {
                "reason": f"Could not reconcile exact {ticker} fill quantity",
            }
        actual_prices[ticker] = price

    fx_results = [
        result
        for result in results
        if result.ticker == USD
        and result.action == action_by_ticker[USD]
        and result.filled > 0
        and result.vwap is not None
    ]
    if not fx_results:
        return None, {"reason": "No matching USD conversion fill"}

    fx_filled = sum(result.filled for result in fx_results)
    actual_prices[USD] = sum(
        result.filled * float(result.vwap)
        for result in fx_results
    ) / fx_filled

    ritc_results = [
        result
        for result in results
        if result.ticker == RITC
        and result.action == action_by_ticker[RITC]
        and result.filled > 0
    ]
    ritc_limit_lead = bool(ritc_results) and all(
        result.order_type.upper() == "LIMIT"
        for result in ritc_results
    )
    ritc_buy_cash = (
        actual_prices[RITC] - EQUITY_LIMIT_REBATE_PER_SHARE
        if ritc_limit_lead
        else actual_prices[RITC] + EQUITY_MARKET_FEE_PER_SHARE
    )
    ritc_sell_cash = (
        actual_prices[RITC] + EQUITY_LIMIT_REBATE_PER_SHARE
        if ritc_limit_lead
        else actual_prices[RITC] - EQUITY_MARKET_FEE_PER_SHARE
    )

    if candidate.direction == "ETF_CHEAP":
        actual_edge = (
            actual_prices[BULL] - EQUITY_MARKET_FEE_PER_SHARE
            + actual_prices[BEAR] - EQUITY_MARKET_FEE_PER_SHARE
            - ritc_buy_cash * actual_prices[USD]
        )
    else:
        actual_edge = (
            ritc_sell_cash * actual_prices[USD]
            - actual_prices[BULL] - EQUITY_MARKET_FEE_PER_SHARE
            - actual_prices[BEAR] - EQUITY_MARKET_FEE_PER_SHARE
        )

    actual_pnl = actual_edge * matched_quantity
    details = {
        "reference_prices": candidate.reference_prices,
        "actual_prices": actual_prices,
        "fx_filled_quantity": fx_filled,
        "actual_edge_cad_per_share": actual_edge,
        "actual_fill_based_pnl_cad": actual_pnl,
        "forecast_error_cad": actual_pnl - candidate.total_pnl_cad,
        "ritc_order_type": "LIMIT" if ritc_limit_lead else "MARKET",
        "ritc_limit_rebate_applied": ritc_limit_lead,
    }
    return actual_pnl, details


def execute_direct_candidate(
    client: RITClient,
    state: MarketState,
    candidate: Candidate,
) -> None:
    client.audit.direct_actions_qualified += 1
    execution_id = (
        f"direct_p{state.period}_t{state.tick}_"
        f"{time.monotonic_ns()}"
    )

    client.audit.action(
        state=state,
        event="DIRECT_ACTION",
        module="DIRECT_ARB",
        label=candidate.label,
        requested_quantity=candidate.quantity,
        average_edge_cad=candidate.average_edge_cad,
        expected_pnl_cad=candidate.total_pnl_cad,
        score_cad=candidate.score_cad,
        status="EXECUTING" if LIVE_TRADING else "DRY_RUN",
        details={
            "execution_id": execution_id,
            "direction": candidate.direction,
            "legs": candidate.legs,
            "reference_prices": candidate.reference_prices,
        },
    )

    logging.warning(
        "DIRECT: %s | q=%d | edge=%.4f CAD | "
        "expected P&L=CAD %.2f",
        candidate.label,
        candidate.quantity,
        candidate.average_edge_cad,
        candidate.total_pnl_cad,
    )

    results: List[OrderResult] = []
    remaining = candidate.quantity
    matched = 0
    executed_expected_pnl = 0.0
    reference_numerators = {
        ticker: 0.0 for ticker in (BULL, BEAR, RITC, USD)
    }
    child_count = 0

    while remaining >= MIN_DIRECT_QTY:
        fresh_state, metrics = load_direct_preflight_state(client)
        client.set_state_context(fresh_state)
        if (
            fresh_state.status != "ACTIVE"
            or fresh_state.seconds_remaining <= STOP_ALL_DIRECT_ARB_SECONDS
        ):
            break

        child_cap = min(DIRECT_PROTECTED_CHILD_QTY, remaining)
        reduction_only = (
            fresh_state.seconds_remaining <= STOP_NEW_DIRECT_ARB_SECONDS
        )
        if reduction_only:
            child_cap = min(
                child_cap,
                direct_inventory_reduction_capacity(
                    fresh_state,
                    candidate.direction,
                ),
            )
        if child_cap < MIN_DIRECT_QTY:
            break

        child_candidate, profitable_depth, reason = evaluate_direct_candidate(
            fresh_state,
            candidate.direction,
            max_quantity=child_cap,
        )
        client.audit.action(
            state=fresh_state,
            event="DIRECT_CHILD_REVALUATION",
            module="DIRECT_ARB",
            label=candidate.label,
            requested_quantity=child_cap,
            filled_quantity=(
                child_candidate.quantity
                if child_candidate is not None
                else 0
            ),
            average_edge_cad=(
                child_candidate.average_edge_cad
                if child_candidate is not None
                else ""
            ),
            expected_pnl_cad=(
                child_candidate.total_pnl_cad
                if child_candidate is not None
                else ""
            ),
            status="PASSED" if child_candidate is not None else "STOPPED",
            message=reason,
            details={
                "execution_id": execution_id,
                "remaining_parent_quantity": remaining,
                "profitable_visible_quantity": profitable_depth,
                **metrics,
            },
        )
        if child_candidate is None:
            break

        child_matched = execute_protected_direct_child(
            client,
            fresh_state,
            child_candidate,
            execution_id=execution_id,
            result_collector=results,
        )
        if child_matched <= 0:
            break

        child_count += 1
        matched += child_matched
        remaining -= child_matched
        executed_expected_pnl += (
            child_candidate.average_edge_cad * child_matched
        )
        for ticker in reference_numerators:
            reference_numerators[ticker] += (
                float(child_candidate.reference_prices[ticker])
                * child_matched
            )

        # A partial lead means the protected price exhausted available
        # liquidity. Do not chase the unfilled remainder at a worse price.
        if child_matched < child_candidate.quantity:
            break

    if LIVE_TRADING and matched > 0:
        client.audit.direct_actions_executed += 1

        action_by_ticker = {
            ticker: action for ticker, action, _ in candidate.legs
        }
        executed_candidate = Candidate(
            kind=candidate.kind,
            label=candidate.label,
            quantity=matched,
            total_pnl_cad=executed_expected_pnl,
            average_edge_cad=executed_expected_pnl / matched,
            score_cad=executed_expected_pnl,
            legs=[
                (ticker, action_by_ticker[ticker], matched)
                for ticker in (BULL, BEAR, RITC)
            ],
            direction=candidate.direction,
            reference_prices={
                ticker: reference_numerators[ticker] / matched
                for ticker in reference_numerators
            },
        )

        actual_pnl, details = direct_fill_based_pnl(
            executed_candidate,
            results,
            matched,
        )
        client.audit.action(
            state=state,
            event="DIRECT_EXECUTION_SUMMARY",
            module="DIRECT_ARB",
            label=candidate.label,
            requested_quantity=candidate.quantity,
            filled_quantity=matched,
            average_edge_cad=(
                actual_pnl / matched
                if actual_pnl is not None and matched > 0
                else ""
            ),
            expected_pnl_cad=executed_expected_pnl,
            score_cad=actual_pnl if actual_pnl is not None else "",
            status=(
                "RECONCILED"
                if actual_pnl is not None
                else "UNAVAILABLE"
            ),
            message=(
                "Fill-based P&L uses actual equity and USD-conversion VWAPs."
            ),
            details={
                "execution_id": execution_id,
                "protected_child_count": child_count,
                "unfilled_parent_quantity": max(0, remaining),
                **details,
            },
        )

        if actual_pnl is not None:
            client.audit.direct_executions_reconciled += 1
            client.audit.direct_expected_pnl_cad += executed_expected_pnl
            client.audit.direct_fill_based_pnl_cad += actual_pnl
            logging.warning(
                "DIRECT FILLS: actual edge=%.4f CAD | "
                "fill-based P&L=CAD %.2f | forecast error=CAD %.2f",
                actual_pnl / matched,
                actual_pnl,
                actual_pnl - executed_expected_pnl,
            )
    elif LIVE_TRADING:
        client.audit.action(
            state=state,
            event="DIRECT_EXECUTION_SUMMARY",
            module="DIRECT_ARB",
            label=candidate.label,
            requested_quantity=candidate.quantity,
            filled_quantity=0,
            average_edge_cad=candidate.average_edge_cad,
            expected_pnl_cad=candidate.total_pnl_cad,
            status="NO_FILL_PRICE_PROTECTED",
            message=(
                "The RITC protection price prevented a stale or adverse fill."
            ),
            details={
                "execution_id": execution_id,
                "protected_child_count": child_count,
            },
        )


def passive_ritc_candidate(state: MarketState) -> Optional[Candidate]:
    """Return the better one-tick passive RITC lead opportunity."""
    if (
        not ENABLE_PASSIVE_RITC_ARB
        or state.seconds_remaining <= PASSIVE_STOP_NEW_QUOTES_SECONDS
    ):
        return None
    quantity = min(PASSIVE_RITC_ORDER_QTY, MAX_EQUITY_ORDER_SIZE)
    if quantity <= 0:
        return None

    candidates: List[Candidate] = []
    for action, direction in (("BUY", "ETF_CHEAP"), ("SELL", "ETF_RICH")):
        ritc_book = state.books[RITC]
        limit_price = ritc_book.best_bid if action == "BUY" else ritc_book.best_ask
        if not math.isfinite(limit_price) or limit_price <= 0:
            continue
        basket_action = "SELL" if action == "BUY" else "BUY"
        bull_levels = (
            state.books[BULL].bids if basket_action == "SELL" else state.books[BULL].asks
        )
        bear_levels = (
            state.books[BEAR].bids if basket_action == "SELL" else state.books[BEAR].asks
        )
        bull_price = depth_vwap(bull_levels, quantity)
        bear_price = depth_vwap(bear_levels, quantity)
        ritc_cash = (
            limit_price - EQUITY_LIMIT_REBATE_PER_SHARE
            if action == "BUY"
            else limit_price + EQUITY_LIMIT_REBATE_PER_SHARE
        )
        fx_levels = state.books[USD].asks if action == "BUY" else state.books[USD].bids
        fx_price = depth_vwap(fx_levels, quantity * ritc_cash)
        if not all(math.isfinite(x) for x in (bull_price, bear_price, fx_price)):
            continue
        if action == "BUY":
            edge = (
                bull_price + bear_price
                - 2.0 * EQUITY_MARKET_FEE_PER_SHARE
                - ritc_cash * fx_price
            )
        else:
            edge = (
                ritc_cash * fx_price
                - bull_price - bear_price
                - 2.0 * EQUITY_MARKET_FEE_PER_SHARE
            )
        pnl = edge * quantity
        lead_deltas = {RITC: signed_delta(action, quantity)}
        final_legs = [
            (RITC, action, quantity),
            (BULL, basket_action, quantity),
            (BEAR, basket_action, quantity),
        ]
        final_deltas = legs_to_deltas(final_legs)
        if (
            edge < PASSIVE_MIN_HEDGE_EDGE_CAD
            or pnl < PASSIVE_MIN_TOTAL_PNL_CAD
            or not risk_allows(state.positions, lead_deltas)
            or not risk_allows(state.positions, final_deltas)
            or not matched_inventory_allows(state.positions, final_deltas)
        ):
            continue
        candidates.append(Candidate(
            kind="PASSIVE_RITC",
            label=f"PASSIVE {action} RITC; hedge BULL+BEAR on fill",
            quantity=quantity,
            total_pnl_cad=pnl,
            average_edge_cad=edge,
            score_cad=pnl,
            legs=[(RITC, action, quantity)],
            direction=direction,
            reference_prices={
                RITC: limit_price,
                BULL: bull_price,
                BEAR: bear_price,
                USD: fx_price,
            },
        ))
    return max(candidates, key=lambda item: item.score_cad, default=None)


def place_passive_ritc_order(
    client: RITClient,
    state: MarketState,
    candidate: Candidate,
) -> bool:
    global active_passive_order
    if active_passive_order is not None:
        return False
    action = candidate.legs[0][1]
    price = float(candidate.reference_prices[RITC])
    result = client.limit_order(
        RITC,
        action,
        candidate.quantity,
        price,
        reference_price=price,
        execution_id=f"passive-p{state.period}-t{state.tick}",
    )
    if not LIVE_TRADING:
        return False
    if result.order_id is None:
        client.audit.passive_hedge_failures += 1
        logging.error("PASSIVE RITC order response did not contain an order id")
        return False
    active_passive_order = PassiveOrderState(
        order_id=result.order_id,
        action=action,
        quantity=candidate.quantity,
        price=price,
        direction=candidate.direction,
        expected_edge_cad=candidate.average_edge_cad,
        expected_pnl_cad=candidate.total_pnl_cad,
        placed_monotonic=time.monotonic(),
        placed_tick=state.tick,
        position_before=int(state.positions.get(RITC, 0)),
    )
    client.audit.passive_quotes_submitted += 1
    logging.warning(
        "PASSIVE LEAD: %s %d RITC @ %.4f | hedge edge %.4f | expected P&L CAD %.2f",
        action,
        candidate.quantity,
        price,
        candidate.average_edge_cad,
        candidate.total_pnl_cad,
    )
    return True


def service_active_passive_order(
    client: RITClient,
    state: MarketState,
    *,
    force_cancel: bool = False,
) -> Tuple[bool, bool]:
    """Cancel an expired lead and immediately hedge its frozen fill.

    Returns (performed_trade_action, order_remains_open).
    """
    global active_passive_order
    lead = active_passive_order
    if lead is None:
        return False, False

    row_optional = client.get_order_optional(lead.order_id)
    row = dict(row_optional) if row_optional is not None else {}
    status = (
        str(row.get("status", "OPEN")).upper()
        if row_optional is not None
        else "TERMINAL_NOT_FOUND"
    )
    age = time.monotonic() - lead.placed_monotonic
    terminal = (
        row_optional is None
        or status in {"CANCELLED", "TRANSACTED", "REJECTED"}
    )
    if not terminal and (force_cancel or age >= PASSIVE_QUOTE_LIFETIME_SECONDS):
        client.cancel_order(lead.order_id)
        row_optional = client.get_order_optional(lead.order_id)
        if row_optional is not None:
            row = dict(row_optional)
            status = str(row.get("status", "CANCELLED")).upper()
        else:
            status = "TERMINAL_NOT_FOUND"
        terminal = True

    reported_fill = int(round(float(row.get("quantity_filled", 0) or 0)))
    inferred_fill = 0
    if row_optional is None:
        inferred_fill = infer_limit_fill_from_position(
            client,
            ticker=RITC,
            action=lead.action,
            position_before=lead.position_before,
            requested=lead.quantity,
        )
        if inferred_fill > reported_fill:
            row["quantity_filled"] = inferred_fill
            row["vwap"] = lead.price
            logging.warning(
                "PASSIVE LIMIT RACE: inferred %d-share %s fill from "
                "the RITC position change",
                inferred_fill,
                lead.action,
            )
    filled = max(reported_fill, inferred_fill)
    if not terminal:
        return False, True

    incremental = max(0, filled - lead.already_hedged)
    active_passive_order = None
    if incremental <= 0:
        client.audit.action(
            state=state,
            event="PASSIVE_ORDER_CLOSED",
            module="PASSIVE_ARB",
            ticker=RITC,
            action=lead.action,
            requested_quantity=lead.quantity,
            filled_quantity=filled,
            status=status,
            message="Passive lead expired without a new fill.",
        )
        return False, False

    client.audit.orders_filled += incremental
    client.audit.passive_shares_filled += incremental
    if incremental > PASSIVE_MAX_FILLED_UNHEDGED_QTY:
        client.audit.passive_hedge_failures += 1
        logging.critical(
            "PASSIVE FILL EXCEEDED CAP: %d > %d",
            incremental,
            PASSIVE_MAX_FILLED_UNHEDGED_QTY,
        )

    fresh_state, _metrics = load_direct_preflight_state(client)
    client.set_state_context(fresh_state)
    basket_action = "SELL" if lead.action == "BUY" else "BUY"
    hedge_results: List[OrderResult] = []
    matched = execute_matched_legs(
        client,
        fresh_state,
        [
            (BULL, basket_action, incremental),
            (BEAR, basket_action, incremental),
        ],
        execution_id=f"passive-hedge-{lead.order_id}",
        result_collector=hedge_results,
    )
    residual = incremental - matched
    if residual > 0:
        submit_in_chunks(
            client,
            RITC,
            opposite(lead.action),
            residual,
            execution_id=f"passive-unwind-{lead.order_id}",
        )
    hedge_fx_to_target(
        client,
        execution_id=f"passive-fx-{lead.order_id}",
        result_collector=hedge_results,
        force=True,
    )
    complete = matched == incremental
    if complete:
        client.audit.passive_hedges_completed += 1
    else:
        client.audit.passive_hedge_failures += 1
    lead_vwap = float(row.get("vwap", lead.price) or lead.price)
    actual_pnl: Optional[float] = None
    bull_vwap = aggregate_fill_vwap(
        hedge_results,
        BULL,
        basket_action,
        matched,
    )
    bear_vwap = aggregate_fill_vwap(
        hedge_results,
        BEAR,
        basket_action,
        matched,
    )
    fx_action = "BUY" if lead.action == "BUY" else "SELL"
    fx_rows = [
        result for result in hedge_results
        if result.ticker == USD
        and result.action == fx_action
        and result.filled > 0
        and result.vwap is not None
    ]
    fx_filled = sum(result.filled for result in fx_rows)
    fx_vwap = (
        sum(result.filled * float(result.vwap) for result in fx_rows)
        / fx_filled
        if fx_filled
        else None
    )
    if (
        complete
        and bull_vwap is not None
        and bear_vwap is not None
        and fx_vwap is not None
    ):
        if lead.action == "BUY":
            actual_edge = (
                bull_vwap + bear_vwap
                - 2.0 * EQUITY_MARKET_FEE_PER_SHARE
                - (lead_vwap - EQUITY_LIMIT_REBATE_PER_SHARE) * fx_vwap
            )
        else:
            actual_edge = (
                (lead_vwap + EQUITY_LIMIT_REBATE_PER_SHARE) * fx_vwap
                - bull_vwap - bear_vwap
                - 2.0 * EQUITY_MARKET_FEE_PER_SHARE
            )
        actual_pnl = actual_edge * incremental
    expected_fill_pnl = lead.expected_edge_cad * incremental
    client.audit.passive_expected_pnl_cad += expected_fill_pnl
    if actual_pnl is not None:
        client.audit.passive_fill_based_pnl_cad += actual_pnl
    client.audit.action(
        state=fresh_state,
        event="PASSIVE_FILL_HEDGED",
        module="PASSIVE_ARB",
        ticker=RITC,
        action=lead.action,
        requested_quantity=lead.quantity,
        filled_quantity=incremental,
        average_edge_cad=lead.expected_edge_cad,
        expected_pnl_cad=expected_fill_pnl,
        score_cad=actual_pnl if actual_pnl is not None else "",
        coverage=(matched / incremental if incremental else 1.0),
        status="HEDGED" if complete else "PARTIAL_HEDGE_AND_RITC_UNWIND",
        details={
            "order_id": lead.order_id,
            "basket_matched": matched,
            "lead_vwap": lead_vwap,
            "bull_vwap": bull_vwap,
            "bear_vwap": bear_vwap,
            "fx_vwap": fx_vwap,
            "actual_fill_based_pnl_cad": actual_pnl,
            "forecast_error_cad": (
                actual_pnl - expected_fill_pnl
                if actual_pnl is not None
                else None
            ),
        },
    )
    logging.warning(
        "PASSIVE FILL: %s %d RITC @ %.4f; basket hedge %d/%d",
        lead.action,
        incremental,
        lead.price,
        matched,
        incremental,
    )
    return True, False


def simulator_pnl_from_audit(audit: AuditLogger) -> Optional[float]:
    snapshot = audit.last_pnl_snapshot or {}
    value = snapshot.get("total_pnl_cad", "")
    try:
        return float(value) if value != "" else None
    except (TypeError, ValueError):
        return None


def trader_pnl_from_payload(payload: Any) -> Optional[float]:
    """Extract account P&L from either supported GET /trader shape."""
    if isinstance(payload, list):
        row = payload[0] if payload else {}
    elif isinstance(payload, dict):
        row = payload
    else:
        row = {}
    for key in ("nlv", "pnl", "total_pnl", "total_pl"):
        value = row.get(key)
        if value in (None, ""):
            continue
        try:
            return float(value)
        except (TypeError, ValueError):
            continue
    return None


def capture_simulator_pnl(client: RITClient) -> Optional[float]:
    """Read current simulator P&L, falling back to the latest audit sample."""
    try:
        value = trader_pnl_from_payload(client.trader())
        if value is not None:
            return value
    except (requests.RequestException, ApiException, ValueError) as exc:
        logging.warning("Tender P&L capture fell back to pnl.csv state: %s", exc)
    return simulator_pnl_from_audit(client.audit)


def log_tender_campaign_pnl(
    client: RITClient,
    state: MarketState,
    *,
    tender_id: int,
    quantity: int,
    expected_pnl_cad: Optional[float],
    pnl_before_accept_cad: Optional[float],
    accepted_monotonic: float,
    route: str,
    status: str,
) -> None:
    """Attribute the full tender campaign from pre-acceptance through FX."""
    pnl_after = capture_simulator_pnl(client)
    actual_change = (
        pnl_after - pnl_before_accept_cad
        if pnl_after is not None and pnl_before_accept_cad is not None
        else None
    )
    client.audit.action(
        state=state,
        event="TENDER_CAMPAIGN_PNL_RECONCILIATION",
        module="TENDER",
        tender_id=tender_id,
        requested_quantity=quantity,
        filled_quantity=quantity,
        expected_pnl_cad=(
            expected_pnl_cad if expected_pnl_cad is not None else ""
        ),
        score_cad=actual_change if actual_change is not None else "",
        status=status,
        message=(
            "score_cad is the simulator account P&L change from immediately "
            "before tender acceptance through hedge, converter, and FX."
        ),
        details={
            "route": route,
            "pnl_before_accept_cad": pnl_before_accept_cad,
            "pnl_after_campaign_cad": pnl_after,
            "actual_campaign_pnl_change_cad": actual_change,
            "forecast_error_cad": (
                actual_change - expected_pnl_cad
                if actual_change is not None and expected_pnl_cad is not None
                else None
            ),
            "campaign_elapsed_seconds": (
                time.monotonic() - accepted_monotonic
            ),
        },
    )
    if actual_change is not None:
        logging.warning(
            "TENDER CAMPAIGN P&L #%d: actual CAD %.2f vs expected CAD %.2f",
            tender_id,
            actual_change,
            float(expected_pnl_cad or 0.0),
        )


def unconverted_liquidation_estimate(
    state: MarketState,
    alert: Dict[str, Any],
) -> Optional[float]:
    """Estimate package P&L if the open converter portion were closed now.

    This uses decision-time entry economics and current visible-depth VWAPs.
    It is a counterfactual estimate, not simulator account P&L.  Once a
    partial conversion is detected, the original no-converter path no longer
    exists and the function deliberately returns None.
    """
    quantity = int(alert.get("quantity", 0))
    if quantity <= 0:
        return None
    if int(alert.get("remaining_quantity", quantity)) != quantity:
        return None

    entry_estimate = alert.get("estimated_no_converter_open_pnl_cad")
    if entry_estimate in (None, ""):
        return None

    tender_action = str(alert.get("tender_action", ""))
    bull = state.books[BULL]
    bear = state.books[BEAR]
    ritc = state.books[RITC]
    usd = state.books[USD]

    if tender_action == "BUY":
        ritc_vwap = depth_vwap(ritc.bids, quantity)
        bull_vwap = depth_vwap(bull.asks, quantity)
        bear_vwap = depth_vwap(bear.asks, quantity)
        usd_proceeds = quantity * (
            ritc_vwap - EQUITY_MARKET_FEE_PER_SHARE
        )
        fx_vwap = depth_vwap(usd.bids, usd_proceeds)
        if not all(math.isfinite(x) for x in (
            ritc_vwap, bull_vwap, bear_vwap, fx_vwap,
        )):
            return None
        close_pnl = (
            usd_proceeds * fx_vwap
            - quantity * bull_vwap
            - quantity * bear_vwap
            - quantity * 2.0 * EQUITY_MARKET_FEE_PER_SHARE
        )
    else:
        ritc_vwap = depth_vwap(ritc.asks, quantity)
        bull_vwap = depth_vwap(bull.bids, quantity)
        bear_vwap = depth_vwap(bear.bids, quantity)
        usd_cost = quantity * (
            ritc_vwap + EQUITY_MARKET_FEE_PER_SHARE
        )
        fx_vwap = depth_vwap(usd.asks, usd_cost)
        if not all(math.isfinite(x) for x in (
            ritc_vwap, bull_vwap, bear_vwap, fx_vwap,
        )):
            return None
        close_pnl = (
            quantity * bull_vwap
            + quantity * bear_vwap
            - quantity * 2.0 * EQUITY_MARKET_FEE_PER_SHARE
            - usd_cost * fx_vwap
        )

    return (
        float(entry_estimate)
        + close_pnl
    )


def converter_progress(
    state: MarketState,
    alert: Dict[str, Any],
) -> Tuple[int, int, bool, Dict[str, int]]:
    before = alert["preconversion_positions"]
    action = str(alert["converter_action"])
    quantity = int(alert["quantity"])

    if action == "REDEEM":
        components = {
            "ritc": int(before[RITC]) - int(state.positions[RITC]),
            "bull": int(state.positions[BULL]) - int(before[BULL]),
            "bear": int(state.positions[BEAR]) - int(before[BEAR]),
        }
    else:
        components = {
            "ritc": int(state.positions[RITC]) - int(before[RITC]),
            "bull": int(before[BULL]) - int(state.positions[BULL]),
            "bear": int(before[BEAR]) - int(state.positions[BEAR]),
        }

    values = list(components.values())
    expected = (
        len(set(values)) == 1
        and 0 <= values[0] <= quantity
        and values[0] % CONVERTER_LOT == 0
    )
    converted = min(quantity, max(0, values[0])) if expected else min(
        quantity,
        max(0, components["ritc"]),
    )
    return converted, max(0, quantity - converted), expected, components


def activate_pending_converter(
    client: RITClient,
    state: MarketState,
    tender: dict,
    candidate: Candidate,
    baseline_positions: Dict[str, int],
    actual_converter_quantity: int,
    *,
    pnl_before_accept_cad: Optional[float],
    campaign_started_monotonic: float,
) -> None:
    global pending_converter, pending_converter_last_reminder

    if actual_converter_quantity <= 0:
        return

    tender_id = int(tender["tender_id"])
    tender_action = str(tender["action"]).upper()
    actual_uses = actual_converter_quantity // CONVERTER_LOT
    preconversion_positions = {
        ticker: int(state.positions.get(ticker, 0))
        for ticker in (BULL, BEAR, RITC)
    }
    signed_converter = actual_converter_quantity if tender_action == "BUY" else -actual_converter_quantity
    signed_basket = -actual_converter_quantity if tender_action == "BUY" else actual_converter_quantity
    expected_preconversion_positions = {
        RITC: int(baseline_positions.get(RITC, 0)) + signed_converter,
        BULL: int(baseline_positions.get(BULL, 0)) + signed_basket,
        BEAR: int(baseline_positions.get(BEAR, 0)) + signed_basket,
    }
    positions_match = preconversion_positions == expected_preconversion_positions
    plan_quantity_match = actual_converter_quantity == candidate.converter_quantity
    plan_estimate_valid = positions_match and plan_quantity_match
    expected_converter_route_pnl = (
        candidate.total_pnl_cad if plan_estimate_valid else None
    )
    estimated_no_converter_open_pnl = (
        candidate.total_pnl_cad + candidate.converter_cost_cad
        if plan_estimate_valid
        else None
    )
    pnl_at_prompt = simulator_pnl_from_audit(client.audit)
    pending_converter = {
        "tender_id": tender_id,
        "action": (
            candidate.converter_action
            if positions_match
            else f"REVIEW BEFORE {candidate.converter_action}"
        ),
        "converter_action": candidate.converter_action,
        "tender_action": tender_action,
        "tender_price": float(tender["price"]),
        "quantity": actual_converter_quantity,
        "remaining_quantity": actual_converter_quantity,
        "remaining_uses": actual_uses,
        "direct_quantity": candidate.quantity - actual_converter_quantity,
        "started_utc": utc_now(),
        "started_monotonic": time.monotonic(),
        "started_tick": state.tick,
        "last_snapshot_tick": None,
        "last_unexpected_signature": None,
        "pnl_at_prompt_cad": pnl_at_prompt,
        "pnl_before_accept_cad": pnl_before_accept_cad,
        "campaign_started_monotonic": campaign_started_monotonic,
        "planned_converter_quantity": candidate.converter_quantity,
        "actual_converter_quantity": actual_converter_quantity,
        "planned_converter_route_pnl_cad": candidate.total_pnl_cad,
        "planned_converter_cost_cad": candidate.converter_cost_cad,
        "plan_estimate_valid": plan_estimate_valid,
        "expected_converter_route_pnl_cad": expected_converter_route_pnl,
        "estimated_no_converter_open_pnl_cad": estimated_no_converter_open_pnl,
        "converter_cost_cad": (
            candidate.converter_cost_cad if plan_quantity_match else None
        ),
        "baseline_positions": {
            ticker: int(baseline_positions.get(ticker, 0))
            for ticker in (BULL, BEAR, RITC)
        },
        "expected_preconversion_positions": expected_preconversion_positions,
        "preconversion_positions": preconversion_positions,
        "positions_reconciled_before_prompt": positions_match,
        "execution_mode": (
            "AUTOMATED" if ENABLE_AUTOMATED_CONVERTER else "MANUAL"
        ),
    }
    pending_converter["latest_no_converter_liquidation_estimate_cad"] = (
        unconverted_liquidation_estimate(state, pending_converter)
    )
    first_counterfactual = pending_converter[
        "latest_no_converter_liquidation_estimate_cad"
    ]
    pending_converter["latest_no_converter_minus_converter_cad"] = (
        first_counterfactual - expected_converter_route_pnl
        if (
            first_counterfactual is not None
            and expected_converter_route_pnl is not None
        )
        else None
    )
    pending_converter_last_reminder = 0.0
    if ENABLE_AUTOMATED_CONVERTER:
        client.audit.automated_converter_attempts += 1
    else:
        client.audit.manual_converter_prompts += 1

    client.audit.action(
        state=state,
        event="MIXED_TENDER_HEDGE_RECONCILIATION",
        module="TENDER",
        tender_id=tender_id,
        requested_quantity=actual_converter_quantity,
        filled_quantity=(actual_converter_quantity if positions_match else ""),
        status=(
            "EXPECTED"
            if plan_estimate_valid
            else (
                "ADJUSTED_AFTER_PARTIAL_FILL"
                if positions_match
                else "POSITION_MISMATCH"
            )
        ),
        message=(
            "Pre-conversion positions and quantity match the mixed-route plan."
            if plan_estimate_valid
            else (
                "Positions reconcile to a smaller complete-lot converter "
                "quantity after partial fills; the original P&L estimate is "
                "marked unavailable."
                if positions_match
                else "Do not convert blindly; actual positions differ from plan."
            )
        ),
        details={
            "baseline_positions": pending_converter["baseline_positions"],
            "expected_preconversion_positions": expected_preconversion_positions,
            "actual_preconversion_positions": preconversion_positions,
            "planned_converter_quantity": candidate.converter_quantity,
            "actual_converter_quantity": actual_converter_quantity,
            "plan_estimate_valid": plan_estimate_valid,
        },
    )

    if positions_match and ENABLE_AUTOMATED_CONVERTER:
        message = (
            f"AUTOMATED CONVERTER STARTING: {candidate.converter_action} "
            f"{actual_converter_quantity:,} RITC "
            f"({actual_uses} x {CONVERTER_LOT:,}). "
            "Each lot will be verified before the next is submitted."
        )
    elif positions_match:
        message = (
            f"ACTION REQUIRED NOW: MANUALLY {candidate.converter_action} "
            f"{actual_converter_quantity:,} RITC "
            f"({actual_uses} x {CONVERTER_LOT:,}). "
            "Strategy is paused until a converter-consistent position reset "
            "is detected."
        )
    else:
        message = (
            "POSITION MISMATCH: DO NOT USE THE CONVERTER BLINDLY. "
            f"Review fills before {candidate.converter_action} "
            f"{actual_converter_quantity:,} RITC. Strategy is paused."
        )
    logging.critical("\a%s", "=" * 78)
    logging.critical("\a%s", message)
    logging.critical("\a%s", "=" * 78)
    client.audit.action(
        state=state,
        event=(
            "AUTOMATED_CONVERTER_STARTED"
            if ENABLE_AUTOMATED_CONVERTER
            else "MANUAL_CONVERTER_REQUIRED"
        ),
        module="TENDER",
        label=message,
        tender_id=tender_id,
        requested_quantity=actual_converter_quantity,
        expected_pnl_cad=(
            expected_converter_route_pnl
            if expected_converter_route_pnl is not None
            else ""
        ),
        score_cad=(
            estimated_no_converter_open_pnl
            if estimated_no_converter_open_pnl is not None
            else ""
        ),
        status=(
            "AUTOMATION_STARTED"
            if positions_match and ENABLE_AUTOMATED_CONVERTER
            else ("ACTION_REQUIRED" if positions_match else "REVIEW_REQUIRED")
        ),
        message=(
            "score_cad stores the estimated entry P&L before converter cost "
            "for later no-converter comparison. Completion is verified from "
            "the exact equal-lot position changes."
        ),
        details=dict(pending_converter),
    )
    if active_dashboard is not None:
        active_dashboard.set_converter_alert(pending_converter)
        active_dashboard.push_event("CRITICAL", message)


def expected_positions_after_converter_lot(
    before: Dict[str, int],
    action: str,
) -> Dict[str, int]:
    """Exact position signature expected after one converter use."""
    expected = {
        ticker: int(before.get(ticker, 0))
        for ticker in (BULL, BEAR, RITC, USD)
    }
    expected[USD] -= int(CONVERTER_COST_USD_PER_USE)

    if action == "CREATE":
        expected[BULL] -= CONVERTER_LOT
        expected[BEAR] -= CONVERTER_LOT
        expected[RITC] += CONVERTER_LOT
    elif action == "REDEEM":
        expected[RITC] -= CONVERTER_LOT
        expected[BULL] += CONVERTER_LOT
        expected[BEAR] += CONVERTER_LOT
    else:
        raise ValueError(f"Unknown converter action: {action}")

    return expected


def wait_for_converter_lot(
    client: RITClient,
    before: Dict[str, int],
    action: str,
) -> Tuple[bool, Dict[str, int], Dict[str, int]]:
    """Poll until one exact converter lot appears or the timeout expires."""
    expected = expected_positions_after_converter_lot(before, action)
    actual = dict(before)
    deadline = time.monotonic() + AUTOMATED_CONVERTER_CONFIRM_TIMEOUT_SECONDS

    while time.monotonic() < deadline:
        actual = client.positions()
        if all(
            int(actual.get(ticker, 0)) == int(expected[ticker])
            for ticker in (BULL, BEAR, RITC, USD)
        ):
            return True, actual, expected
        time.sleep(AUTOMATED_CONVERTER_POLL_INTERVAL_SECONDS)

    return False, actual, expected


def execute_automated_pending_converter(client: RITClient) -> bool:
    """Fund, submit, and verify all converter lots for the pending tender."""
    global pending_converter

    if pending_converter is None:
        return True
    if not ENABLE_AUTOMATED_CONVERTER:
        return False

    action = str(pending_converter["converter_action"]).upper()
    tender_id = int(pending_converter["tender_id"])
    uses = int(pending_converter["remaining_uses"])

    if not pending_converter.get("positions_reconciled_before_prompt"):
        client.audit.automated_converter_failures += 1
        pending_converter["automation_failure_counted"] = True
        logging.critical(
            "AUTOMATED CONVERTER ABORTED: pre-conversion positions mismatch."
        )
        return False

    funding_required = int(round(
        uses * CONVERTER_COST_USD_PER_USE
    ))

    if not lock_preconversion_fx_funding(client, tender_id, uses):
        client.audit.automated_converter_failures += 1
        pending_converter["automation_failure_counted"] = True
        pending_converter["automation_failure"] = {
            "stage": "PRECONVERSION_FX_LOCK",
            "details": pending_converter.get("preconversion_fx_lock"),
        }
        if active_dashboard is not None:
            active_dashboard.set_converter_alert(pending_converter)
            active_dashboard.push_event(
                "CRITICAL",
                "Pre-conversion FX lock failed; converter was not started.",
            )
        return False

    current_positions = client.positions()
    funding_shortfall = max(
        0,
        funding_required - int(current_positions.get(USD, 0)),
    )
    if funding_shortfall:
        funding_result = client.market_order(
            USD,
            "BUY",
            funding_shortfall,
            execution_id=f"converter-{tender_id}-funding",
        )
        if funding_result.filled != funding_shortfall:
            client.audit.automated_converter_failures += 1
            pending_converter["automation_failure_counted"] = True
            logging.critical(
                "AUTOMATED CONVERTER FUNDING FAILED: USD filled %d/%d. "
                "Strategy remains paused.",
                funding_result.filled,
                funding_shortfall,
            )
            return False

    client.audit.action(
        state=client.context_state,
        event="AUTOMATED_CONVERTER_FUNDING",
        module="CONVERTER",
        tender_id=tender_id,
        ticker=USD,
        action="BUY" if funding_shortfall else "NONE",
        requested_quantity=funding_shortfall,
        filled_quantity=funding_shortfall,
        status="READY",
        message=(
            f"USD {funding_required:,} reserved for {uses} converter uses; "
            "other tender-related USD cash has already been converted."
            if LOCK_MIXED_CONVERTER_FX_BEFORE_CONVERSION
            else f"USD {funding_required:,} available for {uses} converter uses."
        ),
    )

    for use_number in range(1, uses + 1):
        before = client.positions()
        request_error: Optional[str] = None
        response: Any = None
        try:
            response = client.use_converter_once(action)
        except (requests.RequestException, ApiException, ValueError) as exc:
            # A lost POST response is ambiguous. Position verification below
            # decides whether the use completed before declaring failure.
            request_error = str(exc)

        confirmed, actual, expected = wait_for_converter_lot(
            client,
            before,
            action,
        )
        client.audit.action(
            state=client.context_state,
            event="AUTOMATED_CONVERTER_LOT",
            module="CONVERTER",
            tender_id=tender_id,
            action=action,
            requested_quantity=CONVERTER_LOT,
            filled_quantity=CONVERTER_LOT if confirmed else 0,
            coverage=(use_number / uses if confirmed else (use_number - 1) / uses),
            status=(
                "CONFIRMED_AFTER_AMBIGUOUS_RESPONSE"
                if confirmed and request_error
                else ("CONFIRMED" if confirmed else "FAILED_VERIFICATION")
            ),
            message=(
                f"Converter lot {use_number}/{uses} verified from positions."
                if confirmed
                else f"Converter lot {use_number}/{uses} was not verified."
            ),
            details={
                "lease_response": response,
                "request_error": request_error,
                "positions_before": before,
                "positions_expected": expected,
                "positions_actual": actual,
            },
        )

        if not confirmed:
            client.audit.automated_converter_failures += 1
            pending_converter["automation_failure_counted"] = True
            pending_converter["automation_failure"] = {
                "use_number": use_number,
                "request_error": request_error,
                "positions_expected": expected,
                "positions_actual": actual,
            }
            logging.critical(
                "AUTOMATED CONVERTER FAILED on lot %d/%d. "
                "No more converter requests or strategy trades will be sent.",
                use_number,
                uses,
            )
            if active_dashboard is not None:
                active_dashboard.set_converter_alert(pending_converter)
                active_dashboard.push_event(
                    "CRITICAL",
                    f"Automated converter failed on lot {use_number}/{uses}; "
                    "strategy paused for review.",
                )
            return False

        client.audit.automated_converter_lots_completed += 1
        logging.warning(
            "AUTOMATED CONVERTER: %s lot %d/%d confirmed.",
            action,
            use_number,
            uses,
        )

    final_state = load_state(client)
    client.set_state_context(final_state)
    service_pending_converter(client, final_state)
    if pending_converter is not None:
        client.audit.automated_converter_failures += 1
        pending_converter["automation_failure_counted"] = True
        logging.critical(
            "AUTOMATED CONVERTER lots completed but final baseline did not "
            "reconcile. Strategy remains paused."
        )
        return False

    client.audit.automated_converter_completions += 1
    return True


def service_pending_converter(
    client: RITClient,
    state: MarketState,
) -> bool:
    """Return True while new strategy trades must remain paused."""
    global pending_converter, pending_converter_last_reminder
    global pending_converter_pnl

    if pending_converter is None:
        return False

    baseline = pending_converter["baseline_positions"]
    action = str(pending_converter["converter_action"])
    converted, remaining, progress_expected, components = converter_progress(
        state,
        pending_converter,
    )
    current_pnl = simulator_pnl_from_audit(client.audit)
    no_converter_estimate = unconverted_liquidation_estimate(
        state,
        pending_converter,
    )
    pending_converter["latest_no_converter_liquidation_estimate_cad"] = (
        no_converter_estimate
    )
    pending_converter["latest_no_converter_minus_converter_cad"] = (
        no_converter_estimate
        - pending_converter["expected_converter_route_pnl_cad"]
        if (
            no_converter_estimate is not None
            and pending_converter.get("expected_converter_route_pnl_cad")
            is not None
        )
        else None
    )

    equity_complete = all(
        int(state.positions[ticker]) == int(baseline[ticker])
        for ticker in (BULL, BEAR, RITC)
    )

    if equity_complete:
        tender_id = int(pending_converter["tender_id"])
        execution_mode = str(
            pending_converter.get("execution_mode", "MANUAL")
        ).upper()
        elapsed = time.monotonic() - float(
            pending_converter["started_monotonic"]
        )
        logging.warning(
            "%s CONVERTER POSITIONS COMPLETE for tender #%d. "
            "Waiting for simulator P&L reconciliation.",
            execution_mode,
            tender_id,
        )
        completion_record = {
            "tender_id": tender_id,
            "execution_mode": execution_mode,
            "quantity": int(pending_converter["quantity"]),
            "expected_pnl_cad": pending_converter[
                "expected_converter_route_pnl_cad"
            ],
            # V12 used pnl_at_prompt_cad here, which is sampled only after
            # acceptance and market hedging.  V13 uses the true campaign
            # baseline captured immediately before the tender POST.
            "pnl_at_prompt_cad": pending_converter.get(
                "pnl_before_accept_cad"
            ),
            "pnl_before_accept_cad": pending_converter.get(
                "pnl_before_accept_cad"
            ),
            "pnl_at_converter_start_cad": pending_converter.get(
                "pnl_at_prompt_cad"
            ),
            "started_monotonic": time.monotonic(),
            "campaign_started_monotonic": pending_converter.get(
                "campaign_started_monotonic"
            ),
            "converter_elapsed_seconds": elapsed,
            "converter_action": pending_converter.get("converter_action"),
            "baseline_positions": baseline,
            "completion_positions": {
                ticker: state.positions[ticker]
                for ticker in (BULL, BEAR, RITC, USD, CAD)
            },
            "last_no_converter_liquidation_estimate_cad":
                no_converter_estimate,
            "last_no_converter_minus_expected_converter_pnl_cad":
                pending_converter.get("latest_no_converter_minus_converter_cad"),
            "preconversion_fx_lock": pending_converter.get(
                "preconversion_fx_lock"
            ),
        }
        client.audit.action(
            state=state,
            event=f"{execution_mode}_CONVERTER_COMPLETE",
            module="TENDER",
            tender_id=tender_id,
            requested_quantity=pending_converter["quantity"],
            filled_quantity=pending_converter["quantity"],
            expected_pnl_cad=pending_converter[
                "expected_converter_route_pnl_cad"
            ],
            score_cad="",
            status="POSITIONS_VERIFIED_PNL_PENDING",
            message=(
                "Converter completion was verified from the exact equal-lot "
                "position reset. A separate reconciliation event will record "
                "the delayed simulator P&L change."
            ),
            details={
                "elapsed_seconds": elapsed,
                "baseline_positions": baseline,
                "actual_positions": {
                    ticker: state.positions[ticker]
                    for ticker in (BULL, BEAR, RITC, USD, CAD)
                },
                "pnl_at_prompt_cad": pending_converter["pnl_at_prompt_cad"],
                "pnl_visible_at_position_completion_cad": current_pnl,
                "last_no_converter_liquidation_estimate_cad": no_converter_estimate,
                "last_no_converter_minus_expected_converter_pnl_cad":
                    pending_converter.get(
                        "latest_no_converter_minus_converter_cad"
                    ),
                "counterfactual_warning": (
                    "Estimate uses decision-time entry economics and current "
                    "executable exit quotes; it is not a second live portfolio."
                ),
                "converter_use_observation": (
                    "INFERRED_FROM_EQUAL_LOT_POSITION_RESET"
                ),
                "preconversion_fx_lock": pending_converter.get(
                    "preconversion_fx_lock"
                ),
            },
        )
        if execution_mode == "MANUAL":
            client.audit.manual_converter_completions += 1
        pending_converter_pnl = completion_record
        if active_dashboard is not None:
            active_dashboard.clear_converter_alert()
            active_dashboard.push_event(
                "INFO",
                f"Converter positions completed for tender #{tender_id}; "
                "waiting for P&L refresh.",
            )
        pre_reconciliation_usd = int(state.positions.get(USD, 0))
        pending_converter = None
        hedge_fx_to_target(
            client,
            state,
            execution_id=f"converter-{tender_id}-post-fx",
            force=True,
        )
        reconciled_state = load_state(client)
        client.set_state_context(reconciled_state)
        final_usd = int(reconciled_state.positions.get(USD, 0))
        client.audit.action(
            state=reconciled_state,
            event="POSTCONVERSION_FX_RECONCILIATION",
            module="FX",
            tender_id=tender_id,
            ticker=USD,
            action=(
                "BUY"
                if pre_reconciliation_usd < 0
                else ("SELL" if pre_reconciliation_usd > 0 else "NONE")
            ),
            requested_quantity=abs(pre_reconciliation_usd),
            filled_quantity=(
                abs(pre_reconciliation_usd) if final_usd == 0 else ""
            ),
            status="FLAT" if final_usd == 0 else "RESIDUAL_USD",
            message=(
                "Converter route finished with USD fully reconciled."
                if final_usd == 0
                else f"Converter route left USD {final_usd:+,}; review required."
            ),
            details={
                "usd_before_reconciliation": pre_reconciliation_usd,
                "usd_after_reconciliation": final_usd,
            },
        )
        log_tender_campaign_pnl(
            client,
            reconciled_state,
            tender_id=tender_id,
            quantity=int(completion_record["quantity"]),
            expected_pnl_cad=completion_record.get("expected_pnl_cad"),
            pnl_before_accept_cad=completion_record.get(
                "pnl_before_accept_cad"
            ),
            accepted_monotonic=float(
                completion_record.get("campaign_started_monotonic")
                or completion_record["started_monotonic"]
            ),
            route="TENDER_MIXED_CONVERTER",
            status=("FX_FLAT" if final_usd == 0 else "RESIDUAL_USD"),
        )
        return False

    pending_converter["remaining_quantity"] = remaining
    pending_converter["remaining_uses"] = int(
        math.ceil(remaining / CONVERTER_LOT)
    )
    if active_dashboard is not None:
        active_dashboard.set_converter_alert(pending_converter)

    if not progress_expected:
        signature = tuple(
            int(state.positions[ticker])
            for ticker in (BULL, BEAR, RITC)
        )
        if signature != pending_converter.get("last_unexpected_signature"):
            client.audit.action(
                state=state,
                event="MANUAL_CONVERTER_UNEXPECTED_POSITION",
                module="TENDER",
                tender_id=pending_converter["tender_id"],
                status="POSITION_PATTERN_MISMATCH",
                message=(
                    "Position changes do not match equal 10,000-share "
                    "converter lots. Strategy remains paused."
                ),
                details={
                    "conversion_components": components,
                    "actual_positions": {
                        ticker: state.positions[ticker]
                        for ticker in (BULL, BEAR, RITC)
                    },
                },
            )
            pending_converter["last_unexpected_signature"] = signature

    if pending_converter.get("last_snapshot_tick") != state.tick:
        pnl_at_prompt = pending_converter.get("pnl_at_prompt_cad")
        client.audit.action(
            state=state,
            event="MANUAL_CONVERTER_WAITING",
            module="TENDER",
            tender_id=pending_converter["tender_id"],
            requested_quantity=pending_converter["quantity"],
            filled_quantity=converted,
            expected_pnl_cad=pending_converter[
                "expected_converter_route_pnl_cad"
            ],
            score_cad=(
                no_converter_estimate
                if no_converter_estimate is not None
                else ""
            ),
            coverage=(
                converted / pending_converter["quantity"]
                if pending_converter["quantity"]
                else 0.0
            ),
            status=(
                "NO_CONVERSION_DETECTED"
                if converted == 0
                else "PARTIAL_CONVERSION_DETECTED"
            ),
            message=(
                "score_cad is estimated P&L if the unconverted package were "
                "liquidated at current executable quotes."
            ),
            details={
                "elapsed_seconds": time.monotonic()
                - pending_converter["started_monotonic"],
                "remaining_quantity": remaining,
                "conversion_components": components,
                "progress_pattern_expected": progress_expected,
                "current_positions": {
                    ticker: state.positions[ticker]
                    for ticker in (BULL, BEAR, RITC, USD, CAD)
                },
                "pnl_at_prompt_cad": pnl_at_prompt,
                "current_simulator_pnl_cad": current_pnl,
                "simulator_pnl_change_while_waiting_cad": (
                    current_pnl - pnl_at_prompt
                    if current_pnl is not None and pnl_at_prompt is not None
                    else None
                ),
                "estimated_no_converter_liquidation_pnl_cad": no_converter_estimate,
                "no_converter_minus_expected_converter_pnl_cad":
                    pending_converter[
                        "latest_no_converter_minus_converter_cad"
                    ],
                "counterfactual_warning": (
                    "Estimate uses decision-time entry economics and current "
                    "visible-depth exit VWAPs; actual fills could differ. "
                    "It becomes unavailable after a partial conversion."
                ),
            },
        )
        pending_converter["last_snapshot_tick"] = state.tick

    now = time.monotonic()
    if now - pending_converter_last_reminder >= 1.0:
        execution_mode = str(
            pending_converter.get("execution_mode", "MANUAL")
        ).upper()
        logging.critical(
            "\a%s CONVERTER PENDING: %s approximately %d RITC remaining "
            "for tender #%d. New strategy trades are PAUSED.",
            execution_mode,
            action,
            remaining,
            int(pending_converter["tender_id"]),
        )
        pending_converter_last_reminder = now

    return True


def service_pending_converter_pnl(
    client: RITClient,
    state: MarketState,
) -> bool:
    """Reconcile delayed simulator P&L after positions have reset.

    Returns True only when new entries should remain paused.
    """
    global pending_converter_pnl

    record = pending_converter_pnl
    if record is None:
        return False

    current_pnl = simulator_pnl_from_audit(client.audit)
    baseline_pnl = record.get("pnl_at_prompt_cad")
    elapsed = time.monotonic() - float(record["started_monotonic"])
    pnl_changed = (
        current_pnl is not None
        and baseline_pnl is not None
        and abs(current_pnl - baseline_pnl)
        >= CONVERTER_PNL_MIN_CHANGE_CAD
    )

    if pnl_changed:
        actual_change = current_pnl - baseline_pnl
        expected_pnl = record.get("expected_pnl_cad")
        client.audit.action(
            state=state,
            event="CONVERTER_PNL_RECONCILIATION",
            module="TENDER",
            tender_id=record["tender_id"],
            requested_quantity=record["quantity"],
            filled_quantity=record["quantity"],
            expected_pnl_cad=expected_pnl,
            score_cad=actual_change,
            status="RECONCILED",
            message=(
                "score_cad is the simulator account P&L change from "
                "immediately before tender acceptance through the delayed "
                "post-converter refresh."
            ),
            details={
                **record,
                "pnl_after_refresh_cad": current_pnl,
                "actual_pnl_change_cad": actual_change,
                "forecast_error_cad": (
                    actual_change - expected_pnl
                    if expected_pnl is not None
                    else None
                ),
                "pnl_refresh_elapsed_seconds": elapsed,
            },
        )
        client.audit.converter_pnl_reconciliations += 1
        logging.warning(
            "CONVERTER P&L RECONCILED for tender #%d: actual change CAD %.2f "
            "versus expected CAD %.2f.",
            int(record["tender_id"]),
            actual_change,
            float(expected_pnl or 0.0),
        )
        if active_dashboard is not None:
            active_dashboard.push_event(
                "INFO",
                f"Tender #{record['tender_id']} converter P&L reconciled: "
                f"CAD {actual_change:,.2f}.",
            )
        pending_converter_pnl = None
        return False

    if elapsed < CONVERTER_PNL_RECONCILIATION_TIMEOUT_SECONDS:
        return PAUSE_FOR_CONVERTER_PNL_RECONCILIATION

    client.audit.action(
        state=state,
        event="CONVERTER_PNL_RECONCILIATION",
        module="TENDER",
        tender_id=record["tender_id"],
        requested_quantity=record["quantity"],
        filled_quantity=record["quantity"],
        expected_pnl_cad=record.get("expected_pnl_cad"),
        score_cad="",
        status="TIMEOUT_NO_PNL_CHANGE_DETECTED",
        message=(
            "Positions were verified, but the simulator P&L did not change "
            "before the reconciliation timeout. pnl.csv remains authoritative."
        ),
        details={
            **record,
            "latest_simulator_pnl_cad": current_pnl,
            "pnl_refresh_elapsed_seconds": elapsed,
        },
    )
    client.audit.converter_pnl_reconciliation_timeouts += 1
    logging.warning(
        "Converter P&L reconciliation timed out for tender #%d; resuming. "
        "Use pnl.csv/final simulator P&L for the run result.",
        int(record["tender_id"]),
    )
    if active_dashboard is not None:
        active_dashboard.push_event(
            "WARNING",
            f"Tender #{record['tender_id']} P&L refresh timed out; "
            "positions were verified and trading resumed.",
        )
    pending_converter_pnl = None
    return False


def log_unresolved_converter_pnl(
    client: RITClient,
    state: Optional[MarketState],
) -> None:
    """Log a converter attribution that remains pending when the run ends."""
    global pending_converter_pnl

    record = pending_converter_pnl
    if record is None:
        return

    current_pnl = simulator_pnl_from_audit(client.audit)
    baseline_pnl = record.get("pnl_at_prompt_cad")
    actual_change = (
        current_pnl - baseline_pnl
        if current_pnl is not None and baseline_pnl is not None
        else None
    )
    client.audit.action(
        state=state,
        event="CONVERTER_PNL_RECONCILIATION",
        module="TENDER",
        tender_id=record["tender_id"],
        requested_quantity=record["quantity"],
        filled_quantity=record["quantity"],
        expected_pnl_cad=record.get("expected_pnl_cad"),
        score_cad=actual_change if actual_change is not None else "",
        status="RUN_ENDED_DURING_PNL_REFRESH",
        message=(
            "Converter positions were verified, but the run ended before a "
            "normal delayed-P&L reconciliation completed."
        ),
        details={
            **record,
            "latest_simulator_pnl_cad": current_pnl,
            "latest_pnl_change_cad": actual_change,
        },
    )
    pending_converter_pnl = None


def log_unresolved_pending_converter(
    client: RITClient,
    state: Optional[MarketState],
    reason: str,
) -> None:
    if pending_converter is None or pending_converter.get("unresolved_logged"):
        return

    pending_converter["unresolved_logged"] = True
    execution_mode = str(
        pending_converter.get("execution_mode", "MANUAL")
    ).upper()
    if execution_mode == "MANUAL":
        client.audit.manual_converter_unresolved += 1
    elif not pending_converter.get("automation_failure_counted"):
        client.audit.automated_converter_failures += 1
        pending_converter["automation_failure_counted"] = True
    estimate = (
        unconverted_liquidation_estimate(state, pending_converter)
        if state is not None
        else None
    )
    client.audit.action(
        state=state,
        event=f"{execution_mode}_CONVERTER_NOT_COMPLETED",
        module="TENDER",
        tender_id=pending_converter["tender_id"],
        requested_quantity=pending_converter["quantity"],
        filled_quantity=(
            pending_converter["quantity"]
            - pending_converter["remaining_quantity"]
        ),
        expected_pnl_cad=pending_converter[
            "expected_converter_route_pnl_cad"
        ],
        score_cad=estimate if estimate is not None else "",
        status="UNRESOLVED",
        message=reason,
        details={
            **pending_converter,
            "final_positions": (
                state.positions if state is not None else None
            ),
            "estimated_no_converter_liquidation_pnl_cad": estimate,
            "no_converter_minus_expected_converter_pnl_cad": (
                estimate
                - pending_converter["expected_converter_route_pnl_cad"]
                if (
                    estimate is not None
                    and pending_converter.get(
                        "expected_converter_route_pnl_cad"
                    ) is not None
                )
                else None
            ),
        },
    )
    logging.critical(
        "%s CONVERTER WAS NOT COMPLETED for tender #%d: %s",
        execution_mode,
        int(pending_converter["tender_id"]),
        reason,
    )
    if active_dashboard is not None:
        active_dashboard.push_event(
            "CRITICAL",
            f"Converter unresolved for tender #{pending_converter['tender_id']}: {reason}",
        )


def execute_mixed_converter_hedge(
    client: RITClient,
    state: MarketState,
    tender: dict,
    candidate: Candidate,
    accepted_quantity: int,
    baseline_positions: Dict[str, int],
    *,
    pnl_before_accept_cad: Optional[float],
    campaign_started_monotonic: float,
) -> None:
    """Execute market legs, then automate and verify converter lots."""
    tender_id = int(tender["tender_id"])
    tender_action = str(tender["action"]).upper()
    unwind_action = "SELL" if tender_action == "BUY" else "BUY"
    basket_action = "SELL" if tender_action == "BUY" else "BUY"

    planned_converter = min(
        candidate.converter_quantity,
        (accepted_quantity // CONVERTER_LOT) * CONVERTER_LOT,
    )
    planned_direct = accepted_quantity - planned_converter

    direct_filled = 0
    if planned_direct > 0:
        direct_filled = submit_in_chunks(
            client,
            RITC,
            unwind_action,
            planned_direct,
        )
        if direct_filled < planned_direct:
            logging.critical(
                "Mixed tender direct remainder filled %d/%d. Retrying once.",
                direct_filled,
                planned_direct,
            )
            direct_filled += submit_in_chunks(
                client,
                RITC,
                unwind_action,
                planned_direct - direct_filled,
            )

    client.audit.action(
        state=client.context_state,
        event="MIXED_TENDER_DIRECT_REMAINDER",
        module="TENDER",
        tender_id=tender_id,
        ticker=RITC,
        action=unwind_action,
        requested_quantity=planned_direct,
        filled_quantity=direct_filled,
        coverage=(direct_filled / planned_direct if planned_direct else 1.0),
        status=(
            "EXPECTED" if direct_filled == planned_direct else "PARTIAL_FILL"
        ),
        message="Direct portion of the mixed tender unwind.",
    )

    fresh_state, _fresh_metrics = load_direct_preflight_state(client)
    client.set_state_context(fresh_state)
    basket_matched = execute_matched_legs(
        client,
        fresh_state,
        [
            (BULL, basket_action, planned_converter),
            (BEAR, basket_action, planned_converter),
        ],
    ) if planned_converter > 0 else 0

    actual_converter = (
        basket_matched // CONVERTER_LOT
    ) * CONVERTER_LOT

    client.audit.action(
        state=client.context_state,
        event="MIXED_TENDER_BASKET_HEDGE",
        module="TENDER",
        tender_id=tender_id,
        requested_quantity=planned_converter,
        filled_quantity=basket_matched,
        coverage=(
            basket_matched / planned_converter if planned_converter else 1.0
        ),
        status=(
            "EXPECTED" if basket_matched == planned_converter else "PARTIAL_FILL"
        ),
        message=(
            f"Complete converter quantity after lot rounding: "
            f"{actual_converter:,}."
        ),
        details={
            "basket_action": basket_action,
            "converter_lot": CONVERTER_LOT,
            "actual_converter_quantity": actual_converter,
        },
    )

    # Converter accepts only complete lots. Roll back any unmatched fraction
    # of a lot and directly unwind the corresponding RITC instead.
    basket_excess = basket_matched - actual_converter
    if basket_excess > 0:
        submit_in_chunks(client, BULL, opposite(basket_action), basket_excess)
        submit_in_chunks(client, BEAR, opposite(basket_action), basket_excess)

    direct_shortfall = accepted_quantity - direct_filled - actual_converter
    if direct_shortfall > 0:
        logging.critical(
            "Converter hedge shortfall: directly unwinding %d additional RITC.",
            direct_shortfall,
        )
        fallback_filled = submit_in_chunks(
            client,
            RITC,
            unwind_action,
            direct_shortfall,
        )
        if fallback_filled < direct_shortfall:
            logging.critical(
                "UNRESOLVED TENDER RISK: direct fallback filled %d/%d RITC.",
                fallback_filled,
                direct_shortfall,
            )

    post_hedge_state = load_state(client)
    client.set_state_context(post_hedge_state)
    activate_pending_converter(
        client,
        post_hedge_state,
        tender,
        candidate,
        baseline_positions,
        actual_converter,
        pnl_before_accept_cad=pnl_before_accept_cad,
        campaign_started_monotonic=campaign_started_monotonic,
    )
    if actual_converter > 0 and ENABLE_AUTOMATED_CONVERTER:
        execute_automated_pending_converter(client)
    elif actual_converter == 0:
        hedge_fx_to_target(client)


def stock_positions_match(
    observed: Dict[str, int],
    expected: Dict[str, int],
) -> bool:
    return all(
        int(observed.get(ticker, 0)) == int(expected.get(ticker, 0))
        for ticker in (BULL, BEAR, RITC)
    )


def wait_for_tender_settlement(
    client: RITClient,
    pending: PendingTenderExecution,
    *,
    timeout_seconds: float,
) -> Optional[MarketState]:
    """Wait for the tender position to appear and remain stable."""
    deadline = time.monotonic() + max(0.0, timeout_seconds)
    last_signature: Optional[Tuple[int, ...]] = None
    stable_reads = 0

    while time.monotonic() <= deadline:
        observed = client.positions()
        pending.last_observed_positions = dict(observed)
        signature = tuple(
            int(observed.get(ticker, 0))
            for ticker in (BULL, BEAR, RITC, USD, CAD)
        )
        if int(observed.get(RITC, 0)) == pending.expected_ritc_position:
            stable_reads = stable_reads + 1 if signature == last_signature else 1
            pending.stable_reads = stable_reads
            if stable_reads >= TENDER_SETTLEMENT_STABLE_READS:
                settled_state = load_state(client)
                if (
                    int(settled_state.positions.get(RITC, 0))
                    == pending.expected_ritc_position
                ):
                    return settled_state
                stable_reads = 0
        else:
            stable_reads = 0
            pending.stable_reads = 0
        last_signature = signature
        if time.monotonic() < deadline:
            time.sleep(TENDER_SETTLEMENT_POLL_INTERVAL_SECONDS)
    return None


def wait_for_expected_stock_positions(
    client: RITClient,
    expected: Dict[str, int],
    *,
    timeout_seconds: float,
) -> Tuple[bool, Dict[str, int]]:
    deadline = time.monotonic() + max(0.0, timeout_seconds)
    observed: Dict[str, int] = {}
    while time.monotonic() <= deadline:
        observed = client.positions()
        if stock_positions_match(observed, expected):
            return True, observed
        if time.monotonic() < deadline:
            time.sleep(TENDER_SETTLEMENT_POLL_INTERVAL_SECONDS)
    return False, observed


def revalue_accepted_tender_candidate(
    state: MarketState,
    tender: dict,
    original: Candidate,
) -> Candidate:
    """Choose the best feasible exit after the accepted tender is visible."""
    direct = tender_direct_candidate(state, tender)
    basket = tender_basket_candidate(state, tender)
    hybrid = tender_hybrid_candidate(
        state,
        tender,
        tender_already_settled=True,
    )
    mixed = mixed_converter_candidate(
        state,
        tender,
        tender_already_settled=True,
    )
    choices: List[Candidate] = []
    if (
        ENABLE_TENDER_DIRECT_UNWIND
        and direct is not None
        and direct.kind == "TENDER_DIRECT"
        and accepted_tender_route_risk_allowed(state, direct)
    ):
        choices.append(direct)
    if (
        ENABLE_TENDER_BASKET_HEDGE
        and basket is not None
        and accepted_tender_route_risk_allowed(state, basket)
    ):
        choices.append(basket)
    if (
        ENABLE_TENDER_HYBRID_ROUTE
        and hybrid is not None
        and accepted_tender_route_risk_allowed(state, hybrid)
    ):
        choices.append(hybrid)
    if (
        ENABLE_MIXED_CONVERTER_ROUTE
        and ENABLE_AUTOMATED_CONVERTER
        and mixed is not None
        and automated_converter_action_allowed(mixed.converter_action)
        and accepted_tender_route_risk_allowed(state, mixed)
    ):
        choices.append(mixed)

    # Once accepted, rejection is no longer possible. If refreshed depth is
    # temporarily incomplete, retain the pre-acceptance plan instead of
    # pretending the exposure does not exist.
    return max(choices, key=lambda item: item.score_cad) if choices else original


def execute_hybrid_tender_hedge(
    client: RITClient,
    state: MarketState,
    tender: dict,
    candidate: Candidate,
    accepted_quantity: int,
) -> Candidate:
    """Execute direct first, then basket-hedge any planned or fill residual."""
    tender_id = int(tender["tender_id"])
    tender_action = str(tender["action"]).upper()
    unwind_action = "SELL" if tender_action == "BUY" else "BUY"
    basket_action = "SELL" if tender_action == "BUY" else "BUY"
    planned_direct = min(
        accepted_quantity,
        max(0, int(candidate.direct_unwind_quantity)),
    )
    planned_basket = accepted_quantity - planned_direct

    direct_filled = (
        submit_in_chunks(client, RITC, unwind_action, planned_direct)
        if planned_direct > 0 else 0
    )
    basket_target = planned_basket + max(0, planned_direct - direct_filled)
    fresh_state, _metrics = load_direct_preflight_state(client)
    client.set_state_context(fresh_state)
    basket_matched = (
        execute_matched_legs(
            client,
            fresh_state,
            [
                (BULL, basket_action, basket_target),
                (BEAR, basket_action, basket_target),
            ],
        )
        if basket_target > 0 else 0
    )
    unresolved = max(
        0,
        accepted_quantity - direct_filled - basket_matched,
    )
    fallback_direct = 0
    if unresolved > 0:
        logging.critical(
            "Hybrid tender basket filled %d/%d; directly unwinding %d RITC.",
            basket_matched,
            basket_target,
            unresolved,
        )
        fallback_direct = submit_in_chunks(
            client,
            RITC,
            unwind_action,
            unresolved,
        )
    remaining = max(
        0,
        accepted_quantity - direct_filled - basket_matched - fallback_direct,
    )
    actual_direct = direct_filled + fallback_direct
    actual_legs: List[Tuple[str, str, int]] = []
    if actual_direct > 0:
        actual_legs.append((RITC, unwind_action, actual_direct))
    if basket_matched > 0:
        actual_legs.extend([
            (BULL, basket_action, basket_matched),
            (BEAR, basket_action, basket_matched),
        ])
    client.audit.action(
        state=client.context_state,
        event="TENDER_HYBRID_EXECUTION",
        module="TENDER",
        label=candidate.label,
        tender_id=tender_id,
        requested_quantity=accepted_quantity,
        filled_quantity=accepted_quantity - remaining,
        coverage=(
            (accepted_quantity - remaining) / accepted_quantity
            if accepted_quantity else 1.0
        ),
        status="EXPECTED" if remaining == 0 else "UNRESOLVED_RITC",
        message=(
            "Direct and basket quantities are actual fills after contingency."
        ),
        details={
            "planned_direct_quantity": planned_direct,
            "planned_basket_quantity": planned_basket,
            "actual_direct_quantity": actual_direct,
            "actual_basket_quantity": basket_matched,
            "remaining_unhedged_ritc": remaining,
        },
    )
    if remaining > 0:
        logging.critical(
            "UNRESOLVED HYBRID TENDER RISK: %d RITC remains unhedged.",
            remaining,
        )
    return replace(
        candidate,
        legs=actual_legs,
        direct_unwind_quantity=actual_direct,
        basket_hedge_quantity=basket_matched,
        coverage=(
            (accepted_quantity - remaining) / accepted_quantity
            if accepted_quantity else 1.0
        ),
    )


def execute_settled_tender_candidate(
    client: RITClient,
    settled_state: MarketState,
    pending: PendingTenderExecution,
) -> bool:
    """Execute a tender route only after its position is observable."""
    global pending_tender_execution

    tender = pending.tender
    tender_id = int(tender["tender_id"])
    tender_action = str(tender["action"]).upper()
    accepted_quantity = int(round(float(tender["quantity"])))
    candidate = revalue_accepted_tender_candidate(
        settled_state,
        tender,
        pending.candidate,
    )
    client.set_state_context(settled_state)
    client.audit.action(
        state=settled_state,
        event="TENDER_POST_SETTLEMENT_REVALUATION",
        module="TENDER",
        label=candidate.label,
        tender_id=tender_id,
        average_edge_cad=candidate.average_edge_cad,
        expected_pnl_cad=candidate.total_pnl_cad,
        score_cad=candidate.score_cad,
        status=(
            "ROUTE_UNCHANGED"
            if candidate.kind == pending.candidate.kind
            else "ROUTE_CHANGED"
        ),
        details={
            "original_route": pending.candidate.kind,
            "refreshed_route": candidate.kind,
            "settlement_latency_seconds": round(
                time.monotonic() - pending.accepted_monotonic,
                4,
            ),
        },
    )

    if candidate.requires_converter and not client.converter_preflight(
        candidate.converter_action
    ):
        logging.critical(
            "Tender #%d settled, but refreshed converter preflight failed; "
            "using the original non-converter route if available.",
            tender_id,
        )
        direct = tender_direct_candidate(settled_state, tender)
        basket = tender_basket_candidate(settled_state, tender)
        fallbacks = [
            item for item in (direct, basket)
            if item is not None
            and accepted_tender_route_risk_allowed(settled_state, item)
        ]
        if fallbacks:
            candidate = max(fallbacks, key=lambda item: item.score_cad)
        else:
            emergency_action = "SELL" if tender_action == "BUY" else "BUY"
            candidate = Candidate(
                kind="TENDER_DIRECT",
                label="Emergency direct RITC unwind after converter failure",
                quantity=accepted_quantity,
                total_pnl_cad=-1.0e12,
                average_edge_cad=-1.0e9,
                score_cad=-1.0e12,
                legs=[(RITC, emergency_action, accepted_quantity)],
                note=(
                    "Tender was already accepted and no refreshed converter "
                    "or complete book route was available; reduce exposure "
                    "with direct RITC market orders."
                ),
            )

    if candidate.kind == "TENDER_MIXED_CONVERTER":
        client.audit.mixed_converter_tenders_started += 1
        pending_tender_execution = None
        execute_mixed_converter_hedge(
            client,
            settled_state,
            tender,
            candidate,
            accepted_quantity,
            pending.baseline_positions,
            pnl_before_accept_cad=pending.pnl_before_accept_cad,
            campaign_started_monotonic=pending.accepted_monotonic,
        )
        return True

    if candidate.kind == "TENDER_HYBRID":
        candidate = execute_hybrid_tender_hedge(
            client,
            settled_state,
            tender,
            candidate,
            accepted_quantity,
        )
    elif candidate.kind == "TENDER_DIRECT":
        unwind_action = "SELL" if tender_action == "BUY" else "BUY"
        filled = submit_in_chunks(client, RITC, unwind_action, accepted_quantity)
        residual = max(0, accepted_quantity - filled)
        basket_matched = 0
        if residual:
            logging.critical(
                "Direct tender unwind left %d RITC; using basket contingency.",
                residual,
            )
            basket_action = "SELL" if tender_action == "BUY" else "BUY"
            fresh_state, _ = load_direct_preflight_state(client)
            client.set_state_context(fresh_state)
            basket_matched = execute_matched_legs(
                client,
                fresh_state,
                [(BULL, basket_action, residual), (BEAR, basket_action, residual)],
            )
        unresolved = max(0, accepted_quantity - filled - basket_matched)
        retry_filled = (
            submit_in_chunks(client, RITC, unwind_action, unresolved)
            if unresolved > 0 else 0
        )
        actual_direct = filled + retry_filled
        actual_legs: List[Tuple[str, str, int]] = []
        if actual_direct > 0:
            actual_legs.append((RITC, unwind_action, actual_direct))
        if basket_matched > 0:
            actual_legs.extend([
                (BULL, basket_action, basket_matched),
                (BEAR, basket_action, basket_matched),
            ])
        candidate = replace(
            candidate,
            legs=actual_legs,
            direct_unwind_quantity=actual_direct,
            basket_hedge_quantity=basket_matched,
            coverage=(
                (actual_direct + basket_matched) / accepted_quantity
                if accepted_quantity else 1.0
            ),
        )
    else:
        fresh_state, _ = load_direct_preflight_state(client)
        client.set_state_context(fresh_state)
        execution_legs = [
            (ticker, action, min(quantity, accepted_quantity))
            for ticker, action, quantity in candidate.legs
        ]
        matched = execute_matched_legs(client, fresh_state, execution_legs)
        residual = max(0, accepted_quantity - matched)
        direct_fallback = 0
        if residual:
            unwind_action = "SELL" if tender_action == "BUY" else "BUY"
            logging.critical(
                "Basket tender hedge covered %d/%d; directly unwinding %d.",
                matched,
                accepted_quantity,
                residual,
            )
            direct_fallback = submit_in_chunks(
                client,
                RITC,
                unwind_action,
                residual,
            )
        basket_action = "SELL" if tender_action == "BUY" else "BUY"
        actual_legs = []
        if direct_fallback > 0:
            actual_legs.append((RITC, unwind_action, direct_fallback))
        if matched > 0:
            actual_legs.extend([
                (BULL, basket_action, matched),
                (BEAR, basket_action, matched),
            ])
        candidate = replace(
            candidate,
            legs=actual_legs,
            direct_unwind_quantity=direct_fallback,
            basket_hedge_quantity=matched,
            coverage=(
                (direct_fallback + matched) / accepted_quantity
                if accepted_quantity else 1.0
            ),
        )

    planned_deltas = {RITC: signed_delta(tender_action, accepted_quantity)}
    for ticker, action, quantity in candidate.legs:
        planned_deltas[ticker] = (
            planned_deltas.get(ticker, 0)
            + signed_delta(action, min(quantity, accepted_quantity))
        )
    expected = positions_after(pending.baseline_positions, planned_deltas)
    pending.phase = "POST_HEDGE_RECONCILIATION"
    pending.expected_stock_positions = {
        ticker: int(expected.get(ticker, 0))
        for ticker in (BULL, BEAR, RITC)
    }
    reconciled, observed = wait_for_expected_stock_positions(
        client,
        pending.expected_stock_positions,
        timeout_seconds=TENDER_POST_HEDGE_RECONCILIATION_TIMEOUT_SECONDS,
    )
    if reconciled:
        client.audit.action(
            state=client.context_state,
            event="TENDER_POST_HEDGE_RECONCILIATION",
            module="TENDER",
            tender_id=tender_id,
            status="EXPECTED",
            message="Tender and hedge stock positions reconciled before FX.",
            details={"expected": pending.expected_stock_positions, "observed": observed},
        )
        pending_tender_execution = None
        hedge_fx_to_target(client, force=True)
        completed_state = load_state(client)
        client.set_state_context(completed_state)
        log_tender_campaign_pnl(
            client,
            completed_state,
            tender_id=tender_id,
            quantity=accepted_quantity,
            expected_pnl_cad=candidate.total_pnl_cad,
            pnl_before_accept_cad=pending.pnl_before_accept_cad,
            accepted_monotonic=pending.accepted_monotonic,
            route=candidate.kind,
            status="POSITIONS_RECONCILED",
        )
    else:
        client.audit.tender_post_hedge_mismatches += 1
        logging.critical(
            "TENDER POSITION MISMATCH #%d: expected=%s observed=%s. "
            "New strategy orders and FX remain locked.",
            tender_id,
            pending.expected_stock_positions,
            observed,
        )
        client.audit.action(
            state=client.context_state,
            event="TENDER_POST_HEDGE_RECONCILIATION",
            module="TENDER",
            tender_id=tender_id,
            status="POSITION_MISMATCH",
            message="New strategy orders and FX locked pending reconciliation.",
            details={"expected": pending.expected_stock_positions, "observed": observed},
        )
    return True


def service_pending_tender_execution(client: RITClient) -> bool:
    """Advance one accepted tender campaign; block unrelated orders."""
    global pending_tender_execution
    pending = pending_tender_execution
    if pending is None:
        return False

    if pending.phase == "POST_HEDGE_RECONCILIATION":
        reconciled, observed = wait_for_expected_stock_positions(
            client,
            pending.expected_stock_positions,
            timeout_seconds=TENDER_SETTLEMENT_POLL_INTERVAL_SECONDS,
        )
        if reconciled:
            client.audit.action(
                state=client.context_state,
                event="TENDER_POST_HEDGE_RECONCILIATION",
                module="TENDER",
                tender_id=pending.tender.get("tender_id"),
                status="LATE_RECONCILIATION",
                details={"expected": pending.expected_stock_positions, "observed": observed},
            )
            pending_tender_execution = None
            hedge_fx_to_target(client, force=True)
            completed_state = load_state(client)
            client.set_state_context(completed_state)
            log_tender_campaign_pnl(
                client,
                completed_state,
                tender_id=int(pending.tender.get("tender_id", -1)),
                quantity=int(round(float(pending.tender.get("quantity", 0)))),
                expected_pnl_cad=pending.candidate.total_pnl_cad,
                pnl_before_accept_cad=pending.pnl_before_accept_cad,
                accepted_monotonic=pending.accepted_monotonic,
                route=pending.candidate.kind,
                status="LATE_POSITIONS_RECONCILED",
            )
        else:
            signature = {
                ticker: int(observed.get(ticker, 0))
                for ticker in (BULL, BEAR, RITC)
            }
            previous = {
                ticker: int(pending.last_observed_positions.get(ticker, 0))
                for ticker in (BULL, BEAR, RITC)
            }
            pending.stable_reads = (
                pending.stable_reads + 1 if signature == previous else 1
            )
            pending.last_observed_positions = dict(observed)
            if pending.stable_reads >= TENDER_SETTLEMENT_STABLE_READS:
                client.audit.action(
                    state=client.context_state,
                    event="TENDER_POST_HEDGE_RECONCILIATION",
                    module="TENDER",
                    tender_id=pending.tender.get("tender_id"),
                    status="STABLE_UNEXPECTED_RELEASED",
                    message=(
                        "Unexpected stock positions remained stable; treating "
                        "the simulator state as authoritative and releasing "
                        "the campaign lock after logging the mismatch."
                    ),
                    details={
                        "expected": pending.expected_stock_positions,
                        "observed": observed,
                        "stable_reads": pending.stable_reads,
                    },
                )
                pending_tender_execution = None
                hedge_fx_to_target(client, force=True)
                completed_state = load_state(client)
                client.set_state_context(completed_state)
                log_tender_campaign_pnl(
                    client,
                    completed_state,
                    tender_id=int(pending.tender.get("tender_id", -1)),
                    quantity=int(round(float(pending.tender.get("quantity", 0)))),
                    expected_pnl_cad=pending.candidate.total_pnl_cad,
                    pnl_before_accept_cad=pending.pnl_before_accept_cad,
                    accepted_monotonic=pending.accepted_monotonic,
                    route=pending.candidate.kind,
                    status="STABLE_UNEXPECTED_POSITIONS",
                )
        return True

    settled_state = wait_for_tender_settlement(
        client,
        pending,
        timeout_seconds=TENDER_SETTLEMENT_TIMEOUT_SECONDS,
    )
    if settled_state is None:
        client.audit.tender_settlement_timeouts += 1
        logging.critical(
            "TENDER SETTLEMENT PENDING #%s: expected RITC=%+d observed=%+d; "
            "no hedge or FX order submitted yet.",
            pending.tender.get("tender_id"),
            pending.expected_ritc_position,
            int(pending.last_observed_positions.get(RITC, 0)),
        )
        client.audit.action(
            state=client.context_state,
            event="TENDER_SETTLEMENT_WAIT",
            module="TENDER",
            tender_id=pending.tender.get("tender_id"),
            status="TIMEOUT_RETRYING",
            details={
                "expected_ritc": pending.expected_ritc_position,
                "observed_positions": pending.last_observed_positions,
            },
        )
        return True

    client.audit.tender_settlements_confirmed += 1
    client.audit.action(
        state=settled_state,
        event="TENDER_SETTLEMENT_CONFIRMED",
        module="TENDER",
        tender_id=pending.tender.get("tender_id"),
        status="STABLE",
        message="Accepted tender position confirmed before hedge execution.",
        details={
            "expected_ritc": pending.expected_ritc_position,
            "observed_positions": settled_state.positions,
            "stable_reads": pending.stable_reads,
        },
    )
    return execute_settled_tender_candidate(client, settled_state, pending)


def execute_tender_candidate(
    client: RITClient,
    state: MarketState,
    tender: dict,
    candidate: Candidate,
    converter: Optional[Candidate],
) -> bool:
    """Accept one fixed tender and start the settlement-locked campaign."""
    global pending_tender_execution
    tender_id = int(tender["tender_id"])
    tender_action = str(tender["action"]).upper()
    tender_quantity = int(round(float(tender["quantity"])))
    client.audit.action(
        state=state,
        event="TENDER_DECISION",
        module="TENDER",
        label=candidate.label,
        tender_id=tender_id,
        action=tender_action,
        requested_quantity=tender_quantity,
        price=tender.get("price"),
        average_edge_cad=candidate.average_edge_cad,
        expected_pnl_cad=candidate.total_pnl_cad,
        score_cad=candidate.score_cad,
        coverage=candidate.coverage,
        status="WOULD_ACCEPT" if not LIVE_TRADING else "ACCEPTING",
        details={
            "route": candidate.kind,
            "note": candidate.note,
            "capacity_release_action": candidate.capacity_release_action,
            "capacity_release_lots": candidate.capacity_release_lots,
        },
    )
    logging.warning(
        "TENDER #%d: %s | q=%d | edge=%.4f | expected P&L=CAD %.2f | score=CAD %.2f",
        tender_id,
        candidate.label,
        tender_quantity,
        candidate.average_edge_cad,
        candidate.total_pnl_cad,
        candidate.score_cad,
    )
    if not LIVE_TRADING:
        return False
    if pending_tender_execution is not None:
        logging.error("Tender #%d not accepted: another tender is still settling", tender_id)
        return False
    baseline = dict(state.positions)
    pnl_before_accept = capture_simulator_pnl(client)
    if not client.accept_fixed_tender(tender):
        logging.error("Tender #%d was not accepted", tender_id)
        return False
    client.audit.tenders_accepted += 1
    pending_tender_execution = PendingTenderExecution(
        tender=dict(tender),
        candidate=candidate,
        converter=converter,
        baseline_positions=baseline,
        expected_ritc_position=(
            int(baseline.get(RITC, 0))
            + signed_delta(tender_action, tender_quantity)
        ),
        accepted_monotonic=time.monotonic(),
        accepted_tick=state.tick,
        pnl_before_accept_cad=pnl_before_accept,
    )
    client.audit.action(
        state=state,
        event="TENDER_ACCEPTED_AWAITING_SETTLEMENT",
        module="TENDER",
        tender_id=tender_id,
        requested_quantity=tender_quantity,
        status="CAMPAIGN_LOCKED",
        message="No hedge, FX, direct-arbitrage, or second-tender order until settlement.",
        details={
            "baseline_positions": baseline,
            "pnl_before_accept_cad": pnl_before_accept,
            "expected_ritc_position": pending_tender_execution.expected_ritc_position,
        },
    )
    return service_pending_tender_execution(client)


