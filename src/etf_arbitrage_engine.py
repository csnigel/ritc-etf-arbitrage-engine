@dataclass
class DirectConfirmationTracker:
    """Track consecutive qualifying direct-arbitrage scans."""

    direction: str = ""
    count: int = 0
    last_tick: Optional[int] = None

    def reset(self) -> None:
        self.direction = ""
        self.count = 0
        self.last_tick = None

    def observe(self, candidate: Optional[Candidate], tick: int) -> int:
        if candidate is None or not candidate.direction:
            self.reset()
            return 0

        is_consecutive = (
            candidate.direction == self.direction
            and self.last_tick is not None
            and tick > self.last_tick
        )

        if is_consecutive:
            self.count += 1
        else:
            self.direction = candidate.direction
            self.count = 1

        self.last_tick = tick
        return self.count


