    def discover_converter_assets(self) -> Dict[str, Dict[str, Any]]:
        """Discover exact case-sensitive converter tickers from GET /assets."""
        wanted = {
            "CREATE": "etfcreation",
            "REDEEM": "etfredemption",
        }
        discovered: Dict[str, Dict[str, Any]] = {}
        rows = self.assets()

        for action, normalized_ticker in wanted.items():
            matches = [
                row for row in rows
                if self._converter_key(row.get("ticker")) == normalized_ticker
            ]
            if len(matches) == 1:
                discovered[action] = dict(matches[0])

        self.converter_assets = discovered
        self.audit.action(
            state=self.context_state,
            event="CONVERTER_ASSET_DISCOVERY",
            module="CONVERTER",
            status=("READY" if len(discovered) == 2 else "INCOMPLETE"),
            message=(
                "Discovered exact converter asset tickers from GET /assets."
            ),
            details={
                "discovered": {
                    action: row.get("ticker")
                    for action, row in discovered.items()
                },
                "available_tickers": [row.get("ticker") for row in rows],
            },
        )
        return discovered

    def ensure_converter_lease(self, action: str) -> Dict[str, Any]:
        """Return a verified lease for CREATE or REDEEM."""
        action = action.upper()
        if action not in ("CREATE", "REDEEM"):
            raise ValueError(f"Unknown converter action: {action}")

        if action not in self.converter_assets:
            self.discover_converter_assets()

        asset = self.converter_assets.get(action)
        if asset is None:
            raise ApiException(
                f"GET /assets did not expose the {action} converter"
            )
        exact_ticker = str(asset.get("ticker", ""))

        for row in self.leases():
            if str(row.get("ticker", "")) == exact_ticker and row.get("id") is not None:
                self.converter_leases[action] = dict(row)
                return self.converter_leases[action]

        payload = self.request_json(
            "POST",
            "leases",
            params={"ticker": exact_ticker},
        )
        if not isinstance(payload, dict) or payload.get("id") is None:
            raise ApiException(
                f"POST /leases did not return a lease id for {exact_ticker}"
            )
        if str(payload.get("ticker", exact_ticker)) != exact_ticker:
            raise ApiException(
                "POST /leases returned a different converter ticker"
            )

        self.converter_leases[action] = dict(payload)
        self.audit.action(
            state=self.context_state,
            event="CONVERTER_LEASE_READY",
            module="CONVERTER",
            label=exact_ticker,
            status="READY",
            message=f"Converter lease {payload['id']} is ready.",
            details={"action": action, "lease": payload},
        )
        return self.converter_leases[action]

    def converter_preflight(self, action: str) -> bool:
        """Lease and verify the exact converter before tender acceptance."""
        try:
            lease = self.ensure_converter_lease(action)
        except (requests.RequestException, ApiException, ValueError) as exc:
            logging.critical("AUTOMATED CONVERTER PREFLIGHT FAILED: %s", exc)
            self.audit.action(
                state=self.context_state,
                event="CONVERTER_PREFLIGHT",
                module="CONVERTER",
                status="FAILED",
                message=str(exc),
                details={"action": action},
            )
            return False

        ready = lease.get("id") is not None
        if ready:
            logging.warning(
                "AUTOMATED CONVERTER READY: action=%s ticker=%s lease_id=%s",
                action.upper(),
                lease.get("ticker"),
                lease.get("id"),
            )
        self.audit.action(
            state=self.context_state,
            event="CONVERTER_PREFLIGHT",
            module="CONVERTER",
            status="READY" if ready else "FAILED",
            message=(
                "Automated converter is ready before tender acceptance."
                if ready else "Converter lease id is missing."
            ),
            details={
                "action": action.upper(),
                "ticker": lease.get("ticker"),
                "lease_id": lease.get("id"),
            },
        )
        return ready

    def use_converter_once(self, action: str) -> Any:
        """Submit one 10,000-share converter use through POST /leases/{id}."""
        action = action.upper()
        lease = self.ensure_converter_lease(action)
        lease_id = int(lease["id"])

        if action == "CREATE":
            params = {
                "from1": BULL,
                "quantity1": CONVERTER_LOT,
                "from2": BEAR,
                "quantity2": CONVERTER_LOT,
                "from3": USD,
                "quantity3": CONVERTER_COST_USD_PER_USE,
            }
        elif action == "REDEEM":
            params = {
                "from1": RITC,
                "quantity1": CONVERTER_LOT,
                "from2": USD,
                "quantity2": CONVERTER_COST_USD_PER_USE,
            }
        else:
            raise ValueError(f"Unknown converter action: {action}")

        return self.request_json(
            "POST",
            f"leases/{lease_id}",
            params=params,
        )

    def market_order(
        self,
        ticker: str,
        action: str,
        quantity: int,
        reference_price: Optional[float] = None,
        execution_id: str = "",
    ) -> OrderResult:
        quantity = int(quantity)
        action = action.upper()

        if quantity <= 0:
            return OrderResult(
                ticker=ticker,
                action=action,
                requested=0,
                filled=0,
                vwap=None,
                status="SKIPPED",
                reference_price=reference_price,
            )

        maximum = (
            MAX_FX_ORDER_SIZE
            if ticker in (CAD, USD)
            else MAX_EQUITY_ORDER_SIZE
        )

        if quantity > maximum:
            raise ValueError(
                f"{ticker} order size {quantity:,} exceeds maximum {maximum:,}"
            )

        self.audit.orders_requested += quantity

        if not LIVE_TRADING:
            result = OrderResult(
                ticker=ticker,
                action=action,
                requested=quantity,
                filled=quantity,
                vwap=None,
                status="DRY_RUN",
                reference_price=reference_price,
            )
        else:
            payload = self.request_json(
                "POST",
                "orders",
                params={
                    "ticker": ticker,
                    "type": "MARKET",
                    "quantity": quantity,
                    "action": action,
                },
            )

            status = str(payload.get("status", "UNKNOWN"))
            filled = int(
                round(float(payload.get("quantity_filled", 0) or 0))
            )

            vwap_raw = payload.get("vwap")
            vwap = float(vwap_raw) if vwap_raw is not None else None

            order_id_raw = payload.get("order_id")
            order_id = (
                int(order_id_raw)
                if order_id_raw is not None
                else None
            )

            result = OrderResult(
                ticker=ticker,
                action=action,
                requested=quantity,
                filled=filled,
                vwap=vwap,
                status=status,
                order_id=order_id,
                reference_price=reference_price,
                order_type="MARKET",
            )

        self.audit.orders_filled += result.filled
        self.audit.action(
            state=self.context_state,
            event="ORDER",
            module="EXECUTION",
            ticker=ticker,
            action=action,
            requested_quantity=quantity,
            filled_quantity=result.filled,
            price=(
                result.reference_price
                if result.reference_price is not None
                else ""
            ),
            vwap=result.vwap if result.vwap is not None else "",
            status=result.status,
            details={
                "order_id": result.order_id,
                "execution_id": execution_id,
                "reference_price": result.reference_price,
                "signed_adverse_price_move": (
                    (
                        result.vwap - result.reference_price
                        if action == "BUY"
                        else result.reference_price - result.vwap
                    )
                    if (
                        result.vwap is not None
                        and result.reference_price is not None
                    )
                    else None
                ),
            },
        )

        logging.info(
            "%s %s %d %s -> filled %d, vwap=%s, status=%s",
            "DRY RUN:" if not LIVE_TRADING else "ORDER:",
            action,
            quantity,
            ticker,
            result.filled,
            result.vwap,
            result.status,
        )

        return result

    def limit_order(
        self,
        ticker: str,
        action: str,
        quantity: int,
        price: float,
        *,
        reference_price: Optional[float] = None,
        execution_id: str = "",
        event: str = "PASSIVE_LIMIT_ORDER",
        module: str = "PASSIVE_ARB",
    ) -> OrderResult:
        """Submit one limit order without assuming an immediate fill."""
        quantity = int(quantity)
        action = action.upper()
        if quantity <= 0 or quantity > MAX_EQUITY_ORDER_SIZE:
            raise ValueError("Passive equity quantity is outside order limits")
        if not math.isfinite(price) or price <= 0:
            raise ValueError("Passive limit price must be positive and finite")

        self.audit.orders_requested += quantity
        if not LIVE_TRADING:
            result = OrderResult(
                ticker=ticker,
                action=action,
                requested=quantity,
                filled=0,
                vwap=None,
                status="DRY_RUN",
                reference_price=reference_price,
                order_type="LIMIT",
            )
        else:
            payload = self.request_json(
                "POST",
                "orders",
                params={
                    "ticker": ticker,
                    "type": "LIMIT",
                    "quantity": quantity,
                    "action": action,
                    "price": f"{price:.10g}",
                },
            )
            result = self.order_result_from_payload(
                ticker,
                action,
                quantity,
                payload,
                reference_price=reference_price,
            )
            result.order_type = "LIMIT"
        result.limit_price = price

        self.audit.action(
            state=self.context_state,
            event=event,
            module=module,
            ticker=ticker,
            action=action,
            requested_quantity=quantity,
            filled_quantity=result.filled,
            price=price,
            vwap=result.vwap if result.vwap is not None else "",
            status=result.status,
            details={
                "order_id": result.order_id,
                "execution_id": execution_id,
            },
        )
        logging.info(
            "%s LIMIT %s %d %s @ %.4f -> initial filled %d, status=%s",
            "DRY RUN:" if not LIVE_TRADING else "ORDER:",
            action,
            quantity,
            ticker,
            price,
            result.filled,
            result.status,
        )
        return result

    @staticmethod
    def order_result_from_payload(
        ticker: str,
        action: str,
        requested: int,
        payload: Any,
        *,
        reference_price: Optional[float] = None,
    ) -> OrderResult:
        row = payload if isinstance(payload, dict) else {}
        filled = int(round(float(row.get("quantity_filled", 0) or 0)))
        vwap_raw = row.get("vwap")
        order_id_raw = row.get("order_id", row.get("id"))
        return OrderResult(
            ticker=ticker,
            action=action.upper(),
            requested=int(requested),
            filled=filled,
            vwap=(float(vwap_raw) if vwap_raw is not None else None),
            status=str(row.get("status", "UNKNOWN")).upper(),
            order_id=(int(order_id_raw) if order_id_raw is not None else None),
            reference_price=reference_price,
            order_type="MARKET",
        )

    def get_order(self, order_id: int) -> dict:
        payload = self.request_json("GET", f"orders/{int(order_id)}")
        if not isinstance(payload, dict):
            raise ApiException(f"GET /orders/{order_id} returned no object")
        return payload

    def get_order_optional(self, order_id: int) -> Optional[dict]:
        payload = self.request_json(
            "GET",
            f"orders/{int(order_id)}",
            acceptable_statuses=(404,),
        )
        if (
            isinstance(payload, dict)
            and payload.get("_accepted_terminal_response")
        ):
            return None
        if not isinstance(payload, dict):
            raise ApiException(f"GET /orders/{order_id} returned no object")
        return payload

    def cancel_order(self, order_id: int) -> Any:
        # A fill can race a cancellation between GET and DELETE. The DMA API
        # then returns 404 because the order is already terminal. That is not
        # a strategy error; callers reconcile the final observed fill next.
        return self.request_json(
            "DELETE",
            f"orders/{int(order_id)}",
            acceptable_statuses=(404,),
        )

    def accept_fixed_tender(self, tender: dict) -> bool:
        tender_id = int(tender["tender_id"])

        if not bool(tender.get("is_fixed_bid", False)):
            raise ValueError(
                "accept_fixed_tender cannot submit a competitive tender"
            )

        if not LIVE_TRADING:
            logging.warning("DRY RUN: would accept tender #%d", tender_id)
            return False

        payload = self.request_json(
            "POST",
            f"tenders/{tender_id}",
            params={"price": f"{float(tender['price']):.10g}"},
        )

        if isinstance(payload, dict):
            return bool(payload.get("success", True))

        return True


