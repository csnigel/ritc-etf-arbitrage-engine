def validate_settings() -> None:
    if LIVE_TRADING and not RISK_LIMITS_CONFIRMED:
        raise RuntimeError(
            "LIVE_TRADING=True but RISK_LIMITS_CONFIRMED=False. "
            "Check GET /limits before enabling trading."
        )

    if not DMA_API_ENDPOINT.startswith(("http://", "https://")):
        raise ValueError("DMA_API_ENDPOINT is not a valid HTTP URL")

    if MIN_DIRECT_QTY <= 0 or QTY_STEP <= 0:
        raise ValueError(
            "MIN_DIRECT_QTY and QTY_STEP must be positive"
        )

    if MAX_DIRECT_QTY_PER_ACTION > MAX_EQUITY_ORDER_SIZE:
        raise ValueError(
            "MAX_DIRECT_QTY_PER_ACTION exceeds the equity "
            "maximum order size"
        )

    if MAX_OPEN_MATCHED_ARB_QTY < MIN_DIRECT_QTY:
        raise ValueError(
            "MAX_OPEN_MATCHED_ARB_QTY must be at least MIN_DIRECT_QTY"
        )

    if REQUIRED_CONSECUTIVE_CONFIRMATIONS < 1:
        raise ValueError(
            "REQUIRED_CONSECUTIVE_CONFIRMATIONS must be at least 1"
        )

    if MAX_ADVERSE_EDGE_DRIFT_CAD < 0:
        raise ValueError("MAX_ADVERSE_EDGE_DRIFT_CAD cannot be negative")

    if not (
        0 <= STOP_ALL_NEW_ORDERS_SECONDS
        <= STOP_ALL_DIRECT_ARB_SECONDS
        <= STOP_NEW_DIRECT_ARB_SECONDS
    ):
        raise ValueError(
            "Direct time gates must satisfy STOP_ALL_NEW_ORDERS_SECONDS <= "
            "STOP_ALL_DIRECT_ARB_SECONDS <= STOP_NEW_DIRECT_ARB_SECONDS"
        )

    if not MIN_DIRECT_QTY <= DIRECT_PROTECTED_CHILD_QTY <= MAX_EQUITY_ORDER_SIZE:
        raise ValueError(
            "DIRECT_PROTECTED_CHILD_QTY must be between MIN_DIRECT_QTY "
            "and the equity order limit"
        )

    if DIRECT_PROTECTED_CHILD_QTY % QTY_STEP:
        raise ValueError(
            "DIRECT_PROTECTED_CHILD_QTY must be a multiple of QTY_STEP"
        )

    if not 0 <= DIRECT_MIN_REALIZED_EDGE_CAD <= MIN_DIRECT_NET_EDGE_CAD:
        raise ValueError(
            "DIRECT_MIN_REALIZED_EDGE_CAD must be between zero and the "
            "direct entry edge"
        )

    if not 0 <= DIRECT_BASKET_SLIPPAGE_RESERVE_CAD <= MAX_ADVERSE_EDGE_DRIFT_CAD:
        raise ValueError(
            "DIRECT_BASKET_SLIPPAGE_RESERVE_CAD must fit inside the "
            "maximum adverse edge drift"
        )

    if DIRECT_MARKETABLE_LIMIT_TTL_SECONDS <= 0:
        raise ValueError("DIRECT_MARKETABLE_LIMIT_TTL_SECONDS must be positive")

    if not 0 < DIRECT_LIMIT_POLL_INTERVAL_SECONDS <= DIRECT_MARKETABLE_LIMIT_TTL_SECONDS:
        raise ValueError(
            "DIRECT_LIMIT_POLL_INTERVAL_SECONDS must be positive and no "
            "longer than the limit-order TTL"
        )

    if not 1 <= FAST_DIRECT_PREFLIGHT_WORKERS <= 6:
        raise ValueError(
            "FAST_DIRECT_PREFLIGHT_WORKERS must be between 1 and 6"
        )

    if not 1 <= FAST_STRATEGY_SNAPSHOT_WORKERS <= 7:
        raise ValueError(
            "FAST_STRATEGY_SNAPSHOT_WORKERS must be between 1 and 7"
        )

    if not 1 <= PASSIVE_RITC_ORDER_QTY <= MAX_EQUITY_ORDER_SIZE:
        raise ValueError(
            "PASSIVE_RITC_ORDER_QTY must be within equity order limits"
        )

    if PASSIVE_MAX_FILLED_UNHEDGED_QTY < PASSIVE_RITC_ORDER_QTY:
        raise ValueError(
            "PASSIVE_MAX_FILLED_UNHEDGED_QTY cannot be below the order quantity"
        )

    if PASSIVE_QUOTE_LIFETIME_SECONDS <= 0:
        raise ValueError("PASSIVE_QUOTE_LIFETIME_SECONDS must be positive")

    if PASSIVE_MIN_HEDGE_EDGE_CAD < 0 or PASSIVE_MIN_TOTAL_PNL_CAD < 0:
        raise ValueError("Passive edge and P&L thresholds cannot be negative")

    if MAX_WEIGHTED_GROSS <= 0:
        raise ValueError("MAX_WEIGHTED_GROSS must be positive")

    if MAX_ABS_WEIGHTED_NET <= 0:
        raise ValueError(
            "MAX_ABS_WEIGHTED_NET must be positive"
        )

    if MAX_TENDER_TRANSIENT_WEIGHTED_GROSS < MAX_WEIGHTED_GROSS:
        raise ValueError(
            "Tender transient gross limit cannot be below the ordinary limit"
        )

    if MAX_TENDER_TRANSIENT_ABS_WEIGHTED_NET < MAX_ABS_WEIGHTED_NET:
        raise ValueError(
            "Tender transient net limit cannot be below the ordinary limit"
        )

    if CONVERTER_LOT <= 0 or CONVERTER_COST_USD_PER_USE < 0:
        raise ValueError("Converter lot and cost settings are invalid")

    if MIXED_CONVERTER_EXECUTION_RISK_PENALTY_CAD_PER_SHARE < 0:
        raise ValueError(
            "Mixed converter execution risk penalty cannot be negative"
        )

    if MAX_MIXED_CONVERTER_TENDERS_PER_RUN < 0:
        raise ValueError(
            "MAX_MIXED_CONVERTER_TENDERS_PER_RUN cannot be negative"
        )

    if TENDER_SETTLEMENT_TIMEOUT_SECONDS <= 0:
        raise ValueError("Tender settlement timeout must be positive")

    if not (
        0 < TENDER_SETTLEMENT_POLL_INTERVAL_SECONDS
        <= TENDER_SETTLEMENT_TIMEOUT_SECONDS
    ):
        raise ValueError(
            "Tender settlement poll interval must be positive and no longer "
            "than its timeout"
        )

    if TENDER_SETTLEMENT_STABLE_READS < 1:
        raise ValueError("Tender settlement stable reads must be at least 1")

    if TENDER_POST_HEDGE_RECONCILIATION_TIMEOUT_SECONDS <= 0:
        raise ValueError("Post-hedge reconciliation timeout must be positive")

    if MAX_PRE_TENDER_CAPACITY_RELEASE_LOTS < 0:
        raise ValueError("Pre-tender capacity-release lots cannot be negative")

    if MIN_SECONDS_FOR_PRE_TENDER_CAPACITY_RELEASE < 0:
        raise ValueError("Capacity-release minimum seconds cannot be negative")

    converter_test_action = AUTOMATED_CONVERTER_TEST_ACTION.strip().upper()
    if converter_test_action not in {"BOTH", "CREATE", "REDEEM"}:
        raise ValueError(
            "AUTOMATED_CONVERTER_TEST_ACTION must be BOTH, CREATE, or REDEEM"
        )

    if (
        LOCK_MIXED_CONVERTER_FX_BEFORE_CONVERSION
        and not ENABLE_FX_HEDGE
    ):
        raise ValueError(
            "LOCK_MIXED_CONVERTER_FX_BEFORE_CONVERSION=True requires "
            "ENABLE_FX_HEDGE=True"
        )

    if ARM_LIVE_AUTOMATED_CONVERTER and not ENABLE_MIXED_CONVERTER_ROUTE:
        raise ValueError(
            "ARM_LIVE_AUTOMATED_CONVERTER=True requires "
            "ENABLE_MIXED_CONVERTER_ROUTE=True"
        )

    if ARM_LIVE_AUTOMATED_CONVERTER and not ENABLE_AUTOMATED_CONVERTER:
        raise ValueError(
            "ARM_LIVE_AUTOMATED_CONVERTER=True requires "
            "ENABLE_AUTOMATED_CONVERTER=True"
        )

    if AUTOMATED_CONVERTER_CONFIRM_TIMEOUT_SECONDS <= 0:
        raise ValueError("Automated converter confirmation timeout must be positive")

    if AUTOMATED_CONVERTER_POLL_INTERVAL_SECONDS <= 0:
        raise ValueError("Automated converter poll interval must be positive")

    if CONVERTER_PNL_RECONCILIATION_TIMEOUT_SECONDS <= 0:
        raise ValueError(
            "Converter P&L reconciliation timeout must be positive"
        )

    if CONVERTER_PNL_MIN_CHANGE_CAD < 0:
        raise ValueError("Converter P&L minimum change cannot be negative")


def startup_report(
    client: RITClient,
    audit: AuditLogger,
) -> None:
    case = client.case()

    logging.warning(
        "MODE=%s | case=%s | period=%s | tick=%s/%s | status=%s",
        "LIVE" if LIVE_TRADING else "DRY RUN",
        case.get("name"),
        case.get("period"),
        case.get("tick"),
        case.get("ticks_per_period"),
        case.get("status"),
    )

    logging.warning(
        "DMA endpoint: %s",
        DMA_API_ENDPOINT,
    )

    try:
        limits = client.limits()

        audit.save_json(
            "simulator_limits_at_startup.json",
            limits,
        )

        for row in limits:
            logging.warning(
                "SIM LIMIT %s: gross=%s net=%s "
                "gross_limit=%s net_limit=%s",
                row.get("name"),
                row.get("gross"),
                row.get("net"),
                row.get("gross_limit"),
                row.get("net_limit"),
            )

        stock_limit = next(
            (
                row for row in limits
                if str(row.get("name", "")).upper() == "LIMIT-STOCK"
            ),
            None,
        )
        if stock_limit is not None:
            simulator_gross = float(stock_limit.get("gross_limit", 0) or 0)
            simulator_net = float(stock_limit.get("net_limit", 0) or 0)
            if (
                MAX_TENDER_TRANSIENT_WEIGHTED_GROSS > simulator_gross
                or MAX_TENDER_TRANSIENT_ABS_WEIGHTED_NET > simulator_net
            ):
                raise RuntimeError(
                    "Local tender transient limits exceed GET /limits. "
                    "Lower them before running."
                )
        elif LIVE_TRADING:
            raise RuntimeError(
                "GET /limits did not return LIMIT-STOCK; refusing to run "
                "live tender logic without verifying the stock limits."
            )

    except (requests.RequestException, ApiException) as exc:
        if LIVE_TRADING:
            raise RuntimeError(
                "Could not verify GET /limits; refusing to run live."
            ) from exc
        logging.warning(
            "Could not read GET /limits at startup: %s",
            exc,
        )

    logging.warning(
        "LOCAL LIMITS: weighted gross <= %d; "
        "|weighted net| <= %d | direct scale stage=%d",
        MAX_WEIGHTED_GROSS,
        MAX_ABS_WEIGHTED_NET,
        DIRECT_SCALE_STAGE,
    )

    logging.warning(
        "DIRECT CONTROL: edge >= %.3f | P&L >= CAD %.2f | "
        "fast_preflight=%s | workers=%d | sequential_fallback=%s",
        MIN_DIRECT_NET_EDGE_CAD,
        MIN_DIRECT_TOTAL_PNL_CAD,
        ENABLE_FAST_DIRECT_PREFLIGHT,
        FAST_DIRECT_PREFLIGHT_WORKERS,
        FAST_DIRECT_PREFLIGHT_FALLBACK_TO_SEQUENTIAL,
    )

    logging.warning(
        "DIRECT EXECUTION: protected RITC lead | child=%d | "
        "min realized edge=%.3f | drift cap=%.3f | basket reserve=%.3f | "
        "limit TTL=%.2fs | matched inventory cap=%d",
        DIRECT_PROTECTED_CHILD_QTY,
        DIRECT_MIN_REALIZED_EDGE_CAD,
        MAX_ADVERSE_EDGE_DRIFT_CAD,
        DIRECT_BASKET_SLIPPAGE_RESERVE_CAD,
        DIRECT_MARKETABLE_LIMIT_TTL_SECONDS,
        MAX_OPEN_MATCHED_ARB_QTY,
    )

    logging.warning(
        "PASSIVE RITC: enabled=%s | q=%d | hedge edge >= %.3f | "
        "P&L >= CAD %.2f | lifetime=%.2fs | stop=%ds",
        ENABLE_PASSIVE_RITC_ARB,
        PASSIVE_RITC_ORDER_QTY,
        PASSIVE_MIN_HEDGE_EDGE_CAD,
        PASSIVE_MIN_TOTAL_PNL_CAD,
        PASSIVE_QUOTE_LIFETIME_SECONDS,
        PASSIVE_STOP_NEW_QUOTES_SECONDS,
    )

    logging.warning(
        "TENDER TRANSIENT LIMITS: weighted gross <= %d; "
        "|weighted net| <= %d",
        MAX_TENDER_TRANSIENT_WEIGHTED_GROSS,
        MAX_TENDER_TRANSIENT_ABS_WEIGHTED_NET,
    )

    logging.warning(
        "TENDER CONTROL: auto_accept=%s | direct_unwind=%s | "
        "basket_hedge=%s | hybrid_direct_basket=%s | "
        "edge>=%.3f | score>=CAD %.2f | automated_converter_armed=%s | "
        "converter_action=%s | "
        "preconversion_fx_lock=%s | mixed_converter_per_run_cap=%d",
        AUTO_ACCEPT_FIXED_TENDERS,
        ENABLE_TENDER_DIRECT_UNWIND,
        ENABLE_TENDER_BASKET_HEDGE,
        ENABLE_TENDER_HYBRID_ROUTE,
        MIN_TENDER_NET_EDGE_CAD,
        MIN_TENDER_TOTAL_PNL_CAD,
        ARM_LIVE_AUTOMATED_CONVERTER,
        AUTOMATED_CONVERTER_TEST_ACTION,
        LOCK_MIXED_CONVERTER_FX_BEFORE_CONVERSION,
        MAX_MIXED_CONVERTER_TENDERS_PER_RUN,
    )

    logging.warning(
        "TENDER SETTLEMENT: timeout=%.2fs | poll=%.2fs | stable_reads=%d | "
        "post_hedge_timeout=%.2fs | capacity_release=%s (max_lots=%d, min_left=%ds)",
        TENDER_SETTLEMENT_TIMEOUT_SECONDS,
        TENDER_SETTLEMENT_POLL_INTERVAL_SECONDS,
        TENDER_SETTLEMENT_STABLE_READS,
        TENDER_POST_HEDGE_RECONCILIATION_TIMEOUT_SECONDS,
        ENABLE_PRE_TENDER_CAPACITY_RELEASE,
        MAX_PRE_TENDER_CAPACITY_RELEASE_LOTS,
        MIN_SECONDS_FOR_PRE_TENDER_CAPACITY_RELEASE,
    )

    logging.warning(
        "Logs: %s",
        audit.run_dir,
    )


def heartbeat(
    state: MarketState,
    audit: Optional[AuditLogger] = None,
) -> None:
    bull = state.books[BULL]
    bear = state.books[BEAR]
    ritc = state.books[RITC]
    usd = state.books[USD]

    gross, net = weighted_risk(state.positions)

    cheap_edge = (
        bull.best_bid
        + bear.best_bid
        - ritc.best_ask * usd.best_ask
        if (
            math.isfinite(ritc.best_ask)
            and math.isfinite(usd.best_ask)
        )
        else math.nan
    )

    rich_edge = (
        ritc.best_bid * usd.best_bid
        - bull.best_ask
        - bear.best_ask
    )

    pnl_value: Any = "n/a"
    if audit is not None and audit.last_pnl_snapshot is not None:
        candidate_pnl = audit.last_pnl_snapshot.get("total_pnl_cad", "")
        if candidate_pnl != "":
            pnl_value = candidate_pnl

    logging.info(
        "tick=%d left=%ds | raw edges: cheap=%.4f rich=%.4f | "
        "positions BULL=%+d BEAR=%+d RITC=%+d USD=%+d | "
        "weighted gross=%d net=%+d | simulator P&L=%s",
        state.tick,
        state.seconds_remaining,
        cheap_edge,
        rich_edge,
        state.positions[BULL],
        state.positions[BEAR],
        state.positions[RITC],
        state.positions[USD],
        gross,
        net,
        pnl_value,
    )


# =============================================================================
# MAIN LOOP
# =============================================================================

def main() -> None:
    global active_dashboard, active_passive_order
    global pending_converter, pending_converter_pnl
    global pending_tender_execution

    validate_settings()

    audit = AuditLogger()
    audit.configure_python_logging()
    audit.save_json("parameters.json", settings_snapshot())

    if ENABLE_LOCAL_DASHBOARD:
        active_dashboard = StrategyDashboard()
        active_dashboard.start()

    username, password = get_credentials()

    client = RITClient(
        api_endpoint=DMA_API_ENDPOINT,
        username=username,
        password=password,
        audit=audit,
    )

    final_positions: Optional[Dict[str, int]] = None
    final_status: Optional[str] = None
    last_active_state: Optional[MarketState] = None
    final_market_state: Optional[MarketState] = None

    try:
        startup_report(client, audit)

        consecutive_errors = 0
        last_heartbeat = 0.0
        last_status: Optional[str] = None
        last_tender_evaluation: Dict[int, int] = {}
        last_direct_action_tick: Optional[int] = None
        has_been_active = False
        pnl_endpoint_available = True
        direct_confirmation = DirectConfirmationTracker()

        while not shutdown_requested:
            try:
                case: Optional[dict] = None
                if not has_been_active:
                    case = client.case()
                    status = str(case.get("status", "STOPPED")).upper()
                    if status != last_status:
                        logging.warning("Case status: %s", status)
                        if active_dashboard is not None:
                            active_dashboard.push_event(
                                "INFO",
                                f"Case status changed to {status}",
                            )
                        last_status = status
                    if not is_new_active_case(has_been_active, status):
                        if not WAIT_FOR_CASE_TO_START:
                            logging.warning("Case is %s. Exiting.", status)
                            break
                        time.sleep(0.5)
                        continue
                    has_been_active = True
                    # Fresh state for every newly activated case.
                    last_tender_evaluation.clear()
                    last_direct_action_tick = None
                    direct_confirmation.reset()
                    pnl_endpoint_available = True
                    consecutive_errors = 0
                    audit.mixed_converter_tenders_started = 0

                    # Pending objects from the previous simulator case are no longer valid.
                    pending_converter = None
                    pending_converter_pnl = None
                    pending_tender_execution = None
                    active_passive_order = None

                    logging.warning(
                        "New ACTIVE case detected. Per-case strategy state reset."
                    )

                try:
                    state, tender_rows, snapshot_metrics = (
                        load_fast_strategy_state(client)
                    )
                except (requests.RequestException, ApiException, KeyError) as exc:
                    logging.warning(
                        "Fast strategy snapshot failed; using sequential fallback: %s",
                        exc,
                    )
                    fallback_started = time.monotonic()
                    state = load_state(client, case)
                    tender_rows = client.tenders()
                    snapshot_metrics = {
                        "preflight_mode": "SEQUENTIAL_FALLBACK",
                        "preflight_fetch_ms": round(
                            (time.monotonic() - fallback_started) * 1000.0,
                            3,
                        ),
                        "fast_snapshot_error": str(exc),
                    }
                last_active_state = state
                client.set_state_context(state)
                if state.status != last_status:
                    logging.warning("Case status: %s", state.status)
                    if active_dashboard is not None:
                        active_dashboard.push_event(
                            "INFO",
                            f"Case status changed to {state.status}",
                        )
                    last_status = state.status
                if state.status != "ACTIVE":
                    if EXIT_AFTER_ACTIVE_PERIOD:
                        logging.warning("Active period ended. Exiting.")
                        break

                    # Re-enter the startup/waiting path so the next ACTIVE case receives
                    # fresh per-case strategy state.
                    has_been_active = False
                    time.sleep(0.5)
                    continue
                acted = False
                had_passive_order = active_passive_order is not None
                passive_acted, passive_open = service_active_passive_order(
                    client,
                    state,
                    force_cancel=(
                        bool(tender_rows)
                        or pending_converter is not None
                        or pending_tender_execution is not None
                        or state.seconds_remaining <= PASSIVE_STOP_NEW_QUOTES_SECONDS
                    ),
                )
                acted = passive_acted

                # The just-cancelled lead may have appeared in the RITC book
                # used by the first snapshot. Never value a new route against
                # our own now-cancelled liquidity.
                if had_passive_order and not passive_open and not acted:
                    state, tender_rows, snapshot_metrics = (
                        load_fast_strategy_state(client)
                    )
                    last_active_state = state
                    client.set_state_context(state)

                if (
                    not acted
                    and not passive_open
                    and service_pending_tender_execution(client)
                ):
                    acted = True

                if not acted and not passive_open and service_pending_converter(client, state):
                    acted = True

                pause_for_pnl = service_pending_converter_pnl(client, state)
                if pause_for_pnl:
                    acted = True

                if (
                    not acted
                    and not passive_open
                    and ENABLE_TENDERS
                    and state.seconds_remaining
                    > STOP_ALL_NEW_ORDERS_SECONDS
                ):
                    for tender in tender_rows:
                        tender_id = int(
                            tender.get("tender_id", -1)
                        )

                        if (
                            last_tender_evaluation.get(tender_id)
                            == state.tick
                        ):
                            continue

                        last_tender_evaluation[tender_id] = state.tick

                        if evaluate_and_maybe_execute_tender(
                            client,
                            state,
                            tender,
                        ):
                            acted = True
                            break

                if (
                    not acted
                    and not passive_open
                    and ENABLE_DIRECT_ARB
                    and state.seconds_remaining > STOP_ALL_DIRECT_ARB_SECONDS
                ):
                    reduction_only = (
                        state.seconds_remaining
                        <= STOP_NEW_DIRECT_ARB_SECONDS
                    )
                    candidate = scan_direct_arbitrage(
                        client,
                        state,
                        reduction_only=reduction_only,
                    )

                    confirmation_count = direct_confirmation.observe(
                        candidate,
                        state.tick,
                    )

                    if candidate is not None:
                        audit.action(
                            state=state,
                            event="DIRECT_CONFIRMATION",
                            module="DIRECT_ARB",
                            label=candidate.label,
                            requested_quantity=candidate.quantity,
                            average_edge_cad=candidate.average_edge_cad,
                            expected_pnl_cad=candidate.total_pnl_cad,
                            status=(
                                "CONFIRMED"
                                if confirmation_count
                                >= REQUIRED_CONSECUTIVE_CONFIRMATIONS
                                else "WAITING"
                            ),
                            message=(
                                f"Confirmation {confirmation_count}/"
                                f"{REQUIRED_CONSECUTIVE_CONFIRMATIONS}"
                            ),
                            details={
                                "direction": candidate.direction,
                                "confirmation_count": confirmation_count,
                            },
                        )

                    if (
                        not acted
                        and candidate is not None
                        and confirmation_count
                        >= REQUIRED_CONSECUTIVE_CONFIRMATIONS
                        and last_direct_action_tick != state.tick
                        and state.seconds_remaining
                        > STOP_ALL_NEW_ORDERS_SECONDS
                    ):
                        audit.action(
                            state=state,
                            event="DIRECT_PREFLIGHT",
                            module="DIRECT_ARB",
                            label=candidate.label,
                            requested_quantity=candidate.quantity,
                            average_edge_cad=candidate.average_edge_cad,
                            expected_pnl_cad=candidate.total_pnl_cad,
                            status="PASSED_SYNCHRONIZED_SNAPSHOT",
                            message=(
                                "Initial concurrent signal passed. Every "
                                f"{DIRECT_PROTECTED_CHILD_QTY:,}-share child will be freshly revalued "
                                "and RITC-price-protected before execution."
                            ),
                            details={
                                "confirmed_direction": candidate.direction,
                                "confirmed_edge_cad":
                                    candidate.average_edge_cad,
                                **snapshot_metrics,
                            },
                        )
                        logging.info(
                            "DIRECT SNAPSHOT PASSED | mode=%s | fetch=%.1fms",
                            snapshot_metrics.get(
                                "preflight_mode",
                                "UNKNOWN",
                            ),
                            float(
                                snapshot_metrics.get(
                                    "preflight_fetch_ms",
                                    0.0,
                                )
                                or 0.0
                            ),
                        )
                        direct_confirmation.reset()
                        execute_direct_candidate(client, state, candidate)
                        last_direct_action_tick = state.tick
                        acted = True

                # Rebalance an existing FX hedge even when no new
                # arbitrage or tender action occurs.
                if not acted and not passive_open and ENABLE_FX_HEDGE:
                    acted = hedge_fx_to_target(client, state) > 0

                if not acted and not passive_open:
                    passive_candidate = passive_ritc_candidate(state)
                    if passive_candidate is not None:
                        place_passive_ritc_order(
                            client,
                            state,
                            passive_candidate,
                        )

                # Diagnostics are intentionally after the decision path so
                # file I/O and GET /trader cannot age executable quotes.
                audit.record_market(state)
                audit.record_books(state)
                now = time.monotonic()
                if now - audit.last_pnl_log >= PNL_LOG_INTERVAL_SECONDS:
                    trader_payload: Any = {}
                    if pnl_endpoint_available:
                        try:
                            trader_payload = client.trader()
                        except (requests.RequestException, ApiException) as exc:
                            pnl_endpoint_available = False
                            logging.warning(
                                "GET /trader unavailable; pnl.csv will still "
                                "contain per-security P&L fields: %s",
                                exc,
                            )
                    audit.record_pnl(state, trader_payload)
                if active_dashboard is not None:
                    active_dashboard.update_market(state, audit)
                if now - last_heartbeat >= HEARTBEAT_SECONDS:
                    heartbeat(state, audit)
                    last_heartbeat = now

                consecutive_errors = 0
                time.sleep(LOOP_INTERVAL_SECONDS)

            except KeyboardInterrupt:
                logging.warning("Stopped by user")
                break

            except (
                requests.RequestException,
                ApiException,
                ValueError,
                RuntimeError,
                KeyError,
            ) as exc:
                consecutive_errors += 1
                audit.error_events += 1

                logging.exception(
                    "Loop error %d/%d: %s",
                    consecutive_errors,
                    MAX_CONSECUTIVE_ERRORS,
                    exc,
                )

                audit.action(
                    state=client.context_state,
                    event="LOOP_ERROR",
                    module="MAIN",
                    status="ERROR",
                    message=str(exc),
                    details={
                        "consecutive_errors":
                            consecutive_errors,
                    },
                )

                if (
                    consecutive_errors
                    >= MAX_CONSECUTIVE_ERRORS
                ):
                    logging.critical(
                        "Too many consecutive errors. "
                        "Stopping safely."
                    )
                    break

                time.sleep(
                    min(
                        2.0,
                        LOOP_INTERVAL_SECONDS
                        * consecutive_errors,
                    )
                )

    finally:
        if active_passive_order is not None:
            try:
                if last_active_state is not None:
                    service_active_passive_order(
                        client,
                        last_active_state,
                        force_cancel=True,
                    )
                else:
                    client.cancel_order(active_passive_order.order_id)
            except (requests.RequestException, ApiException) as exc:
                logging.critical(
                    "Could not cancel passive RITC order %d during shutdown: %s",
                    active_passive_order.order_id,
                    exc,
                )
            active_passive_order = None
        try:
            final_case = client.case()
            final_status = str(
                final_case.get("status", "UNKNOWN")
            ).upper()
            final_rows = client.securities()
            final_positions = client.positions_from_rows(final_rows)

            if last_active_state is not None:
                final_state = MarketState(
                    period=int(
                        final_case.get(
                            "period",
                            last_active_state.period,
                        )
                    ),
                    tick=int(final_case.get("tick", last_active_state.tick)),
                    ticks_per_period=int(
                        final_case.get(
                            "ticks_per_period",
                            last_active_state.ticks_per_period,
                        )
                    ),
                    status=final_status,
                    seconds_remaining=max(
                        0,
                        int(
                            final_case.get(
                                "ticks_per_period",
                                last_active_state.ticks_per_period,
                            )
                        )
                        - int(final_case.get("tick", last_active_state.tick)),
                    ),
                    books=last_active_state.books,
                    positions=final_positions,
                    security_rows=final_rows,
                )
                try:
                    final_trader_payload = client.trader()
                except Exception as exc:
                    final_trader_payload = {}
                    logging.warning(
                        "Could not retrieve final account P&L: %s",
                        exc,
                    )
                audit.record_pnl(
                    final_state,
                    final_trader_payload,
                    phase=(
                        "POST_STOP"
                        if final_status != "ACTIVE"
                        else "FINAL_ACTIVE"
                    ),
                )
                final_market_state = final_state
                if active_dashboard is not None:
                    active_dashboard.update_market(final_state, audit)
        except Exception as exc:
            logging.warning(
                "Could not retrieve final state: %s",
                exc,
            )

        if pending_tender_execution is not None:
            audit.action(
                state=final_market_state or last_active_state,
                event="TENDER_CAMPAIGN_UNRESOLVED_AT_SHUTDOWN",
                module="TENDER",
                tender_id=pending_tender_execution.tender.get("tender_id"),
                status=pending_tender_execution.phase,
                message=(
                    "The run ended before the accepted tender campaign fully "
                    "settled and reconciled."
                ),
                details={
                    "expected_ritc_position":
                        pending_tender_execution.expected_ritc_position,
                    "expected_stock_positions":
                        pending_tender_execution.expected_stock_positions,
                    "last_observed_positions":
                        pending_tender_execution.last_observed_positions,
                },
            )
            logging.critical(
                "Tender campaign #%s ended unresolved in phase %s.",
                pending_tender_execution.tender.get("tender_id"),
                pending_tender_execution.phase,
            )

        log_unresolved_pending_converter(
            client,
            final_market_state or last_active_state,
            "The run ended before the expected converter position reset was detected.",
        )

        if final_market_state is not None:
            service_pending_converter_pnl(client, final_market_state)
        log_unresolved_converter_pnl(
            client,
            final_market_state or last_active_state,
        )

        audit.close(final_positions, final_status)
        client.session.close()

        if active_dashboard is not None:
            active_dashboard.finish(final_status or "UNKNOWN")

        logging.warning(
            "Run finished. Logs saved in: %s",
            audit.run_dir,
        )


if __name__ == "__main__":
    signal.signal(signal.SIGINT, signal_handler)
    main()
