class DepthCursor:
    """Walk through one side of an aggregated order book."""

    def __init__(self, levels: Sequence[Level]):
        self.levels = list(levels)
        self.index = 0
        self.remaining = float(self.levels[0].quantity) if self.levels else 0.0

    @property
    def valid(self) -> bool:
        return self.index < len(self.levels)

    @property
    def price(self) -> float:
        return self.levels[self.index].price if self.valid else math.nan

    def consume(self, quantity: float) -> None:
        left = float(quantity)

        while left > 1e-9 and self.valid:
            used = min(left, self.remaining)
            self.remaining -= used
            left -= used

            if self.remaining <= 1e-9:
                self.index += 1
                if self.valid:
                    self.remaining = float(self.levels[self.index].quantity)

        if left > 1e-6:
            raise ValueError("Attempted to consume beyond visible order-book depth")


