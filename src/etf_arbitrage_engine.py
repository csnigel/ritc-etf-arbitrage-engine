def dashboard_json_safe(value: Any) -> Any:
    """Return a detached value tree containing only strict JSON values."""
    if isinstance(value, float) and not math.isfinite(value):
        return None
    if isinstance(value, dict):
        return {str(key): dashboard_json_safe(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [dashboard_json_safe(item) for item in value]
    return value


