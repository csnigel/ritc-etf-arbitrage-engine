def tender_risk_allowed(
    state: MarketState,
    tender: dict,
    candidate: Candidate,
) -> bool:
    quantity = int(round(float(tender["quantity"])))
    action = str(tender["action"]).upper()

    tender_delta = {
        RITC: signed_delta(action, quantity)
    }

    # The tender is applied before our hedge orders.
    if not risk_allows(
        state.positions,
        tender_delta,
        max_gross=MAX_TENDER_TRANSIENT_WEIGHTED_GROSS,
        max_abs_net=MAX_TENDER_TRANSIENT_ABS_WEIGHTED_NET,
    ):
        return False

    running_deltas = dict(tender_delta)

    # Limits apply after each submitted order, not only after the finished
    # package. Candidate.legs is stored in intended execution order.
    for ticker, leg_action, leg_quantity in candidate.legs:
        running_deltas[ticker] = (
            running_deltas.get(ticker, 0)
            + signed_delta(leg_action, leg_quantity)
        )
        if not risk_allows(
            state.positions,
            running_deltas,
            max_gross=MAX_TENDER_TRANSIENT_WEIGHTED_GROSS,
            max_abs_net=MAX_TENDER_TRANSIENT_ABS_WEIGHTED_NET,
        ):
            return False

    return True


def accepted_tender_route_risk_allowed(
    state: MarketState,
    candidate: Candidate,
) -> bool:
    """Check hedge legs when the tender is already in observed positions."""
    running_deltas: Dict[str, int] = {}
    for ticker, action, quantity in candidate.legs:
        running_deltas[ticker] = (
            running_deltas.get(ticker, 0)
            + signed_delta(action, quantity)
        )
        if not risk_allows_or_reduces(
            state.positions,
            running_deltas,
            max_gross=MAX_TENDER_TRANSIENT_WEIGHTED_GROSS,
            max_abs_net=MAX_TENDER_TRANSIENT_ABS_WEIGHTED_NET,
        ):
            return False
    return True


def capacity_release_variant(
    state: MarketState,
    tender: dict,
    candidate: Candidate,
) -> Optional[Candidate]:
    """Price a converter release of existing matched inventory before tender."""
    # Partial/zero-depth candidates are diagnostics, not executable routes.
    # Releasing risk capacity cannot create missing market depth, and their
    # score is deliberately -inf.  Reject them before any per-share math.
    if (
        not ENABLE_PRE_TENDER_CAPACITY_RELEASE
        or candidate.quantity <= 0
        or candidate.coverage < 1.0
        or not candidate.legs
        or not math.isfinite(candidate.score_cad)
        or not math.isfinite(candidate.total_pnl_cad)
    ):
        return None
    positions = state.positions
    create_lots = max(
        0,
        min(
            int(positions.get(BULL, 0)),
            int(positions.get(BEAR, 0)),
            -int(positions.get(RITC, 0)),
        ) // CONVERTER_LOT,
    )
    redeem_lots = max(
        0,
        min(
            -int(positions.get(BULL, 0)),
            -int(positions.get(BEAR, 0)),
            int(positions.get(RITC, 0)),
        ) // CONVERTER_LOT,
    )
    choices = (("CREATE", create_lots), ("REDEEM", redeem_lots))
    fx_ask = state.books[USD].best_ask
    if not math.isfinite(fx_ask) or fx_ask <= 0:
        return None

    for action, available_lots in choices:
        maximum = min(available_lots, MAX_PRE_TENDER_CAPACITY_RELEASE_LOTS)
        for lots in range(1, maximum + 1):
            projected = dict(positions)
            for _ in range(lots):
                projected = expected_positions_after_converter_lot(projected, action)
            projected_state = replace(state, positions=projected)
            if not tender_risk_allowed(projected_state, tender, candidate):
                continue
            cost_cad = lots * CONVERTER_COST_USD_PER_USE * fx_ask
            return replace(
                candidate,
                label=(
                    f"{candidate.label}; release {lots} existing lot(s) via {action}"
                ),
                total_pnl_cad=candidate.total_pnl_cad - cost_cad,
                average_edge_cad=(
                    (candidate.total_pnl_cad - cost_cad) / candidate.quantity
                ),
                score_cad=candidate.score_cad - cost_cad,
                note=(
                    f"{candidate.note} Before acceptance, {action} {lots} "
                    f"matched inventory lot(s) to free official capacity; "
                    f"estimated release cost CAD {cost_cad:,.2f}."
                ),
                capacity_release_action=action,
                capacity_release_lots=lots,
                capacity_release_cost_cad=cost_cad,
            )
    return None


def execute_capacity_release(
    client: RITClient,
    state: MarketState,
    tender: dict,
    candidate: Candidate,
) -> bool:
    """Convert existing matched inventory, then re-fetch the same tender."""
    action = candidate.capacity_release_action.upper()
    lots = int(candidate.capacity_release_lots)
    tender_id = int(tender["tender_id"])
    if not action or lots <= 0:
        return False
    client.audit.capacity_release_attempts += 1
    if not client.converter_preflight(action):
        client.audit.capacity_release_failures += 1
        return False
    if not lock_preconversion_fx_funding(client, tender_id, lots):
        client.audit.capacity_release_failures += 1
        return False

    completed = 0
    for lot_number in range(1, lots + 1):
        before = client.positions()
        client.use_converter_once(action)
        confirmed, observed, expected = wait_for_converter_lot(client, before, action)
        client.audit.action(
            state=client.context_state,
            event="PRE_TENDER_CAPACITY_RELEASE_LOT",
            module="CONVERTER",
            tender_id=tender_id,
            requested_quantity=CONVERTER_LOT,
            filled_quantity=CONVERTER_LOT if confirmed else 0,
            status="CONFIRMED" if confirmed else "POSITION_MISMATCH",
            details={
                "action": action,
                "lot_number": lot_number,
                "expected_positions": expected,
                "observed_positions": observed,
            },
        )
        if not confirmed:
            client.audit.capacity_release_failures += 1
            logging.critical(
                "CAPACITY RELEASE FAILED after %d/%d lots; tender #%d not accepted.",
                completed,
                lots,
                tender_id,
            )
            hedge_fx_to_target(client, force=True)
            return True
        completed += 1
        client.audit.capacity_release_lots_completed += 1

    hedge_fx_to_target(client, force=True)
    fresh_state = load_state(client)
    client.set_state_context(fresh_state)
    same_tender = next(
        (
            row for row in client.tenders()
            if int(row.get("tender_id", -1)) == tender_id
        ),
        None,
    )
    if same_tender is None:
        client.audit.capacity_release_failures += 1
        client.audit.action(
            state=fresh_state,
            event="PRE_TENDER_CAPACITY_RELEASE",
            module="TENDER",
            tender_id=tender_id,
            status="TENDER_EXPIRED_AFTER_RELEASE",
            message="Capacity was freed, but the tender was no longer available.",
        )
        return True
    evaluate_and_maybe_execute_tender(
        client,
        fresh_state,
        same_tender,
        allow_capacity_release=False,
    )
    # Capacity-release orders were submitted even if the refreshed tender no
    # longer qualifies, so the main loop must not start another strategy in
    # this same iteration.
    return True


def log_tender_route(
    audit: AuditLogger,
    state: MarketState,
    tender_id: Any,
    candidate: Optional[Candidate],
    route: str,
) -> None:
    if candidate is None:
        audit.action(
            state=state,
            event="TENDER_ROUTE",
            module="TENDER",
            label=route,
            tender_id=tender_id,
            status="UNAVAILABLE",
        )
        return

    audit.action(
        state=state,
        event="TENDER_ROUTE",
        module="TENDER",
        label=candidate.label,
        tender_id=tender_id,
        requested_quantity=candidate.quantity,
        average_edge_cad=candidate.average_edge_cad,
        expected_pnl_cad=candidate.total_pnl_cad,
        score_cad=candidate.score_cad,
        coverage=candidate.coverage,
        status="EVALUATED",
        message=candidate.note,
        details={
            "route": candidate.kind,
            "direct_unwind_quantity": candidate.direct_unwind_quantity,
            "basket_hedge_quantity": candidate.basket_hedge_quantity,
            "converter_quantity": candidate.converter_quantity,
            "converter_action": candidate.converter_action,
            "converter_uses": candidate.converter_uses,
            "converter_cost_cad": candidate.converter_cost_cad,
            "requires_converter": candidate.requires_converter,
        },
    )


def evaluate_and_maybe_execute_tender(
    client: RITClient,
    state: MarketState,
    tender: dict,
    *,
    allow_capacity_release: bool = True,
) -> bool:
    tender_id = tender.get("tender_id", "?")

    if not bool(tender.get("is_fixed_bid", False)):
        client.audit.action(
            state=state,
            event="TENDER_SKIPPED",
            module="TENDER",
            tender_id=tender_id,
            status="COMPETITIVE",
            message=(
                "Competitive tender requires a submitted bid price. "
                "This strategy only automates fixed-price tenders."
            ),
            details={"tender": tender},
        )
        return False

    if tender.get("price") is None:
        client.audit.action(
            state=state,
            event="TENDER_REJECTED",
            module="TENDER",
            tender_id=tender_id,
            status="INVALID",
            message="Fixed tender did not contain a price",
            details={"tender": tender},
        )
        return False

    tender_action = str(tender.get("action", "")).upper()

    direct = tender_direct_candidate(state, tender)
    basket = tender_basket_candidate(state, tender)
    hybrid = tender_hybrid_candidate(state, tender)
    converter = converter_candidate(
        state,
        basket,
        tender_action,
    )
    mixed_converter = mixed_converter_candidate(
        state,
        tender,
        ignore_risk=allow_capacity_release,
    )

    log_tender_route(
        client.audit,
        state,
        tender_id,
        direct,
        "Direct RITC unwind",
    )
    log_tender_route(
        client.audit,
        state,
        tender_id,
        basket,
        "BULL/BEAR basket hedge",
    )
    log_tender_route(
        client.audit,
        state,
        tender_id,
        hybrid,
        "Risk-aware direct + basket hybrid",
    )
    log_tender_route(
        client.audit,
        state,
        tender_id,
        converter,
        "Automated converter",
    )
    log_tender_route(
        client.audit,
        state,
        tender_id,
        mixed_converter,
        "Mixed direct + automated converter",
    )

    eligible: List[Candidate] = []
    route_diagnostics: List[Dict[str, Any]] = []
    mixed_direction_ok = bool(
        mixed_converter is not None
        and automated_converter_action_allowed(
            mixed_converter.converter_action
        )
    )
    route_specs = [
        (
            "DIRECT",
            direct,
            (
                ENABLE_TENDER_DIRECT_UNWIND
                and direct is not None
                and direct.kind == "TENDER_DIRECT"
            ),
            state.seconds_remaining > STOP_NEW_TENDER_DIRECT_SECONDS,
            True,
        ),
        (
            "BASKET",
            basket,
            ENABLE_TENDER_BASKET_HEDGE,
            state.seconds_remaining > STOP_NEW_TENDER_BASKET_SECONDS,
            True,
        ),
        (
            "HYBRID",
            hybrid,
            ENABLE_TENDER_HYBRID_ROUTE,
            state.seconds_remaining > STOP_NEW_TENDER_BASKET_SECONDS,
            True,
        ),
        (
            "MIXED_CONVERTER",
            mixed_converter,
            (
                ENABLE_MIXED_CONVERTER_ROUTE
                and ENABLE_AUTOMATED_CONVERTER
                and (
                    MAX_MIXED_CONVERTER_TENDERS_PER_RUN == 0
                    or client.audit.mixed_converter_tenders_started
                    < MAX_MIXED_CONVERTER_TENDERS_PER_RUN
                )
                and mixed_direction_ok
            ),
            state.seconds_remaining > STOP_NEW_TENDER_BASKET_SECONDS,
            mixed_direction_ok,
        ),
    ]

    for (
        route_name,
        route_candidate,
        enabled,
        time_ok,
        direction_ok,
    ) in route_specs:
        if (
            route_candidate is not None
            and enabled
            and time_ok
            and direction_ok
            and route_candidate.quantity > 0
            and route_candidate.coverage >= 1.0
            and bool(route_candidate.legs)
            and math.isfinite(route_candidate.score_cad)
            and math.isfinite(route_candidate.total_pnl_cad)
            and not tender_risk_allowed(state, tender, route_candidate)
            and allow_capacity_release
            and ENABLE_PRE_TENDER_CAPACITY_RELEASE
            and ENABLE_AUTOMATED_CONVERTER
            and (not LIVE_TRADING or ARM_LIVE_AUTOMATED_CONVERTER)
            and state.seconds_remaining
            > MIN_SECONDS_FOR_PRE_TENDER_CAPACITY_RELEASE
        ):
            release_variant = capacity_release_variant(
                state,
                tender,
                route_candidate,
            )
            if (
                release_variant is not None
                and automated_converter_action_allowed(
                    release_variant.capacity_release_action
                )
            ):
                route_candidate = release_variant
        edge_ok = bool(
            route_candidate is not None
            and route_candidate.average_edge_cad >= MIN_TENDER_NET_EDGE_CAD
        )
        pnl_ok = bool(
            route_candidate is not None
            and route_candidate.score_cad >= MIN_TENDER_TOTAL_PNL_CAD
        )
        risk_ok = bool(
            route_candidate is not None
            and (
                route_candidate.capacity_release_lots > 0
                or tender_risk_allowed(state, tender, route_candidate)
            )
        )
        route_eligible = bool(
            enabled
            and time_ok
            and route_candidate is not None
            and edge_ok
            and pnl_ok
            and risk_ok
        )
        route_diagnostics.append({
            "route": route_name,
            "candidate_exists": route_candidate is not None,
            "enabled": enabled,
            "direction_ok": direction_ok,
            "time_ok": time_ok,
            "edge_ok": edge_ok,
            "score_ok": pnl_ok,
            "risk_ok": risk_ok,
            "eligible": route_eligible,
            "average_edge_cad": (
                route_candidate.average_edge_cad
                if route_candidate is not None else None
            ),
            "expected_pnl_cad": (
                route_candidate.total_pnl_cad
                if route_candidate is not None else None
            ),
            "score_cad": (
                route_candidate.score_cad
                if route_candidate is not None else None
            ),
        })
        if route_eligible and route_candidate is not None:
            eligible.append(route_candidate)

    if not eligible:
        if active_dashboard is not None:
            active_dashboard.set_tender(
                tender,
                [direct, basket, hybrid, converter, mixed_converter],
                "REJECTED — no complete profitable route",
            )
        client.audit.action(
            state=state,
            event="TENDER_REJECTED",
            module="TENDER",
            tender_id=tender_id,
            status="NO_ELIGIBLE_ROUTE",
            message=(
                "No fully hedgeable route met edge, P&L, "
                "time, and risk requirements."
            ),
            details={
                "tender": tender,
                "route_diagnostics": route_diagnostics,
                "thresholds": {
                    "minimum_edge_cad": MIN_TENDER_NET_EDGE_CAD,
                    "minimum_score_cad": MIN_TENDER_TOTAL_PNL_CAD,
                    "automated_converter_test_action":
                        AUTOMATED_CONVERTER_TEST_ACTION,
                    "tender_transient_gross_limit":
                        MAX_TENDER_TRANSIENT_WEIGHTED_GROSS,
                    "tender_transient_abs_net_limit":
                        MAX_TENDER_TRANSIENT_ABS_WEIGHTED_NET,
                },
            },
        )
        return False

    chosen = max(
        eligible,
        key=lambda candidate: candidate.score_cad,
    )

    if chosen.capacity_release_lots > 0:
        client.audit.tenders_qualified += 1
        if active_dashboard is not None:
            active_dashboard.set_tender(
                tender,
                [direct, basket, hybrid, converter, mixed_converter],
                f"FREEING CAPACITY — {chosen.label}",
            )
        if not AUTO_ACCEPT_FIXED_TENDERS or not LIVE_TRADING:
            client.audit.action(
                state=state,
                event="TENDER_QUALIFIED",
                module="TENDER",
                label=chosen.label,
                tender_id=tender_id,
                status=(
                    "AUTO_ACCEPT_DISABLED"
                    if not AUTO_ACCEPT_FIXED_TENDERS
                    else "DRY_RUN_CAPACITY_RELEASE"
                ),
            )
            return False
        if not ARM_LIVE_AUTOMATED_CONVERTER:
            client.audit.action(
                state=state,
                event="TENDER_QUALIFIED",
                module="TENDER",
                label=chosen.label,
                tender_id=tender_id,
                status="CAPACITY_RELEASE_NOT_ARMED",
            )
            return False
        return execute_capacity_release(
            client,
            state,
            tender,
            chosen,
        )

    client.audit.tenders_qualified += 1

    if active_dashboard is not None:
        active_dashboard.set_tender(
            tender,
            [direct, basket, hybrid, converter, mixed_converter],
            f"QUALIFIED — {chosen.label}",
        )

    if not AUTO_ACCEPT_FIXED_TENDERS:
        client.audit.action(
            state=state,
            event="TENDER_QUALIFIED",
            module="TENDER",
            label=chosen.label,
            tender_id=tender_id,
            status="AUTO_ACCEPT_DISABLED",
        )
        return False

    if (
        chosen.requires_converter
        and LIVE_TRADING
        and not ARM_LIVE_AUTOMATED_CONVERTER
    ):
        message = (
            "Profitable mixed converter route found, but "
            "ARM_LIVE_AUTOMATED_CONVERTER is False. Tender not accepted."
        )
        logging.critical("%s", message)
        client.audit.action(
            state=state,
            event="TENDER_QUALIFIED",
            module="TENDER",
            label=chosen.label,
            tender_id=tender_id,
            status="AUTOMATED_CONVERTER_NOT_ARMED",
            message=message,
        )
        if active_dashboard is not None:
            active_dashboard.set_tender(
                tender,
                [direct, basket, hybrid, converter, mixed_converter],
                "QUALIFIED, NOT ACCEPTED — automated converter is not armed",
            )
            active_dashboard.push_event("CRITICAL", message)
        return False

    if (
        chosen.requires_converter
        and LIVE_TRADING
        and not client.converter_preflight(chosen.converter_action)
    ):
        message = (
            "Converter preflight failed before tender acceptance. "
            "Tender was not accepted and no hedge orders were submitted."
        )
        client.audit.action(
            state=state,
            event="TENDER_QUALIFIED",
            module="TENDER",
            label=chosen.label,
            tender_id=tender_id,
            status="CONVERTER_PREFLIGHT_FAILED",
            message=message,
        )
        if active_dashboard is not None:
            active_dashboard.set_tender(
                tender,
                [direct, basket, hybrid, converter, mixed_converter],
                "QUALIFIED, NOT ACCEPTED — converter preflight failed",
            )
            active_dashboard.push_event("CRITICAL", message)
        return False

    return execute_tender_candidate(
        client,
        state,
        tender,
        chosen,
        converter,
    )


def direct_inventory_reduction_capacity(
    state: MarketState,
    direction: str,
) -> int:
    """Largest matched quantity that reduces all three open arb legs.

    The cap prevents a late trade from crossing through flat and opening a
    new position in the opposite direction.
    """
    bull = state.positions[BULL]
    bear = state.positions[BEAR]
    ritc = state.positions[RITC]

    if direction == "ETF_CHEAP":
        # BUY RITC / SELL basket reduces +BULL, +BEAR, -RITC.
        return max(0, min(bull, bear, -ritc))

    if direction == "ETF_RICH":
        # SELL RITC / BUY basket reduces -BULL, -BEAR, +RITC.
        return max(0, min(-bull, -bear, ritc))

    return 0


def scan_direct_arbitrage(
    client: RITClient,
    state: MarketState,
    reduction_only: bool = False,
) -> Optional[Candidate]:
    results = []

    for direction in ("ETF_CHEAP", "ETF_RICH"):
        quantity_cap = MAX_DIRECT_QTY_PER_ACTION

        if reduction_only:
            quantity_cap = min(
                quantity_cap,
                direct_inventory_reduction_capacity(state, direction),
            )

        if quantity_cap < MIN_DIRECT_QTY:
            candidate = None
            profitable_depth = 0
            reason = (
                "Late-period gate: direction does not reduce matched inventory"
            )
        else:
            candidate, profitable_depth, reason = evaluate_direct_candidate(
                state,
                direction,
                max_quantity=quantity_cap,
            )

        client.audit.action(
            state=state,
            event="DIRECT_SCAN",
            module="DIRECT_ARB",
            label=direction,
            requested_quantity=(
                candidate.quantity
                if candidate is not None
                else profitable_depth
            ),
            average_edge_cad=(
                candidate.average_edge_cad
                if candidate is not None
                else ""
            ),
            expected_pnl_cad=(
                candidate.total_pnl_cad
                if candidate is not None
                else ""
            ),
            score_cad=(
                candidate.score_cad
                if candidate is not None
                else ""
            ),
            status=(
                "ELIGIBLE"
                if candidate is not None
                else "NO_ACTION"
            ),
            message=reason,
            details={
                "direction": direction,
                "profitable_visible_quantity": profitable_depth,
                "reduction_only": reduction_only,
                "quantity_cap": quantity_cap,
                "matched_arb_inventory": matched_arb_inventory(
                    state.positions
                ),
                "max_open_matched_arb_qty": MAX_OPEN_MATCHED_ARB_QTY,
            },
        )

        if candidate is not None:
            results.append(candidate)

    if not results:
        return None

    return max(
        results,
        key=lambda candidate: candidate.score_cad,
    )


def preflight_direct_candidate(
    client: RITClient,
    confirmed_candidate: Candidate,
) -> Tuple[
    Optional[MarketState],
    Optional[Candidate],
    str,
    Dict[str, Any],
]:
    """Download a fresh state and revalue only the confirmed direction."""
    fresh_state, metrics = load_direct_preflight_state(client)
    client.set_state_context(fresh_state)

    if fresh_state.status != "ACTIVE":
        return fresh_state, None, "Case is no longer active", metrics

    if fresh_state.seconds_remaining <= STOP_ALL_NEW_ORDERS_SECONDS:
        return (
            fresh_state,
            None,
            "Inside the all-orders stop window",
            metrics,
        )

    if fresh_state.seconds_remaining <= STOP_ALL_DIRECT_ARB_SECONDS:
        return (
            fresh_state,
            None,
            "Inside the direct-arbitrage completion stop window",
            metrics,
        )

    reduction_only = (
        fresh_state.seconds_remaining <= STOP_NEW_DIRECT_ARB_SECONDS
    )
    quantity_cap = min(
        MAX_DIRECT_QTY_PER_ACTION,
        confirmed_candidate.quantity,
    )
    if reduction_only:
        quantity_cap = min(
            quantity_cap,
            direct_inventory_reduction_capacity(
                fresh_state,
                confirmed_candidate.direction,
            ),
        )

    fresh_candidate, profitable_depth, reason = evaluate_direct_candidate(
        fresh_state,
        confirmed_candidate.direction,
        max_quantity=quantity_cap,
    )
    if fresh_candidate is None:
        return (
            fresh_state,
            None,
            f"Fresh valuation rejected signal: {reason}; "
            f"profitable depth={profitable_depth}",
            metrics,
        )

    edge_drift = (
        confirmed_candidate.average_edge_cad
        - fresh_candidate.average_edge_cad
    )
    reduction_capacity = direct_inventory_reduction_capacity(
        fresh_state,
        confirmed_candidate.direction,
    )
    fully_inventory_reducing = (
        reduction_capacity >= fresh_candidate.quantity
    )

    # A still-profitable trade that closes existing matched inventory lowers
    # risk. Do not reject it solely because the edge moved by more than the
    # entry drift tolerance; the fresh candidate has already passed the live
    # edge, total-P&L, depth, and risk checks above.
    if (
        edge_drift > MAX_ADVERSE_EDGE_DRIFT_CAD
        and not fully_inventory_reducing
    ):
        return (
            fresh_state,
            None,
            "Fresh edge deteriorated by "
            f"{edge_drift:.4f} CAD/share, exceeding "
            f"{MAX_ADVERSE_EDGE_DRIFT_CAD:.4f}",
            metrics,
        )

    if (
        edge_drift > MAX_ADVERSE_EDGE_DRIFT_CAD
        and fully_inventory_reducing
    ):
        return (
            fresh_state,
            fresh_candidate,
            "Fresh confirmation passed: inventory-reducing trade "
            "remains profitable despite adverse edge drift",
            metrics,
        )

    return (
        fresh_state,
        fresh_candidate,
        "Fresh confirmation passed",
        metrics,
    )


