class RITClient:
    def __init__(
        self,
        api_endpoint: str,
        username: str,
        password: str,
        audit: AuditLogger,
    ):
        self.api_endpoint = api_endpoint.rstrip("/")
        self.audit = audit

        self.session = requests.Session()
        self.session.auth = (username, password)
        self.session.headers.update({"Accept": "application/json"})

        # Each fast-snapshot endpoint owns its own Session.  No Session is
        # used by two worker threads at the same time, avoiding concurrent
        # access to requests.Session while retaining persistent connections.
        self.fast_sessions: Dict[str, requests.Session] = {}
        for key in (
            "case",
            "securities",
            "tenders",
            BULL,
            BEAR,
            RITC,
            USD,
        ):
            session = requests.Session()
            session.auth = (username, password)
            session.headers.update({"Accept": "application/json"})
            self.fast_sessions[key] = session

        self.context_state: Optional[MarketState] = None
        self.converter_assets: Dict[str, Dict[str, Any]] = {}
        self.converter_leases: Dict[str, Dict[str, Any]] = {}

    def set_state_context(self, state: Optional[MarketState]) -> None:
        self.context_state = state

    @staticmethod
    def _rate_limit_wait(response: requests.Response) -> float:
        header_wait = 0.0
        body_wait = 0.0

        try:
            header_wait = float(response.headers.get("Retry-After", 0) or 0)
        except (TypeError, ValueError):
            pass

        try:
            payload = response.json()
            body_wait = float(payload.get("wait", 0) or 0)
        except (ValueError, TypeError, AttributeError):
            pass

        return max(header_wait, body_wait, 0.05)

    def request_json(
        self,
        method: str,
        endpoint: str,
        params: Optional[dict] = None,
        acceptable_statuses: Optional[Sequence[int]] = None,
    ) -> Any:
        method = method.upper()
        endpoint = endpoint.lstrip("/")
        url = f"{self.api_endpoint}/{endpoint}"

        for attempt in range(1, MAX_API_RETRIES + 1):
            started = time.monotonic()

            try:
                response = self.session.request(
                    method,
                    url,
                    params=params,
                    timeout=HTTP_TIMEOUT_SECONDS,
                )
            except requests.RequestException as exc:
                # Do not blindly retry an ambiguous POST. The server may have
                # received it even if the response was lost.
                self.audit.error_events += 1
                self.audit.action(
                    state=self.context_state,
                    event="API_NETWORK_ERROR",
                    module="API",
                    status="ERROR",
                    message=str(exc),
                    details={
                        "method": method,
                        "endpoint": endpoint,
                        "params": params,
                    },
                )
                raise

            latency = time.monotonic() - started

            if response.status_code == 401:
                raise ApiException(
                    "DMA authentication failed. Check your Trader ID and password."
                )

            if response.status_code == 429:
                wait_time = self._rate_limit_wait(response)
                self.audit.rate_limit_events += 1
                self.audit.action(
                    state=self.context_state,
                    event="RATE_LIMIT",
                    module="API",
                    status="RETRYING",
                    message=f"Waiting {wait_time:.3f} seconds",
                    details={
                        "method": method,
                        "endpoint": endpoint,
                        "attempt": attempt,
                        "latency_seconds": latency,
                    },
                )
                logging.warning(
                    "DMA rate limit on %s %s; waiting %.3fs",
                    method,
                    endpoint,
                    wait_time,
                )
                time.sleep(wait_time)
                continue

            if response.status_code in set(acceptable_statuses or ()):
                return {
                    "_http_status": response.status_code,
                    "_accepted_terminal_response": True,
                }

            if not response.ok:
                self.audit.error_events += 1
                self.audit.action(
                    state=self.context_state,
                    event="API_HTTP_ERROR",
                    module="API",
                    status=str(response.status_code),
                    message=response.text[:1000],
                    details={
                        "method": method,
                        "endpoint": endpoint,
                        "params": params,
                        "latency_seconds": latency,
                    },
                )
                raise ApiException(
                    f"{method} {endpoint} failed with HTTP "
                    f"{response.status_code}: {response.text}"
                )

            if response.status_code == 204 or not response.content:
                return {}

            try:
                return response.json()
            except ValueError as exc:
                raise ApiException(
                    f"{method} {endpoint} returned invalid JSON"
                ) from exc

        raise ApiException(
            f"{method} {endpoint} remained rate-limited after "
            f"{MAX_API_RETRIES} attempts"
        )

    def case(self) -> dict:
        payload = self.request_json("GET", "case")
        if not isinstance(payload, dict):
            raise ApiException("GET /case did not return a JSON object")
        return payload

    def limits(self) -> List[dict]:
        payload = self.request_json("GET", "limits")
        return payload if isinstance(payload, list) else []

    def securities(self) -> List[dict]:
        payload = self.request_json("GET", "securities")
        return payload if isinstance(payload, list) else []

    def trader(self) -> Any:
        """Return account-level fields, including simulator P&L/NLV."""
        return self.request_json("GET", "trader")

    @staticmethod
    def positions_from_rows(rows: Sequence[dict]) -> Dict[str, int]:
        positions = {
            row["ticker"]: int(round(float(row.get("position", 0) or 0)))
            for row in rows
            if row.get("ticker")
        }

        for ticker in (CAD, USD, BULL, BEAR, RITC):
            positions.setdefault(ticker, 0)

        return positions

    def positions(self) -> Dict[str, int]:
        return self.positions_from_rows(self.securities())

    @staticmethod
    def _remaining_quantity(order: dict) -> int:
        quantity = float(order.get("quantity", 0) or 0)
        filled = float(order.get("quantity_filled", 0) or 0)
        return max(0, int(math.floor(quantity - filled)))

    @staticmethod
    def _aggregate_levels(
        raw_orders: Iterable[dict],
        reverse: bool,
    ) -> List[Level]:
        by_price: Dict[float, int] = {}

        for order in raw_orders:
            status = str(order.get("status", "OPEN")).upper()

            if status not in ("OPEN", ""):
                continue

            price = float(order.get("price", 0) or 0)
            remaining = RITClient._remaining_quantity(order)

            if price > 0 and remaining > 0:
                by_price[price] = by_price.get(price, 0) + remaining

        return [
            Level(price=price, quantity=by_price[price])
            for price in sorted(by_price, reverse=reverse)
        ]

    def book(self, ticker: str) -> Book:
        payload = self.request_json(
            "GET",
            "securities/book",
            params={
                "ticker": ticker,
                "limit": BOOK_ORDER_LIMIT,
            },
        )

        return self.book_from_payload(ticker, payload)

    def book_from_payload(self, ticker: str, payload: Any) -> Book:
        if not isinstance(payload, dict):
            raise ApiException(
                f"GET /securities/book for {ticker} did not return an object"
            )

        raw_bids = payload.get("bids", payload.get("bid", [])) or []
        raw_asks = payload.get("asks", payload.get("ask", [])) or []

        return Book(
            ticker=ticker,
            bids=self._aggregate_levels(raw_bids, reverse=True),
            asks=self._aggregate_levels(raw_asks, reverse=False),
        )

    def _fast_get_json(
        self,
        key: str,
        endpoint: str,
        params: Optional[dict] = None,
    ) -> Tuple[Any, Dict[str, Any]]:
        """GET one preflight endpoint through its dedicated Session."""
        endpoint = endpoint.lstrip("/")
        url = f"{self.api_endpoint}/{endpoint}"
        started = time.monotonic()

        for attempt in range(1, MAX_API_RETRIES + 1):
            response = self.fast_sessions[key].get(
                url,
                params=params,
                timeout=HTTP_TIMEOUT_SECONDS,
            )

            if response.status_code == 401:
                raise ApiException(
                    "DMA authentication failed during fast direct preflight"
                )

            if response.status_code == 429:
                wait_time = self._rate_limit_wait(response)
                self.audit.rate_limit_events += 1
                logging.warning(
                    "DMA rate limit during fast preflight on %s; "
                    "waiting %.3fs",
                    endpoint,
                    wait_time,
                )
                time.sleep(wait_time)
                continue

            if not response.ok:
                raise ApiException(
                    f"GET {endpoint} failed during fast preflight with HTTP "
                    f"{response.status_code}: {response.text[:500]}"
                )

            if response.status_code == 204 or not response.content:
                payload: Any = {}
            else:
                try:
                    payload = response.json()
                except ValueError as exc:
                    raise ApiException(
                        f"GET {endpoint} returned invalid JSON during "
                        "fast preflight"
                    ) from exc

            finished = time.monotonic()
            return payload, {
                "attempts": attempt,
                "latency_ms": (finished - started) * 1000.0,
                "completed_monotonic": finished,
            }

        raise ApiException(
            f"GET {endpoint} remained rate-limited during fast preflight"
        )

    def fast_direct_snapshot_payloads(
        self,
        *,
        include_tenders: bool = False,
    ) -> Tuple[Dict[str, Any], Dict[str, Any]]:
        """Fetch a near-synchronized strategy state concurrently."""
        specs: Dict[str, Tuple[str, Optional[dict]]] = {
            "case": ("case", None),
            "securities": ("securities", None),
            BULL: (
                "securities/book",
                {"ticker": BULL, "limit": BOOK_ORDER_LIMIT},
            ),
            BEAR: (
                "securities/book",
                {"ticker": BEAR, "limit": BOOK_ORDER_LIMIT},
            ),
            RITC: (
                "securities/book",
                {"ticker": RITC, "limit": BOOK_ORDER_LIMIT},
            ),
            USD: (
                "securities/book",
                {"ticker": USD, "limit": BOOK_ORDER_LIMIT},
            ),
        }
        if include_tenders:
            specs["tenders"] = ("tenders", None)
        started = time.monotonic()
        payloads: Dict[str, Any] = {}
        endpoint_metrics: Dict[str, Dict[str, Any]] = {}

        with ThreadPoolExecutor(
            max_workers=min(
                (
                    FAST_STRATEGY_SNAPSHOT_WORKERS
                    if include_tenders
                    else FAST_DIRECT_PREFLIGHT_WORKERS
                ),
                len(specs),
            ),
            thread_name_prefix="ritcx-preflight",
        ) as executor:
            futures = {
                executor.submit(
                    self._fast_get_json,
                    key,
                    endpoint,
                    params,
                ): key
                for key, (endpoint, params) in specs.items()
            }

            for future in as_completed(futures):
                key = futures[future]
                payload, metrics = future.result()
                payloads[key] = payload
                endpoint_metrics[key] = metrics

        finished = time.monotonic()
        completion_times = [
            float(metrics["completed_monotonic"])
            for metrics in endpoint_metrics.values()
        ]
        latency_by_endpoint = {
            key: round(float(metrics["latency_ms"]), 3)
            for key, metrics in endpoint_metrics.items()
        }

        return payloads, {
            "preflight_mode": "CONCURRENT",
            "preflight_fetch_ms": round((finished - started) * 1000.0, 3),
            "preflight_endpoint_latency_ms": latency_by_endpoint,
            "preflight_completion_span_ms": round(
                (max(completion_times) - min(completion_times)) * 1000.0,
                3,
            ),
        }

    def _fast_market_order(
        self,
        ticker: str,
        action: str,
        quantity: int,
        reference_price: Optional[float],
    ) -> OrderResult:
        """Submit one direct-arbitrage leg on the ticker's own Session.

        This method deliberately performs no logging from its worker thread;
        the caller serializes all audit writes after the futures complete.
        """
        if not LIVE_TRADING:
            return OrderResult(
                ticker=ticker,
                action=action,
                requested=quantity,
                filled=quantity,
                vwap=None,
                status="DRY_RUN",
                reference_price=reference_price,
            )

        endpoint = "orders"
        url = f"{self.api_endpoint}/{endpoint}"
        params = {
            "ticker": ticker,
            "type": "MARKET",
            "quantity": int(quantity),
            "action": action.upper(),
        }
        for _attempt in range(1, MAX_API_RETRIES + 1):
            response = self.fast_sessions[ticker].post(
                url,
                params=params,
                timeout=HTTP_TIMEOUT_SECONDS,
            )
            if response.status_code == 401:
                raise ApiException("DMA authentication failed during direct execution")
            if response.status_code == 429:
                time.sleep(self._rate_limit_wait(response))
                continue
            if not response.ok:
                raise ApiException(
                    f"POST orders failed for {ticker} with HTTP "
                    f"{response.status_code}: {response.text[:500]}"
                )
            payload = response.json() if response.content else {}
            return self.order_result_from_payload(
                ticker,
                action,
                quantity,
                payload,
                reference_price=reference_price,
            )
        raise ApiException(f"Direct order for {ticker} remained rate-limited")

