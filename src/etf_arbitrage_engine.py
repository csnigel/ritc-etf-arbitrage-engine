def tender_direct_candidate(
    state: MarketState,
    tender: dict,
) -> Optional[Candidate]:
    quantity = int(round(float(tender.get("quantity", 0) or 0)))
    price_raw = tender.get("price")
    action = str(tender.get("action", "")).upper()

    if (
        quantity <= 0
        or price_raw is None
        or action not in ("BUY", "SELL")
    ):
        return None

    tender_price = float(price_raw)
    unwind_action = "SELL" if action == "BUY" else "BUY"

    levels = (
        state.books[RITC].bids
        if unwind_action == "SELL"
        else state.books[RITC].asks
    )

    cursor = DepthCursor(levels)

    # Positive USD tender profit is conservatively converted at the USD bid.
    fx_rate = state.books[USD].best_bid

    if fx_rate <= 0:
        return None

    left = quantity
    slices: List[Slice] = []

    while left > 0 and cursor.valid:
        used = min(left, int(cursor.remaining))

        if action == "BUY":
            usd_profit_per_share = cursor.price - tender_price
        else:
            usd_profit_per_share = tender_price - cursor.price

        # Only the market RITC unwind pays a fee.  It is a USD fee and must
        # be deducted before the remaining USD profit is converted to CAD.
        edge = (
            usd_profit_per_share - EQUITY_MARKET_FEE_PER_SHARE
        ) * fx_rate

        if edge < MIN_TENDER_NET_EDGE_CAD:
            break

        slices.append(
            Slice(
                quantity=used,
                net_edge_cad=edge,
            )
        )

        cursor.consume(used)
        left -= used

    covered = slices_quantity(slices)
    pnl = slices_pnl(slices)
    coverage = covered / quantity if quantity else 0.0

    if covered < quantity:
        return Candidate(
            kind="TENDER_DIRECT_PARTIAL",
            label=f"Tender {action}; partial direct RITC unwind",
            quantity=covered,
            total_pnl_cad=pnl,
            average_edge_cad=pnl / covered if covered else 0.0,
            score_cad=-math.inf,
            coverage=coverage,
            note="Full tender cannot currently be unwound profitably.",
            direct_unwind_quantity=covered,
        )

    return Candidate(
        kind="TENDER_DIRECT",
        label=f"Tender {action}; {unwind_action} RITC immediately",
        quantity=quantity,
        total_pnl_cad=pnl,
        average_edge_cad=pnl / quantity,
        score_cad=pnl,
        legs=[(RITC, unwind_action, quantity)],
        direct_unwind_quantity=quantity,
    )


def tender_direct_exact_slices(
    state: MarketState,
    tender_action: str,
    tender_price: float,
    quantity: int,
) -> Optional[List[Slice]]:
    """Value an exact direct residual, including marginally negative depth.

    A mixed route is accepted on its combined economics, so the direct
    remainder does not independently need to pass the tender edge threshold.
    It does, however, require visible depth for every residual share.
    """
    if quantity <= 0:
        return []

    unwind_action = "SELL" if tender_action == "BUY" else "BUY"
    levels = (
        state.books[RITC].bids
        if unwind_action == "SELL"
        else state.books[RITC].asks
    )
    cursor = DepthCursor(levels)
    left = int(quantity)
    slices: List[Slice] = []

    while left > 0 and cursor.valid:
        used = min(left, int(cursor.remaining))
        if used <= 0:
            break

        if tender_action == "BUY":
            usd_profit = cursor.price - tender_price
        else:
            usd_profit = tender_price - cursor.price

        usd_profit -= EQUITY_MARKET_FEE_PER_SHARE
        fx_rate = (
            state.books[USD].best_bid
            if usd_profit >= 0
            else state.books[USD].best_ask
        )
        if fx_rate <= 0 or not math.isfinite(fx_rate):
            return None

        slices.append(Slice(used, usd_profit * fx_rate))
        cursor.consume(used)
        left -= used

    return slices if left == 0 else None


def tender_basket_slices(
    state: MarketState,
    action: str,
    tender_price_usd: float,
    quantity: int,
) -> List[Slice]:
    buy_tender = action == "BUY"

    bull = DepthCursor(
        state.books[BULL].bids
        if buy_tender
        else state.books[BULL].asks
    )
    bear = DepthCursor(
        state.books[BEAR].bids
        if buy_tender
        else state.books[BEAR].asks
    )
    fx = DepthCursor(
        state.books[USD].asks
        if buy_tender
        else state.books[USD].bids
    )

    output: List[Slice] = []
    used_total = 0

    while (
        all(cursor.valid for cursor in (bull, bear, fx))
        and used_total < quantity
    ):
        fx_share_capacity = int(
            math.floor(fx.remaining / tender_price_usd)
        )

        take = min(
            int(bull.remaining),
            int(bear.remaining),
            fx_share_capacity,
            quantity - used_total,
        )

        if take <= 0:
            if fx.valid and fx.remaining > 0:
                fx.consume(fx.remaining)
                continue
            break

        fees = 2.0 * EQUITY_MARKET_FEE_PER_SHARE

        if buy_tender:
            edge = (
                bull.price
                + bear.price
                - tender_price_usd * fx.price
                - fees
            )
        else:
            edge = (
                tender_price_usd * fx.price
                - bull.price
                - bear.price
                - fees
            )

        output.append(
            Slice(
                quantity=take,
                net_edge_cad=edge,
            )
        )

        bull.consume(take)
        bear.consume(take)
        fx.consume(take * tender_price_usd)

        used_total += take

    return output


def tender_basket_candidate(
    state: MarketState,
    tender: dict,
) -> Optional[Candidate]:
    quantity = int(round(float(tender.get("quantity", 0) or 0)))
    price_raw = tender.get("price")
    action = str(tender.get("action", "")).upper()

    if (
        quantity <= 0
        or price_raw is None
        or action not in ("BUY", "SELL")
    ):
        return None

    slices = tender_basket_slices(
        state,
        action,
        float(price_raw),
        quantity,
    )

    if slices_quantity(slices) < quantity:
        return None

    pnl = slices_pnl(slices)

    if action == "BUY":
        legs = [
            (BULL, "SELL", quantity),
            (BEAR, "SELL", quantity),
        ]
    else:
        legs = [
            (BULL, "BUY", quantity),
            (BEAR, "BUY", quantity),
        ]

    late_fraction = 0.0

    if state.seconds_remaining < TENDER_LATE_PENALTY_START_SECONDS:
        late_fraction = (
            TENDER_LATE_PENALTY_START_SECONDS
            - state.seconds_remaining
        ) / TENDER_LATE_PENALTY_START_SECONDS

    risk_penalty = quantity * (
        TENDER_HOLD_RISK_PENALTY_CAD_PER_SHARE
        + late_fraction
        * TENDER_LATE_TIME_PENALTY_CAD_PER_SHARE
    )

    return Candidate(
        kind="TENDER_BASKET",
        label=f"Tender {action}; hedge with BULL+BEAR",
        quantity=quantity,
        total_pnl_cad=pnl,
        average_edge_cad=pnl / quantity,
        score_cad=pnl - risk_penalty,
        legs=legs,
        note=(
            f"Score includes CAD {risk_penalty:,.2f} "
            "hold/time risk penalty."
        ),
        basket_hedge_quantity=quantity,
    )


def tender_basket_risk_penalty(
    state: MarketState,
    quantity: int,
) -> float:
    """Risk-score haircut for the portion left as a basket hedge."""
    late_fraction = 0.0
    if state.seconds_remaining < TENDER_LATE_PENALTY_START_SECONDS:
        late_fraction = (
            TENDER_LATE_PENALTY_START_SECONDS - state.seconds_remaining
        ) / TENDER_LATE_PENALTY_START_SECONDS
    return int(quantity) * (
        TENDER_HOLD_RISK_PENALTY_CAD_PER_SHARE
        + late_fraction * TENDER_LATE_TIME_PENALTY_CAD_PER_SHARE
    )


def tender_hybrid_candidate(
    state: MarketState,
    tender: dict,
    *,
    tender_already_settled: bool = False,
) -> Optional[Candidate]:
    """Optimize a complete tender across direct RITC and basket hedging.

    V12 considered only the two endpoints: 100% direct or 100% basket.  This
    optimizer also tests the quantities between them.  That matters when the
    best direct depth is insufficient but a smaller basket residual fits the
    official transient limits.  Marginal direct shares may be individually
    below the tender threshold; only the fully hedged package must pass the
    configured edge and score tests.
    """
    quantity = int(round(float(tender.get("quantity", 0) or 0)))
    price_raw = tender.get("price")
    action = str(tender.get("action", "")).upper()
    if quantity <= 0 or price_raw is None or action not in ("BUY", "SELL"):
        return None

    tender_price = float(price_raw)
    unwind_action = "SELL" if action == "BUY" else "BUY"
    basket_action = "SELL" if action == "BUY" else "BUY"
    best: Optional[Candidate] = None

    # Endpoints are valued by the dedicated routes.  Search only true hybrids.
    for direct_quantity in range(QTY_STEP, quantity, QTY_STEP):
        basket_quantity = quantity - direct_quantity
        if basket_quantity <= 0:
            continue

        direct_slices = tender_direct_exact_slices(
            state,
            action,
            tender_price,
            direct_quantity,
        )
        if direct_slices is None:
            continue
        basket_slices = tender_basket_slices(
            state,
            action,
            tender_price,
            basket_quantity,
        )
        if slices_quantity(basket_slices) < basket_quantity:
            continue

        accounting_pnl = (
            slices_pnl(direct_slices) + slices_pnl(basket_slices)
        )
        risk_penalty = tender_basket_risk_penalty(
            state,
            basket_quantity,
        )
        legs = [
            (RITC, unwind_action, direct_quantity),
            (BULL, basket_action, basket_quantity),
            (BEAR, basket_action, basket_quantity),
        ]
        candidate = Candidate(
            kind="TENDER_HYBRID",
            label=(
                f"Tender {action}; direct {direct_quantity:,} + "
                f"basket {basket_quantity:,}"
            ),
            quantity=quantity,
            total_pnl_cad=accounting_pnl,
            average_edge_cad=accounting_pnl / quantity,
            score_cad=accounting_pnl - risk_penalty,
            legs=legs,
            note=(
                f"Directly unwind {direct_quantity:,} RITC and basket-hedge "
                f"{basket_quantity:,}; score includes CAD {risk_penalty:,.2f} "
                "hold/time risk penalty on only the basket residual."
            ),
            direct_unwind_quantity=direct_quantity,
            basket_hedge_quantity=basket_quantity,
        )
        risk_ok = (
            accepted_tender_route_risk_allowed(state, candidate)
            if tender_already_settled
            else tender_risk_allowed(state, tender, candidate)
        )
        if not risk_ok:
            continue
        if best is None or candidate.score_cad > best.score_cad:
            best = candidate

    return best


def converter_candidate(
    state: MarketState,
    basket_candidate: Optional[Candidate],
    tender_action: str,
) -> Optional[Candidate]:
    if basket_candidate is None:
        return None

    if basket_candidate.quantity % CONVERTER_LOT != 0:
        return None

    fx_ask = state.books[USD].best_ask

    if not math.isfinite(fx_ask):
        return None

    uses = basket_candidate.quantity // CONVERTER_LOT

    converter_cost_cad = (
        uses
        * CONVERTER_COST_USD_PER_USE
        * fx_ask
    )

    pnl = basket_candidate.total_pnl_cad - converter_cost_cad

    conversion = (
        "REDEEM RITC"
        if tender_action == "BUY"
        else "CREATE RITC"
    )

    return Candidate(
        kind="TENDER_CONVERTER",
        label=f"{basket_candidate.label}; automated {conversion}",
        quantity=basket_candidate.quantity,
        total_pnl_cad=pnl,
        average_edge_cad=pnl / basket_candidate.quantity,
        score_cad=pnl,
        legs=basket_candidate.legs,
        requires_converter=True,
        note=(
            f"Automated route: {uses} verified converter use(s), "
            f"estimated cost CAD {converter_cost_cad:,.2f}."
        ),
        basket_hedge_quantity=basket_candidate.quantity,
        converter_quantity=basket_candidate.quantity,
        converter_action=conversion.split()[0],
        converter_uses=uses,
        converter_cost_cad=converter_cost_cad,
    )


def automated_converter_action_allowed(action: str) -> bool:
    """Return whether this converter direction is armed for the current run."""
    configured = AUTOMATED_CONVERTER_TEST_ACTION.strip().upper()
    normalized = str(action).strip().upper()
    return configured == "BOTH" or normalized == configured


def mixed_converter_candidate(
    state: MarketState,
    tender: dict,
    *,
    tender_already_settled: bool = False,
    ignore_risk: bool = False,
) -> Optional[Candidate]:
    """Find the best full tender plan using direct depth plus converter lots.

    Example: a 98,000-share tender can use an 8,000-share direct RITC unwind
    and nine 10,000-share converter lots.  The candidate includes every market
    fee, executable book depth, FX conversion and the fixed converter charge.
    """
    quantity = int(round(float(tender.get("quantity", 0) or 0)))
    price_raw = tender.get("price")
    action = str(tender.get("action", "")).upper()

    if quantity <= 0 or price_raw is None or action not in ("BUY", "SELL"):
        return None

    fx_ask = state.books[USD].best_ask
    if fx_ask <= 0 or not math.isfinite(fx_ask):
        return None

    tender_price = float(price_raw)
    unwind_action = "SELL" if action == "BUY" else "BUY"
    conversion = "REDEEM" if action == "BUY" else "CREATE"
    best: Optional[Candidate] = None

    maximum_converter_quantity = (
        quantity // CONVERTER_LOT
    ) * CONVERTER_LOT

    for converter_quantity in range(
        CONVERTER_LOT,
        maximum_converter_quantity + 1,
        CONVERTER_LOT,
    ):
        direct_quantity = quantity - converter_quantity
        direct_slices = tender_direct_exact_slices(
            state,
            action,
            tender_price,
            direct_quantity,
        )
        if direct_slices is None:
            continue

        basket_slices = tender_basket_slices(
            state,
            action,
            tender_price,
            converter_quantity,
        )
        if slices_quantity(basket_slices) < converter_quantity:
            continue

        uses = converter_quantity // CONVERTER_LOT
        converter_cost_cad = (
            uses * CONVERTER_COST_USD_PER_USE * fx_ask
        )
        accounting_pnl = (
            slices_pnl(direct_slices)
            + slices_pnl(basket_slices)
            - converter_cost_cad
        )
        manual_risk_penalty = (
            converter_quantity
            * MIXED_CONVERTER_EXECUTION_RISK_PENALTY_CAD_PER_SHARE
        )
        score = accounting_pnl - manual_risk_penalty

        basket_action = "SELL" if action == "BUY" else "BUY"
        legs: List[Tuple[str, str, int]] = []
        if direct_quantity > 0:
            legs.append((RITC, unwind_action, direct_quantity))
        legs.extend([
            (BULL, basket_action, converter_quantity),
            (BEAR, basket_action, converter_quantity),
        ])

        candidate = Candidate(
            kind="TENDER_MIXED_CONVERTER",
            label=(
                f"Tender {action}; direct {direct_quantity:,} + "
                f"automated {conversion} {converter_quantity:,}"
            ),
            quantity=quantity,
            total_pnl_cad=accounting_pnl,
            average_edge_cad=accounting_pnl / quantity,
            score_cad=score,
            legs=legs,
            requires_converter=True,
            note=(
                f"Directly unwind {direct_quantity:,} RITC; hedge and "
                f"automatically {conversion} {converter_quantity:,} RITC "
                f"({uses} converter use(s)). Estimated converter cost "
                f"CAD {converter_cost_cad:,.2f}; execution-risk "
                f"penalty CAD {manual_risk_penalty:,.2f}."
            ),
            direct_unwind_quantity=direct_quantity,
            basket_hedge_quantity=converter_quantity,
            converter_quantity=converter_quantity,
            converter_action=conversion,
            converter_uses=uses,
            converter_cost_cad=converter_cost_cad,
        )

        # Do this inside the optimizer, not only after it returns.  The most
        # profitable converter size may breach transient risk while a smaller
        # number of 10,000-share lots is fully feasible.
        risk_ok = (
            accepted_tender_route_risk_allowed(state, candidate)
            if tender_already_settled
            else tender_risk_allowed(state, tender, candidate)
        )
        if not ignore_risk and not risk_ok:
            continue

        if best is None or candidate.score_cad > best.score_cad:
            best = candidate

    return best


