    def record_books(self, state: MarketState) -> None:
        if self._book_file is None:
            return

        now = time.monotonic()
        if (
            now - self._last_disk_space_check
            >= DISK_SPACE_CHECK_INTERVAL_SECONDS
        ):
            self._last_disk_space_check = now
            if not self._has_book_log_disk_reserve():
                self._disable_log_stream(
                    "_book_file",
                    None,
                    "full_book_depth.jsonl.gz",
                    OSError("disk-space reserve reached"),
                )
                return

        if (
            FULL_BOOK_LOG_INTERVAL_SECONDS > 0
            and now - self.last_book_log < FULL_BOOK_LOG_INTERVAL_SECONDS
        ):
            return

        payload = {
            "timestamp_utc": utc_now(),
            "period": state.period,
            "tick": state.tick,
            "seconds_remaining": state.seconds_remaining,
            "books": {
                ticker: {
                    "bids": [asdict(level) for level in book.bids],
                    "asks": [asdict(level) for level in book.asks],
                }
                for ticker, book in state.books.items()
            },
        }

        try:
            self._book_file.write(json.dumps(payload) + "\n")
            self._book_file.flush()
            self.last_book_log = now
        except OSError as exc:
            self._disable_log_stream(
                "_book_file",
                None,
                "full_book_depth.jsonl.gz",
                exc,
            )

