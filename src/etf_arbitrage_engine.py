def load_state(
    client: RITClient,
    case: Optional[dict] = None,
) -> MarketState:
    case = case or client.case()

    ticks_per_period = int(case.get("ticks_per_period", 300) or 300)
    tick = int(case.get("tick", 0) or 0)

    books = {
        ticker: client.book(ticker)
        for ticker in (BULL, BEAR, RITC, USD)
    }

    security_rows = client.securities()
    positions = client.positions_from_rows(security_rows)

    return MarketState(
        period=int(case.get("period", 0) or 0),
        tick=tick,
        ticks_per_period=ticks_per_period,
        status=str(case.get("status", "STOPPED")).upper(),
        seconds_remaining=max(0, ticks_per_period - tick),
        books=books,
        positions=positions,
        security_rows=security_rows,
    )


def load_direct_preflight_state(
    client: RITClient,
) -> Tuple[MarketState, Dict[str, Any]]:
    """Load a fresh state for direct execution, with a safe fallback."""
    if not ENABLE_FAST_DIRECT_PREFLIGHT:
        started = time.monotonic()
        state = load_state(client)
        return state, {
            "preflight_mode": "SEQUENTIAL",
            "preflight_fetch_ms": round(
                (time.monotonic() - started) * 1000.0,
                3,
            ),
        }

    try:
        payloads, metrics = client.fast_direct_snapshot_payloads()

        case = payloads.get("case")
        security_rows = payloads.get("securities")
        if not isinstance(case, dict):
            raise ApiException(
                "Concurrent preflight GET /case did not return an object"
            )
        if not isinstance(security_rows, list):
            raise ApiException(
                "Concurrent preflight GET /securities did not return a list"
            )

        ticks_per_period = int(
            case.get("ticks_per_period", 300) or 300
        )
        tick = int(case.get("tick", 0) or 0)
        books = {
            ticker: client.book_from_payload(ticker, payloads[ticker])
            for ticker in (BULL, BEAR, RITC, USD)
        }
        state = MarketState(
            period=int(case.get("period", 0) or 0),
            tick=tick,
            ticks_per_period=ticks_per_period,
            status=str(case.get("status", "STOPPED")).upper(),
            seconds_remaining=max(0, ticks_per_period - tick),
            books=books,
            positions=client.positions_from_rows(security_rows),
            security_rows=security_rows,
        )
        return state, metrics

    except (requests.RequestException, ApiException, KeyError) as exc:
        if not FAST_DIRECT_PREFLIGHT_FALLBACK_TO_SEQUENTIAL:
            raise

        logging.warning(
            "Fast direct preflight failed; using safe sequential fallback: %s",
            exc,
        )
        started = time.monotonic()
        state = load_state(client)
        return state, {
            "preflight_mode": "SEQUENTIAL_FALLBACK",
            "preflight_fetch_ms": round(
                (time.monotonic() - started) * 1000.0,
                3,
            ),
            "fast_preflight_error": str(exc),
        }


def load_fast_strategy_state(
    client: RITClient,
) -> Tuple[MarketState, List[dict], Dict[str, Any]]:
    """Load books, positions, case, and tenders on one concurrent pass."""
    payloads, metrics = client.fast_direct_snapshot_payloads(
        include_tenders=True,
    )
    case = payloads.get("case")
    security_rows = payloads.get("securities")
    tender_rows = payloads.get("tenders")
    if not isinstance(case, dict):
        raise ApiException("Fast strategy GET /case returned no object")
    if not isinstance(security_rows, list):
        raise ApiException(
            "Fast strategy GET /securities returned no list"
        )
    if not isinstance(tender_rows, list):
        raise ApiException("Fast strategy GET /tenders returned no list")

    ticks_per_period = int(case.get("ticks_per_period", 300) or 300)
    tick = int(case.get("tick", 0) or 0)
    state = MarketState(
        period=int(case.get("period", 0) or 0),
        tick=tick,
        ticks_per_period=ticks_per_period,
        status=str(case.get("status", "STOPPED")).upper(),
        seconds_remaining=max(0, ticks_per_period - tick),
        books={
            ticker: client.book_from_payload(ticker, payloads[ticker])
            for ticker in (BULL, BEAR, RITC, USD)
        },
        positions=client.positions_from_rows(security_rows),
        security_rows=security_rows,
    )
    metrics = dict(metrics)
    metrics["snapshot_includes_tenders"] = True
    return state, tender_rows, metrics


def weighted_risk(positions: Dict[str, int]) -> Tuple[int, int]:
    bull = int(positions.get(BULL, 0))
    bear = int(positions.get(BEAR, 0))
    ritc = int(positions.get(RITC, 0))

    gross = (
        abs(bull)
        + abs(bear)
        + RITC_POSITION_MULTIPLIER * abs(ritc)
    )

    net = (
        bull
        + bear
        + RITC_POSITION_MULTIPLIER * ritc
    )

    return gross, net


def positions_after(
    positions: Dict[str, int],
    deltas: Dict[str, int],
) -> Dict[str, int]:
    result = dict(positions)

    for ticker, delta in deltas.items():
        result[ticker] = result.get(ticker, 0) + int(delta)

    return result


def risk_allows(
    positions: Dict[str, int],
    deltas: Dict[str, int],
    *,
    max_gross: int = MAX_WEIGHTED_GROSS,
    max_abs_net: int = MAX_ABS_WEIGHTED_NET,
) -> bool:
    projected = positions_after(positions, deltas)
    gross, net = weighted_risk(projected)

    return (
        gross <= max_gross
        and abs(net) <= max_abs_net
    )


def risk_allows_or_reduces(
    positions: Dict[str, int],
    deltas: Dict[str, int],
    *,
    max_gross: int = MAX_WEIGHTED_GROSS,
    max_abs_net: int = MAX_ABS_WEIGHTED_NET,
) -> bool:
    """Allow an over-cap position to move strictly toward lower risk."""
    if risk_allows(
        positions,
        deltas,
        max_gross=max_gross,
        max_abs_net=max_abs_net,
    ):
        return True

    before_gross, before_net = weighted_risk(positions)
    after_gross, after_net = weighted_risk(
        positions_after(positions, deltas)
    )
    return (
        after_gross < before_gross
        and abs(after_net) <= abs(before_net)
        and abs(after_net) <= max_abs_net
    )


def signed_delta(action: str, quantity: int) -> int:
    return quantity if action.upper() == "BUY" else -quantity


def legs_to_deltas(
    legs: Sequence[Tuple[str, str, int]],
) -> Dict[str, int]:
    deltas: Dict[str, int] = {}

    for ticker, action, quantity in legs:
        deltas[ticker] = (
            deltas.get(ticker, 0)
            + signed_delta(action, quantity)
        )

    return deltas


def matched_arb_inventory(positions: Dict[str, int]) -> int:
    """Return coherent matched ETF/basket relative-value inventory."""
    bull = int(positions.get(BULL, 0))
    bear = int(positions.get(BEAR, 0))
    ritc = int(positions.get(RITC, 0))

    etf_rich = max(0, min(bull, bear, -ritc))
    etf_cheap = max(0, min(-bull, -bear, ritc))
    return etf_rich + etf_cheap


def matched_inventory_allows(
    positions: Dict[str, int],
    deltas: Dict[str, int],
) -> bool:
    before = matched_arb_inventory(positions)
    after = matched_arb_inventory(positions_after(positions, deltas))
    return after <= MAX_OPEN_MATCHED_ARB_QTY or after < before


