def trim_slices(
    slices: Sequence[Slice],
    quantity: int,
) -> List[Slice]:
    left = int(quantity)
    result: List[Slice] = []

    for item in slices:
        if left <= 0:
            break

        used = min(left, item.quantity)

        if used > 0:
            result.append(
                Slice(
                    quantity=used,
                    net_edge_cad=item.net_edge_cad,
                )
            )
            left -= used

    return result


def slices_quantity(slices: Sequence[Slice]) -> int:
    return sum(item.quantity for item in slices)


def slices_pnl(slices: Sequence[Slice]) -> float:
    return sum(
        item.quantity * item.net_edge_cad
        for item in slices
    )


def depth_vwap(levels: Sequence[Level], quantity: float) -> float:
    """Return visible-depth VWAP for quantity, or NaN if not covered."""
    left = float(quantity)
    notional = 0.0
    filled = 0.0

    for level in levels:
        if left <= 1e-9:
            break
        take = min(left, float(level.quantity))
        notional += take * level.price
        filled += take
        left -= take

    if left > 1e-6 or filled <= 0:
        return math.nan
    return notional / filled


def direct_reference_prices(
    state: MarketState,
    direction: str,
    quantity: int,
) -> Dict[str, float]:
    """Capture decision-time visible-depth VWAPs for later slippage analysis."""
    cheap_etf = direction == "ETF_CHEAP"
    actions = {
        BULL: "SELL" if cheap_etf else "BUY",
        BEAR: "SELL" if cheap_etf else "BUY",
        RITC: "BUY" if cheap_etf else "SELL",
    }
    output: Dict[str, float] = {}

    for ticker, action in actions.items():
        book = state.books[ticker]
        levels = book.asks if action == "BUY" else book.bids
        output[ticker] = depth_vwap(levels, quantity)

    ritc_price = output[RITC]
    ritc_cash_usd = quantity * (
        ritc_price + EQUITY_MARKET_FEE_PER_SHARE
        if cheap_etf
        else ritc_price - EQUITY_MARKET_FEE_PER_SHARE
    )
    fx_action = "BUY" if cheap_etf else "SELL"
    fx_levels = (
        state.books[USD].asks
        if fx_action == "BUY"
        else state.books[USD].bids
    )
    output[USD] = depth_vwap(fx_levels, ritc_cash_usd)
    return output


def synchronized_direct_slices(
    state: MarketState,
    direction: str,
    max_quantity: int,
) -> List[Slice]:
    cheap_etf = direction == "ETF_CHEAP"

    bull = DepthCursor(
        state.books[BULL].bids
        if cheap_etf
        else state.books[BULL].asks
    )
    bear = DepthCursor(
        state.books[BEAR].bids
        if cheap_etf
        else state.books[BEAR].asks
    )
    ritc = DepthCursor(
        state.books[RITC].asks
        if cheap_etf
        else state.books[RITC].bids
    )
    fx = DepthCursor(
        state.books[USD].asks
        if cheap_etf
        else state.books[USD].bids
    )

    output: List[Slice] = []
    used_total = 0

    while (
        all(cursor.valid for cursor in (bull, bear, ritc, fx))
        and used_total < max_quantity
    ):
        if ritc.price <= 0:
            break

        # RITC's market-order fee is charged in USD because RITC is quoted
        # in USD.  The executable USD cash flow is therefore ask + fee when
        # buying and bid - fee when selling.
        ritc_cash_usd_per_share = (
            ritc.price + EQUITY_MARKET_FEE_PER_SHARE
            if cheap_etf
            else ritc.price - EQUITY_MARKET_FEE_PER_SHARE
        )
        if ritc_cash_usd_per_share <= 0:
            break

        fx_share_capacity = int(
            math.floor(fx.remaining / ritc_cash_usd_per_share)
        )

        quantity = min(
            int(bull.remaining),
            int(bear.remaining),
            int(ritc.remaining),
            fx_share_capacity,
            max_quantity - used_total,
        )

        if quantity <= 0:
            if fx.valid and fx.remaining > 0:
                fx.consume(fx.remaining)
                continue
            break

        basket_fees_cad = 2.0 * EQUITY_MARKET_FEE_PER_SHARE

        if cheap_etf:
            edge = (
                bull.price
                + bear.price
                - ritc_cash_usd_per_share * fx.price
                - basket_fees_cad
            )
        else:
            edge = (
                ritc_cash_usd_per_share * fx.price
                - bull.price
                - bear.price
                - basket_fees_cad
            )

        if edge < MIN_DIRECT_NET_EDGE_CAD:
            break

        output.append(
            Slice(
                quantity=quantity,
                net_edge_cad=edge,
            )
        )

        bull.consume(quantity)
        bear.consume(quantity)
        ritc.consume(quantity)
        fx.consume(quantity * ritc_cash_usd_per_share)

        used_total += quantity

    return output


def evaluate_direct_candidate(
    state: MarketState,
    direction: str,
    max_quantity: Optional[int] = None,
) -> Tuple[Optional[Candidate], int, str]:
    quantity_cap = (
        MAX_DIRECT_QTY_PER_ACTION
        if max_quantity is None
        else min(MAX_DIRECT_QTY_PER_ACTION, max(0, int(max_quantity)))
    )

    if quantity_cap < MIN_DIRECT_QTY:
        return None, 0, "Permitted quantity below MIN_DIRECT_QTY"

    slices = synchronized_direct_slices(
        state,
        direction,
        quantity_cap,
    )

    raw_quantity = slices_quantity(slices)
    quantity = (raw_quantity // QTY_STEP) * QTY_STEP

    if quantity < MIN_DIRECT_QTY:
        return None, raw_quantity, "Profitable depth below MIN_DIRECT_QTY"

    if direction == "ETF_CHEAP":
        actions = [
            (BULL, "SELL"),
            (BEAR, "SELL"),
            (RITC, "BUY"),
        ]
        label = "BUY RITC / SELL BULL+BEAR"
    else:
        actions = [
            (BULL, "BUY"),
            (BEAR, "BUY"),
            (RITC, "SELL"),
        ]
        label = "SELL RITC / BUY BULL+BEAR"

    while quantity >= MIN_DIRECT_QTY:
        legs = [
            (ticker, action, quantity)
            for ticker, action in actions
        ]

        deltas = legs_to_deltas(legs)

        reduction_capacity = direct_inventory_reduction_capacity(
            state,
            direction,
        )
        fully_inventory_reducing = reduction_capacity >= quantity
        risk_ok = (
            risk_allows_or_reduces(state.positions, deltas)
            if fully_inventory_reducing
            else risk_allows(state.positions, deltas)
        )

        if risk_ok and matched_inventory_allows(state.positions, deltas):
            selected_slices = trim_slices(slices, quantity)
            pnl = slices_pnl(selected_slices)

            if pnl < MIN_DIRECT_TOTAL_PNL_CAD:
                return (
                    None,
                    raw_quantity,
                    "Expected P&L below minimum total P&L",
                )

            return (
                Candidate(
                    kind="DIRECT_ARB",
                    label=label,
                    quantity=quantity,
                    total_pnl_cad=pnl,
                    average_edge_cad=pnl / quantity,
                    score_cad=pnl,
                    legs=legs,
                    direction=direction,
                    reference_prices=direct_reference_prices(
                        state,
                        direction,
                        quantity,
                    ),
                ),
                raw_quantity,
                "Eligible",
            )

        quantity -= QTY_STEP

    return (
        None,
        raw_quantity,
        "Local weighted risk or matched-inventory cap blocked trade",
    )


